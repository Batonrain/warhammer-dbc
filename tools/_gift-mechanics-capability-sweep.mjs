let entryCount = 0, capabilityCount = 0;
const capabilitiesToRegister = [];

for (const [god, dir] of Object.entries(GOD_DIRS)) {
  const files = fs.readdirSync(dir).filter(f => f.endsWith(".json") && f !== "_Folder.json");
  const byName = new Map();
  for (const f of files) {
    const full = path.join(dir, f);
    const doc = JSON.parse(fs.readFileSync(full, "utf8"));
    if (!byName.has(doc.name)) byName.set(doc.name, []);
    byName.get(doc.name).push({ full, doc });
  }

  for (const [name, slug, label] of ENTRIES[god]) {
    const matches = byName.get(name);
    if (!matches) {
      console.error(`MISSING FILE for [${god}] "${name}" — skipped`);
      continue;
    }
    const capabilityKey = `gift.${god}.${slug}`;
    let registeredThisKey = false;
    for (const { full, doc } of matches) {
      const groups = doc.flags?.["warhammer-dbc"]?.mechanics || [];
      if (groups.length > 0) {
        console.log(`already has mechanics, skip: ${full}`);
        continue;
      }
      const e = blankMechEntry("capability");
      e.id = `${slug}-cap`;
      e.capabilityKey = capabilityKey;
      doc.flags ??= {};
      doc.flags["warhammer-dbc"] ??= {};
      doc.flags["warhammer-dbc"].mechanics = [ (() => { const g = blankMechGroup("AND"); g.entries = [e]; return g; })() ];
      fs.writeFileSync(full, JSON.stringify(doc, null, 2) + "\n");
      entryCount++;
      if (!registeredThisKey) registeredThisKey = true;
    }
    if (registeredThisKey) {
      capabilitiesToRegister.push({ key: capabilityKey, label, god, name });
      capabilityCount++;
    }
  }
}

// ── Регистрация в capabilities.mjs ─────────────────────────────────────────
const CAP_FILE = "module/constants/capabilities.mjs";
let capSrc = fs.readFileSync(CAP_FILE, "utf8");
const GOD_RU = { khorne: "Кхорн", nurgle: "Нургл", slaanesh: "Слаанеш", tzeentch: "Тзинч" };

let block = "\n  // ── Дары Богов Хаоса (wdbc-1rno) — активные/условные способности без\n" +
  "  // подходящего поля Конструктора, заглушка данными, reader пуст сознательно ──\n";
for (const { key, label, god, name } of capabilitiesToRegister) {
  const engName = name.split(" / ")[0];
  block += `  "${key}": {\n` +
    `    label: ${JSON.stringify(label)},\n` +
    `    source: "Дар ${GOD_RU[god]} (${engName})",\n` +
    `    reader: ""\n` +
    `  },\n`;
}

const marker = "\n};";
const idx = capSrc.lastIndexOf(marker);
if (idx === -1) throw new Error("marker not found");
capSrc = capSrc.slice(0, idx) + block + capSrc.slice(idx);
fs.writeFileSync(CAP_FILE, capSrc);

console.log(`OK: ${entryCount} файлов Даров получили capability-запись, ${capabilityCount} новых ключей зарегистрировано в ${CAP_FILE}`);
