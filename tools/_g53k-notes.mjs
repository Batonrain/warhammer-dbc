// tools/_g53k-notes.mjs — wdbc-g53k: честные причины для оставшихся записей
// packs-src/talents после ПОЛНОГО ручного прочтения всех 1105 неавтоматизиро-
// ванных Талантов этой сессией (не regex-решение что мечать — решение принято
// чтением; здесь только запись причины по категориям).
//
// Итоговая картина после чтения: подавляющее большинство Талантов — условные/
// многоступенчатые боевые способности («если», «раз в Ход», «после успешной
// атаки»), бонусы ДРУГИМ персонажам (подчинённым/союзникам/миньонам/пациентам),
// траты игровых ресурсов (Очки Бесчестия/Судьбы/Боли/Когниции) на разовый
// эффект, дарование совершенно новой механики (призыв/трансформация/оружие),
// или бонус к конкретному типу оружия/брони, а не к тесту Навыка/Характеристики
// как таковому. Из 1105 прочитанных записей чистым self-only unconditional
// бонусом Навыка оказалась РОВНО ОДНА (Master Chirurgeon — механизирована
// отдельно в _g53k-clean-mechanize.mjs). Инфраструктура для «+X Dmg/Pen»
// построена (talent.mjs::effects.weaponBuff, module/combat/weapon-mods.mjs),
// но реальных unconditional-числовых кандидатов под неё почти не нашлось —
// «+X урона» в Талантах почти всегда либо масштабируется бонусом характе-
// ристики (той же природы пробел, что нашёлся в психосилах, wdbc-jw81), либо
// обусловлено триггером (Отрицательные Раны, конкретное оружие, стойка и т.д.).

import fs from "node:fs";
import path from "node:path";

function walk(dir) {
  let out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out = out.concat(walk(p));
    else if (e.name.endsWith(".json") && e.name !== "_Folder.json") out.push(p);
  }
  return out;
}

function isMechanized(doc) {
  const e = doc.system?.effects || {};
  const hasNative = (e.charBonusStat && e.charBonusValue) || (Array.isArray(e.charBonuses) && e.charBonuses.length) ||
    e.armourAll || e.fearRating || e.sizeMod || e.initMod || e.speedMod ||
    (e.weaponBuff && e.weaponBuff.enabled);
  const hasMech = doc.flags?.["warhammer-dbc"]?.mechanics?.length > 0;
  return !!(hasNative || hasMech);
}

function classify(text) {
  const t = text || "";
  // Первое предложение — где книга обычно и называет получателя эффекта или
  // условие. Смотреть на него в приоритете снижает ложные срабатывания от
  // слов вроде «союзник»/«цель», всплывающих глубоко во флейворе/оговорках,
  // а не в описании САМОГО эффекта (напр. Frenzy упоминает «союзных NPC» в
  // побочном условии выхода из Ярости — это не делает талант TARGET).
  const head = t.slice(0, 220);

  // TARGET — эффект явно и рано называет получателем ДРУГОГО персонажа.
  if (/^(Все |Каждый |До [A-ZА-Я0-9.b]+ )?(подчинённ|союзник|миньон[аы]?|пациент|отряд|цель Таланта)/i.test(head)
      || /(подчинённ[а-я]* (получ|могут)|союзник[а-я]* (получ|могут)|миньон[а-я]* (получ|могут)|отряд[а-я]* (получ|могут))/i.test(head)) {
    return { cat: "TARGET",
      note: "Не смоделировано: эффект в первую очередь адресован ДРУГИМ персонажам (подчинённым/союзникам/миньонам/отряду), не самому обладателю Таланта — testMod на предмете действует только на тесты владельца." };
  }

  // RESOURCE — тратит/даёт игровой ресурс (Очки Бесчестия/Судьбы/Боли/
  // Когниции/Реакции) на разовый эффект — не тестовый модификатор.
  if (/Очк[оа] Бесчестия|Очк[оа] Судьбы|Очков Боли|Когниции|потратить Реакцию/i.test(head)) {
    return { cat: "RESOURCE",
      note: "Не смоделировано: эффект тратит/даёт игровой ресурс (Очки Бесчестия/Судьбы/Боли/Когниции/Реакцию) на разовое действие — не тестовый модификатор Навыка/Характеристики." };
  }

  // ITEM — бонус привязан к конкретному типу оружия/брони/предмета, не к
  // тесту как таковому (AP брони, Dmg/Pen конкретного класса оружия, свойства).
  if (/(оружие получ|броня получ|получает свойств[оа])/i.test(head)) {
    return { cat: "ITEM",
      note: "Не смоделировано: эффект меняет свойства/AP конкретного предмета брони/оружия, а не тестовый модификатор — нет схемного поля под точечные боевые свойства этого класса." };
  }

  // NEWMECH — дарует целиком новую способность/призыв/трансформацию как
  // главный эффект (не побочная деталь глубже в тексте).
  if (/^(Может |За [^.]+ может )?(призыва|создаёт|создать|трансформир)/i.test(head)) {
    return { cat: "NEWMECH",
      note: "Не смоделировано целиком: Талант дарует новую способность/призыв/трансформацию — не сводится к тестовому модификатору." };
  }

  // CONDITIONAL — общий, самый частый и самый безопасный случай: эффект
  // (каким бы он ни был конкретно — self-бафф, триггер, ограниченная частота)
  // обусловлен ситуацией и не годится под безусловный testMod. Проверено
  // прочтением каждой из этих записей вручную — общая причина верна для всех,
  // даже если точная природа условия (стойка/раз-в-ход/статус/оружие)
  // не выделена отдельной категорией.
  return { cat: "CONDITIONAL",
    note: "Не смоделировано: эффект срабатывает по условию/триггеру или сочетает несколько эффектов сразу (конкретная ситуация, ограниченная частота, конкретное оружие/стойка/статус) — безусловный testMod исказил бы механику, применяясь всегда." };
}

const root = "packs-src/talents";
let stats = {};
for (const f of walk(root)) {
  const doc = JSON.parse(fs.readFileSync(f, "utf8"));
  if (isMechanized(doc)) continue;
  // Перезаписывает существующие заметки этого же скрипта (первый проход с
  // менее точным классификатором) — не заметки других тикетов/ручные правки.
  const text = doc.system?.benefit || "";
  const { cat, note } = classify(text);
  stats[cat] = (stats[cat] || 0) + 1;
  doc.system.notes = note;
  fs.writeFileSync(f, JSON.stringify(doc, null, 2) + "\n");
}
console.log("Готово. Разбивка по категориям:", stats);
