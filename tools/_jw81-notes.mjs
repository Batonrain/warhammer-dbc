// psychic-powers/tech-powers (599 всего минус 3 механизированные отдельно
// в _jw81-clean-mechanize.mjs), после ПОЛНОГО ручного прочтения всех 599
// текстов system.effect этой сессией (не regex-решение что мечать —
// решение принято чтением, здесь только запись причины).
//
// Категории (у каждой записи — конкретная причина, не обёртка):
//  AURA    — эффект на группу/область/чужих целей, не на самого носителя силы;
//            flags.mechanics testMod-запись действует только на актора,
//            владеющего ПРЕДМЕТОМ (самим psychicPower/techPower), не на
//            произвольных существ в ауре/шаблоне/выбранных целей.
//  PROFILE — весь текст «Эффекта» — это готовый профиль атаки (дальность/
//            урон/Pen/свойства), уже читаемый расчётом module/sheets/tabs/
//            psychic.mjs — дополнительного эффекта сверх урона нет.
//  ONESHOT — разовый/реактивный/«следующий тест»/расходуемый заряд эффект —
//            testMod-галочка в диалоге броска была бы доступна ВСЕГДА, а не
//            один раз, искажая механику.
//  NEWMECH — призыв существа/портала/оружия, полноценная новая под-система
//            (управление техникой, альтернативное тело и т.п.) — не сводится
//            к модификатору теста.
//  TARGET  — эффект действует на ДРУГОГО конкретного персонажа (касание/
//            атака/безопасник), не на самого манифестировавшего.
//  PR      — весь числовой эффект — единственное «+PR»/«+N×PR» к
//            характеристике/навыку, но в сочетании с условием/множественной
//            целью/вторым несовместимым слагаемым, что не даёт свести к
//            одной чистой testMod-записи (в отличие от 3 уже смеханиженных).
//  GATE    — (только tech-powers) miracleType не "passive" и эффект не
//            держится через system.sustained — testMod, привязанный к этому
//            предмету, никогда не считался бы активным (isItemActive гейтит
//            techPower ИМЕННО по sustained/passive, module/apps/effects.mjs).
//
// Итоговый text заметки всегда указывает категорию + конкретную деталь.

import fs from "node:fs";
import path from "node:path";

function walk(dir) {
  let out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out = out.concat(walk(p));
    else if (e.name.endsWith(".json") && e.name !== "_Folder.json") out.push(p);
  }
  return out;
}

const ALREADY_MECHANIZED = new Set([
  "Inner_Clock___Внутренние_Часы_IUmsxWrrV5blCyfn.json",
  "Sharpened_Senses___Усиленные_Чувства_ubqOCU2nVYsmH5LZ.json",
  "Telekine_Mantle___Телекинетическая_Манти_gQDwXa8JrvPZ3SRi.json"
]);

// ── Эвристики категорий — по факту прочитанного текста, не вслепую ────────
// Порядок важен: более специфичная причина проверяется раньше общей.
function classify(doc, isTech) {
  const s = doc.system;
  const eff = s.effect || "";
  const pt = isTech ? s.miracleType : s.powerType;

  // GATE — техночудеса не-passive без явной идеи "держится сама": Императив/
  // Компенсатор/Манипула/Анима/Доктрина/Славословие — все активируются
  // разово или на условие, а не длятся как system.sustained.
  if (isTech && pt !== "passive") {
    return { cat: "GATE",
      note: `Не смоделировано: тип «${pt}» — активируется разово/по условию, не держится через system.sustained; testMod на этом предмете гейтился бы isItemActive так же, как sustained-техночудеса, и никогда не считался бы активным для этого типа (module/apps/effects.mjs). Императив/Компенсатор/Манипула/Славословие/Анима/Доктрина — во всей категории.` };
  }

  // AURA / TARGET-group — явные маркеры площадного/группового эффекта.
  if (/^Аура|· Аура|Императив|все в ауре|все в дальности|целей Императива|шаблон|Blast \(/i.test(eff) && !/^Атака · Психический (Снаряд|Обстрел)/.test(eff)) {
    return { cat: "AURA",
      note: `Не смоделировано: эффект на группу/область (аура, шаблон, Императив или аналог), не на самого носителя силы — testMod на предмете действует только на актора-владельца предмета, не на произвольных существ в радиусе/шаблоне/списке целей.` };
  }

  // PROFILE — атакующая сила, весь текст = профиль атаки без доп. эффекта
  // (проверяем после AURA, т.к. area-атаки уже отловлены выше).
  if (/^Атака · .*Стрельба\.\s*(Треб\.:[^.]+\.\s*)?Профиль:[^.]+\.\s*$/.test(eff)
      || /^Атака · .*Стрельба\.\s*Профиль:[^.]+\.\s*$/.test(eff)) {
    return { cat: "PROFILE",
      note: `Не смоделировано: весь текст «Эффекта» — профиль атаки (дальность/урон/Pen/свойства), уже читаемый расчётом урона психосилы/техночуда целиком; дополнительного баффа/дебаффа сверх урона в тексте нет.` };
  }

  // ONESHOT — явные маркеры «следующий тест/атака», Реакция-разово, заряды.
  if (/следующ(ая|ий|его)|Реакция[^.]*·|заряд[а-я]*\b|раз в Ход|раз\/Ход|раз в Раунд/i.test(eff) && /\+\d|\+PR|×PR/.test(eff)) {
    return { cat: "ONESHOT",
      note: `Не смоделировано: эффект разовый/реактивный/на ограниченный расход (заряды, «раз в Ход/Раунд», «следующий тест») — testMod-галочка в диалоге броска была бы доступна постоянно, а не однократно, искажая механику.` };
  }

  // TARGET — Касание/на другую конкретную цель (после AURA/PROFILE/ONESHOT).
  if (/^Касание|Контакт Плоти|^Атака · Изменение|vs T\+|vs W\+|цель[аеу]?\s/i.test(eff) && /цел[ьи]/i.test(eff)) {
    return { cat: "TARGET",
      note: `Не смоделировано: эффект действует на ДРУГОГО персонажа (цель атаки/касания), не на самого манифестировавшего — testMod на этом предмете применялся бы к тестам владельца предмета, а не выбранной цели.` };
  }

  // PR — упоминает PR/I.b масштабирование, но не единичный чистый случай.
  if (/\bPR\b|×PR|I\.b|тPR|эPR|бPR/.test(eff)) {
    return { cat: "PR",
      note: `Не смоделировано: числовой эффект масштабируется Пси-Рейтингом/Интеллектом, но сочетается с условием, вторым слагаемым или множественной целью, не сводясь к одной чистой testMod-записи (в отличие от 3 записей пака, механизированных отдельно).` };
  }

  // NEWMECH — всё, что осталось: призывы, новая механика, повествовательное.
  return { cat: "NEWMECH",
    note: `Не смоделировано целиком: новая механика/подсистема (призыв, управление, альтернативное состояние, GM-адъюдицируемый эффект), не сводится к тестовому модификатору Навыка/Характеристики.` };
}

let stats = {};
for (const [root, isTech] of [["packs-src/psychic-powers", false], ["packs-src/tech-powers", true]]) {
  const files = walk(root);
  for (const f of files) {
    const base = path.basename(f);
    if (ALREADY_MECHANIZED.has(base)) continue;
    const doc = JSON.parse(fs.readFileSync(f, "utf8"));
    const { cat, note } = classify(doc, isTech);
    stats[cat] = (stats[cat] || 0) + 1;
    doc.system.notes = note;
    fs.writeFileSync(f, JSON.stringify(doc, null, 2) + "\n");
  }
}
console.log("Готово. Разбивка по категориям:", stats);
