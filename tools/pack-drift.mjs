//  Обратный рассинхрон: исходники новее базы (wdbc-uozs).
//
//  Сторож в pack-stamp.mjs проверяет ОДНО направление — «в игре правили
//  после последней сборки», и останавливает сборку, чтобы она не снесла
//  ручные правки. Обратное направление не проверялось вообще, а оно
//  симметрично опасно: `packs:unpack` извлекает базу поверх packs-src с
//  clean:true, то есть документ, которого в базе нет, из исходников
//  ИСЧЕЗАЕТ.
//
//  Так и вышло 2026-09-05: в собранных компендиумах месяцами не было 44
//  документов ветки psychic-powers/АЭЛЬДАРИ/МИРОВОЙ ПЕВЕЦ, Черты «Аура
//  Смирения» и полей resistChar/resistMod у 83 психосил — всё это лежало в
//  packs-src, закоммиченное. Полный unpack удалил 45 файлов и откатил 87
//  (3554 удаления против 166 вставок). Спасло только то, что рабочая копия
//  была чиста и git всё вернул.
//
//  Здесь — чистая часть проверки: сравнение состава по идентификаторам
//  документов. Читающая обёртка ниже, а решение «остановиться или нет»
//  принимает сам unpack.
// ════════════════════════════════════════════════════════════════════════

import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Документы, которые есть в ИСХОДНИКАХ, но которых нет в базе. Именно они
 * пропали бы молча при извлечении.
 *
 * Чистая функция: принимает уже собранные идентификаторы, поэтому
 * проверяется без файловой системы.
 *
 * @param {Iterable<string>} srcIds  идентификаторы документов packs-src
 * @param {Iterable<string>} dbIds   идентификаторы документов базы
 * @returns {string[]} потерянные идентификаторы, по возрастанию
 */
export function docsMissingInDb(srcIds, dbIds) {
  const inDb = new Set(dbIds);
  return [...new Set(srcIds)].filter(id => !inDb.has(id)).sort();
}

/**
 * Идентификаторы документов в каталоге исходника пака: `_id` из каждого
 * .json, включая служебные `_Folder.json` — папка тоже документ, и её
 * пропажа так же реальна, как пропажа предмета.
 *
 * Файл без `_id` (битый или чужой) пропускается молча: задача этой функции
 * — сравнить состав, а не проверять формат.
 *
 * @returns {Map<string, string>} идентификатор → путь файла, для отчёта
 */
export function docIdsIn(dir) {
  const out = new Map();
  if (!existsSync(dir)) return out;
  const walk = current => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const full = join(current, entry.name);
      if (entry.isDirectory()) { walk(full); continue; }
      if (!entry.name.endsWith(".json")) continue;
      try {
        const id = JSON.parse(readFileSync(full, "utf8"))?._id;
        if (id) out.set(String(id), full);
      } catch { /* битый файл — не наша забота, состав по нему не судим */ }
    }
  };
  walk(dir);
  return out;
}
