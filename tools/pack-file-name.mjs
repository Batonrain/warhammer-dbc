// tools/pack-file-name.mjs
//
// Имя файла документа в packs-src — одно правило на всех. Его задаёт выгрузка
// (tools/unpack.mjs), а генераторы (races-to-pack, race-traits) кладут файлы
// сами и обязаны называть их так же: CI собирает пак, разбирает обратно и
// требует, чтобы packs-src не изменился. Разошедшееся правило выглядит там как
// «сборка компендиумов теряет документ».
//
// Отдельным модулем, а не экспортом из unpack.mjs: тот — скрипт без защиты от
// импорта, и любой `import` из него запускает полную распаковку паков.

// Сам по себе CLI кладёт документ в «<Папка>_<id16>/<Название>_<id16>.json».
// На кириллице такой путь перестаёт влезать в лимит Windows: буква весит два
// байта, и самый длинный путь тянул на 300 байт при потолке в 260 — checkout
// падал с «Filename too long». Поэтому у каталогов снимается суффикс id
// (одноимённых соседей в паках нет), а название документа режется. Полное имя
// лежит внутри JSON, id в имени файла остаётся, максимум пути — 240 байт.
export const NAME_LIMIT = 40;

/** Как в CLI: в имени файла остаются только буквы и цифры. */
export const safe = (name) => String(name).replace(/[^a-zA-Z0-9А-я]/g, "_");

export const packFileName = (name, id) => `${safe(name).slice(0, NAME_LIMIT)}_${id}.json`;
