function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (e.name !== "node_modules") walk(p, out); }
    else out.push(p);
  }
  return out;
}

export function run({ dry = false } = {}) {
  const map = new Map(ACCEPTED.map(([en, oldRu, newRu]) =>
    [`${en} / ${oldRu}`, `${en} / ${newRu}`]));

  const touched = [];
  const files = [
    ...walk(path.join(ROOT, "packs-src")),
    ...walk(path.join(ROOT, "module")),
    ...walk(path.join(ROOT, "test"))
  ].filter(f => /\.(json|mjs|hbs)$/.test(f));

  for (const file of files) {
    const raw = fs.readFileSync(file, "utf8");
    let out = raw;
    for (const [oldName, newName] of map) {
      if (!out.includes(oldName)) continue;
      out = out.split(oldName).join(newName);
    }
    if (out === raw) continue;
    if (!dry) fs.writeFileSync(file, out);
    touched.push(path.relative(ROOT, file).split(path.sep).join("/"));

    // Файл документа пака называется по имени документа — переименовываем.
    if (!file.includes(`${path.sep}packs-src${path.sep}`) || !file.endsWith(".json")) continue;
    let doc;
    try { doc = JSON.parse(out); } catch { continue; }
    if (!doc?.name || !doc?._id) continue;
    const want = path.join(path.dirname(file), packFileName(doc.name, doc._id));
    if (want !== file && !dry) fs.renameSync(file, want);
  }
  return { touched, renamed: map.size };
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  const dry = process.argv.includes("--dry");
  const { touched, renamed } = run({ dry });
  for (const [en, oldRu, newRu, why] of ACCEPTED) console.log(`${en}: ${oldRu} → ${newRu}   (${why})`);
  console.log(`\n${dry ? "БУДЕТ изменено" : "изменено"}: ${renamed} названий в ${touched.length} файлах`);
  console.log(`оставлено как есть: ${REJECTED.length} (см. REJECTED в этом файле)`);
}
