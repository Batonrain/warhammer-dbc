function setNote(file, note) {
  const doc = load(file);
  if (doc.system.notes && doc.system.notes.trim()) { console.log("ПРОПУСК:", doc.name); return; }
  doc.system.notes = note;
  save(file, doc);
  console.log("OK:", doc.name);
}

