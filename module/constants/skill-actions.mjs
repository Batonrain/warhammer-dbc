/** Строка «Действие» для тултипа: у специализации своя (Вождение), иначе — Навыка/группы. */
export function skillActionOf(key, specialty = "") {
  const text = (specialty && SPECIALTY_ACTIONS[key]?.[specialty]) || SKILL_ACTIONS[key] || "";
  return text ? `Действие: ${text.charAt(0).toUpperCase()}${text.slice(1)}` : "";
}
