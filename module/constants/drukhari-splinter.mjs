/** Осколочное ли это оружие. */
export function isSplinter(system) {
  return String(system?.weaponType || "") === "splinter";
}

/**
 * Длинная очередь из любого осколочного оружия получает Tearing.
 * Возвращает true, если свойство нужно добавить к этому выстрелу.
 */
export function splinterFullAutoTearing(system, rofMode) {
  return isSplinter(system) && rofMode === "full";
}

/**
 * Каскад яда: если цель УЖЕ страдает от отравления прошлым осколочным
 * попаданием, новое попадание требует теста против ПОЛОВИНЫ (окр. ▲) рейтинга
 * Toxic прошлой атаки. Провал — 2d10 урона от Toxic.
 */
export function splinterCascadeTest(prevToxicRating) {
  const r = Math.max(0, Number(prevToxicRating) || 0);
  return { rating: Math.ceil(r / 2), damage: "2d10" };
}

