export function dpGodMeta(key) {
  const d = DP_GODS_MAP[key] || DP_GODS_MAP.undivided;
  const g = WARP_GODS_MAP[key];
  return {
    ...d,
    color: g?.color || "#b477ff",
    glow:  g?.glow  || "rgba(180,119,255,0.9)",
    sigil: ASSET(g?.sigil || "Chaos")
  };
}

