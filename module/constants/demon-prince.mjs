export const DP_MANIFEST_STEPS = ["Раундов", "Минут", "Часов", "Дней", "Месяцев", "∞ (постоянно)"];

// Расчёт длительности пребывания в форме (Книга Хаоса, DEMON_FORMS).
// Возвращает {rollFormula, addend, min, unit, note} или null (Хост — бессрочно).
// wb/infb — бонусы Силы Воли и Бесчестия; thinSteps — эффективное Истончение
// (+ Якори в Реальности). thinSteps смещает единицу времени на ступени выше.
export function dpManifest(formKey, wb, infb, thinSteps = 0) {
  const idx = (base) => Math.min(DP_MANIFEST_STEPS.length - 1, Math.max(0, base + Math.max(0, thinSteps)));
  if (formKey === "trueForm")
    return { formula: "1d10", addend: 2 * wb - infb, min: 2, unit: DP_MANIFEST_STEPS[idx(0)],
             note: "Истинная Форма нестабильна: даёт чародейский сквозной щит 1-10." };
  if (formKey === "vessel")
    return { formula: "1d5", addend: 2 * wb - infb, min: 2, unit: DP_MANIFEST_STEPS[idx(3)],
             note: "Вселение в труп: начинает с Ранами трупа, лечится поглощением тел; плоть разрушается со временем." };
  return null; // host — долговременно, пока не выброшен
}

