// Полный реестр даров (общие + бога) для листа.
export function dpGiftsFor(godKey) {
  const godGifts = (DP_GIFTS_GODS[godKey] || []).map(g => ({ ...g, god: godKey }));
  return [...DP_GIFTS_COMMON.map(g => ({ ...g, god: "common" })), ...godGifts];
}

// Цена следующего взятия дара с учётом эскалации повторов.
export function dpGiftCost(gift, ownedCount = 0) {
  if (gift.variable) return null;                       // X — задаётся при взятии
  return gift.cost + (gift.escalate || 0) * ownedCount;
}

