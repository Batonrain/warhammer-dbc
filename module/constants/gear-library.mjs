/**
 * Библиотека Снаряжения (Warhammer DBC).
 *
 * Создаётся системой в компендиуме "warhammer-dbc.gear" при первом запуске
 * (см. warhammer-dbc.mjs, хук "ready") и раскладывается по папкам категорий
 * (по полю system.gearCategory): Разгрузка / Мобильность / Головное / Разное /
 * Мистическое. Оттуда предметы перетаскиваются в лист персонажа Drag-and-drop.
 *
 * Поля:
 *   gearCategory  — категория/папка (rig|mobility|head|misc|mystic)
 *   worn          — где носится / метки И,П,Н для головного (интегр./под/на шлем)
 *   effect        — краткая механическая сводка
 *   reminder      — короткая строка-напоминание (для чата)
 *   qualityEffects{poor,good,best} — эффекты конкретных уровней качества предмета
 *   isRig + rig{comfort, backSlot, slots[], magLocks[]} — разгрузка (для слот-менеджера)
 *   itemSize      — размер, если предмет сам занимает слот разгрузки
 *
 * Универсальный эффект качества («Прочее снаряжение»: Poor −10 / Good +5 / Best +10
 * на тесты с предметом) применяется движком module/constants/quality.mjs и не
 * дублируется в qualityEffects — там только специфичные для предмета правила.
 */

import { DRUKHARI_GEAR } from "./drukhari-gear.mjs";

const IMG = "icons/svg/item-bag.svg";

function G(name, gearCategory, availability, weight, opts = {}) {
  return {
    name, type: "gear", img: opts.img || IMG,
    system: {
      gearCategory, availability, weight,
      quantity: opts.quantity ?? 1,
      quality: "common",
      description: opts.description || "",
      effect: opts.effect || "",
      reminder: opts.reminder || "",
      worn: opts.worn || "",
      isRig: !!opts.rig,
      rig: opts.rig || { comfort: "normal", backSlot: false, slots: [], magLocks: [] },
      itemSize: opts.itemSize || "",
      // Предмет из компендиума оружия с боевым профилем этого снаряжения
      // (Нартеций, Арканный Глаз и т.п.) — чтобы было чем бросать.
      linkedWeapon: opts.weapon || "",
      qualityEffects: opts.q || { poor: "", good: "", best: "" },
      bonuses: opts.bonuses || []
    }
  };
}

