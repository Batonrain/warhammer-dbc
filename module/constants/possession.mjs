export const TWIN_SPIRIT_MAP = Object.fromEntries(TWIN_SPIRIT_DEMONS.map(d => [d.key, d]));

// Мета демона Двойного Духа: цвет/сигил/свечение бога-патрона.
export function twinSpiritMeta(demonKey) {
  const d = TWIN_SPIRIT_MAP[demonKey] || TWIN_SPIRIT_MAP.katart;
  const g = WARP_GODS_MAP[d.god] || WARP_GODS_MAP.undivided;
  return {
    ...d, godLabel: g.label,
    color: g.color, glow: g.glow, sigil: ASSET(g.sigil)
  };
}

