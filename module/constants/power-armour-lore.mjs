/** Особенность по броску к10 в указанной таблице. */
export function entryByRoll(table, roll) {
  const t = PA_TABLES[table];
  if (!t) return null;
  const r = Math.max(1, Math.min(10, Number(roll) || 1));
  return t.entries.find(e => r >= e.min && r <= e.max) || null;
}

/** Подпись диапазона: «1» или «3-4». */
export function rangeLabel(e) {
  return e.min === e.max ? String(e.min) : `${e.min}-${e.max}`;
}

/**
 * Допустимые сдвиги результата: ±½ Inf.b (окр.▲); 1 меняется на 2 или 10,
 * 10 — на 9 или 1.
 */
export function shiftOptions(roll, infBonus) {
  const r = Math.max(1, Math.min(10, Number(roll) || 1));
  const span = Math.ceil((Number(infBonus) || 0) / 2);
  const out = new Set([r]);
  for (let d = 1; d <= span; d++) {
    if (r - d >= 1) out.add(r - d);
    if (r + d <= 10) out.add(r + d);
  }
  if (r === 1)  { out.add(2); out.add(10); }
  if (r === 10) { out.add(9); out.add(1); }
  return [...out].sort((a, b) => a - b);
}
