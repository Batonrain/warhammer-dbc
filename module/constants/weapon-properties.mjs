//  Каждое свойство — объект:
//    key      : строковый идентификатор (хранится в system.weaponProps[].key)
//    label    : русское название
//    en       : оригинальное название (для тултипа)
//    rating   : true → принимает рейтинг (X)
//    rating2  : true → принимает второй рейтинг (X/Y)
//    cat      : "ranged" | "melee" | "both"  — к чему применимо (информативно)
//    desc     : полное описание правила
//    reminder : короткое напоминание для чата (если есть — выводится при броске)
//    auto     : директивы автоматизации (см. ниже). Отсутствует → только напоминание.
//
//  ── Поддерживаемые директивы auto.* (читаются движком combat/weapon-properties.mjs):
//    attackMod   : number   — постоянный модификатор к попаданию этим оружием
//    noAim       : true      — прицеливание не даёт бонуса (Inaccurate)
//    noCalledShot: true      — нельзя делать Избирательные попадания (Imprecise)
//    calledShotMod: number   — изменяет штраф Избирательного попадания (Precise: +20)
//    accurate    : true      — Меткое: одиночный выстрел удваивает бонус Прицеливания
//                              (attack-dialog.mjs) и, только С Прицеливанием, даёт доп.
//                              кубы урона по СУ (attack-outcome.mjs::bonusDamageDice, wdbc-1rno.5)
//    tearing     : true      — Рвущее: +1 куб урона, отбросить наименьший
//    proven      : true      — Проверенное: куб урона < рейтинга считается рейтингом
//    extreme     : true      — Экстремальное: порог экстрем. урона = рейтинг (по умолч. 10)
//    razorSharp  : true      — Бритвенно острое: при 3+ СУ удваивает Пробитие
//    meltaShort  : true      — Мельта: на короткой дистанции ×2 Проб. и игнор Reinforced
//    mightySB    : true      — Могучее: ×2 бонус Силы в рукопашном уроне
//    containedSB : true      — Сдержанное: не добавляет бонус Силы к урону
//    felling     : true      — Разящее: рейтинг снижает Сверхъест. Стойкость цели
//    primitive   : true      — Примитивное: высокотех. броня цели ×2 (макс +6)
//    flexible    : true      — Гибкое: эту атаку нельзя парировать
//    unseen      : true      — Незримое: Уклонение/Парирование недоступны цели,
//                              пока не засекла атаку альтернативными методами
//                              (module/rules/unseen-attack.mjs, wdbc-1rno.2)
//    defensive   : true      — Защитное: +15 к Парированию, −10 к попаданию
//    powerField  : true      — Силовое поле: при парировании может уничтожить оружие
//    reinforced  : true      — Укреплённое: не уничтожается силовым полем
//    reliability : "reliable" | "veryReliable" | "unreliable" — пороги заклинивания
//    recharge    : true      — Перезарядка: нельзя стрелять в следующий ход
//    extraHits   : "storm" | "twinLinked" | "multiStrike" — доп. попадания
//    ammoMult    : number    — множитель расхода боеприпасов
//    scatter     : true      — Рассеивание: на короткой дист. +10 поп. и +1d10 урона
//    maximal     : true      — Максимальное: режим макс. мощности (диалог)
//    corrosive   : true      — Разъедающее: потеря AP в месте попадания (damage.mjs)
//    crippling   : true      — Калечащее: рана с шипами, урон по триггеру (damage.mjs)
//    piercing    : true      — Проникающее: снаряд в ране, −1 SPD торс/нога (damage.mjs)
//    haywire     : true      — ЭМИ: бросок по таблице при попадании (damage.mjs)
//    targetEffect: {...}      — эффект на цель (кнопка в чате), см. движок
//      condition, testChar, testMod/testPerRating, rounds/fixedRounds,
//      damage (формула кубика), damageFromRating — как раньше; onBreach — только при пробитии брони (стр. 42, hooks.mjs::_applyWeaponPropEffect);
//      damageFromRating2: true — доп. урон = rating2 предмета, если он задан
//        (число или дайс-строка вроде «2d10+PR», PR резолвится в
//        resolvePropRating до сюда), иначе — обычный `damage` как дефолт
//        (Toxic: «1d10» книжной формулы по умолчанию, но Kurnous Darts дают
//        нестандартное «2d10+PR» через rating2 — wdbc-cy4z). В отличие от
//        damageFromRating (= сам rating, X) это ВТОРОЙ, отдельный рейтинг Y.
//      provalyDamage: { mult, add } — доп. вариант вместо damage: непоглощаемый
//        урон = рейтинг×mult + add + Провалы теста сопротивления цели (для
//        свойств вида «X+Провалы» — Bane, Vibro и т.п.), без броска кубика.
//      vehicleFlatDamage: true — против цели-Техники тест/provalyDamage не
//        применяются вовсе: рейтинг X идёт в Структуру напрямую, без теста
//        (Bane: «Техника при попадании автоматически получает X урона»).
//      armorPenDamage: true — provalyDamage идёт ЧЕРЕЗ поглощение брони
//        (Pen = рейтинг X), а не «минуя броню» — для свойств вида
//        «X+Провалы, но НЕ непоглощаемый» (Monofilament, в отличие от
//        Bane/Vibro выше). Плюс бросок 1d5≤X на Сочленение/Шею и −1 AP брони
//        во всех частях тела за попадание (applyMonofilamentHit, damage.mjs).
//    extremeLevelBonus: number — плюс к уровню Экстремального урона/тяжести
//      Критического эффекта ЭТОГО оружия (combat/attack.mjs rollExtremeDamage),
//      не связано с targetEffect (Monofilament: «+2 Экстремальный урон или
