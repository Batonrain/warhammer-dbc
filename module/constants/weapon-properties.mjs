//    reinforced  : true      — Укреплённое: не уничтожается силовым полем
//    reliability : "reliable" | "veryReliable" | "unreliable" — пороги заклинивания
//    recharge    : true      — Перезарядка: нельзя стрелять в следующий ход
//    extraHits   : "storm" | "twinLinked" | "multiStrike" — доп. попадания
//    ammoMult    : number    — множитель расхода боеприпасов
//    scatter     : true      — Рассеивание: на короткой дист. +10 поп. и +1d10 урона
//    maximal     : true      — Максимальное: режим макс. мощности (диалог)
//    corrosive   : true      — Разъедающее: потеря AP в месте попадания (damage.mjs)
//    crippling   : true      — Калечащее: рана с шипами, урон по триггеру (damage.mjs)
//    piercing    : true      — Проникающее: снаряд в ране, −1 SPD торс/нога (damage.mjs)
//    haywire     : true      — ЭМИ: бросок по таблице при попадании (damage.mjs)
//    targetEffect: {...}      — эффект на цель (кнопка в чате), см. движок
//      condition, testChar, testMod/testPerRating, rounds/fixedRounds,
//      damage (формула кубика), damageFromRating, onUnsoaked — как раньше;
//      provalyDamage: { mult, add } — доп. вариант вместо damage: непоглощаемый
//        урон = рейтинг×mult + add + Провалы теста сопротивления цели (для
//        свойств вида «X+Провалы» — Bane, Vibro и т.п.), без броска кубика.
//      vehicleFlatDamage: true — против цели-Техники тест/provalyDamage не
//        применяются вовсе: рейтинг X идёт в Структуру напрямую, без теста
//        (Bane: «Техника при попадании автоматически получает X урона»).
//      armorPenDamage: true — provalyDamage идёт ЧЕРЕЗ поглощение брони
//        (Pen = рейтинг X), а не «минуя броню» — для свойств вида
//        «X+Провалы, но НЕ непоглощаемый» (Monofilament, в отличие от
//        Bane/Vibro выше). Плюс бросок 1d5≤X на Сочленение/Шею и −1 AP брони
//        во всех частях тела за попадание (applyMonofilamentHit, damage.mjs).
//    extremeLevelBonus: number — плюс к уровню Экстремального урона/тяжести
