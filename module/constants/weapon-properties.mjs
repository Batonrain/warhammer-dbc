//    rating   : true → принимает рейтинг (X)
//    rating2  : true → принимает второй рейтинг (X/Y)
//    cat      : "ranged" | "melee" | "both"  — к чему применимо (информативно)
//    desc     : полное описание правила
//    reminder : короткое напоминание для чата (если есть — выводится при броске)
//    auto     : директивы автоматизации (см. ниже). Отсутствует → только напоминание.
//
//  ── Поддерживаемые директивы auto.* (читаются движком combat/weapon-properties.mjs):
//    attackMod   : number   — постоянный модификатор к попаданию этим оружием
//    noAim       : true      — прицеливание не даёт бонуса (Inaccurate)
//    noCalledShot: true      — нельзя делать Избирательные попадания (Imprecise)
//    calledShotMod: number   — изменяет штраф Избирательного попадания (Precise: +20)
//    accurate    : true      — Меткое: одиночный прицельный +10 и доп. кубы урона по СУ
//    tearing     : true      — Рвущее: +1 куб урона, отбросить наименьший
//    proven      : true      — Проверенное: куб урона < рейтинга считается рейтингом
//    extreme     : true      — Экстремальное: порог экстрем. урона = рейтинг (по умолч. 10)
//    razorSharp  : true      — Бритвенно острое: при 3+ СУ удваивает Пробитие
//    meltaShort  : true      — Мельта: на короткой дистанции ×2 Проб. и игнор Reinforced
//    mightySB    : true      — Могучее: ×2 бонус Силы в рукопашном уроне
//    containedSB : true      — Сдержанное: не добавляет бонус Силы к урону
//    felling     : true      — Разящее: рейтинг снижает Сверхъест. Стойкость цели
//    primitive   : true      — Примитивное: высокотех. броня цели ×2 (макс +6)
