// Бросок одного Демонического Свойства: god-таблица, 1d100 (+adj), min 1.
export function rollDemonProperty(godKey, adj = 0) {
  const table = DEMON_WEAPON_TABLES[godKey] || DEMON_WEAPON_TABLES.undivided;
  const raw = Math.floor(Math.random() * 100) + 1;
  const total = Math.max(1, raw + (adj || 0));
  const row = table.find(r => total >= r.min && total <= r.max) || table[table.length - 1];
  return { god: godKey, roll: raw, total, name: row.name, text: row.text, prop: row.prop || null };
}

// Свойства из выбранной строки → массив {key,rating} для weaponProps (авто).
export function propsFromRow(prop, demonWb) {
  if (!prop) return [];
  const out = [];
  const one = (p) => {
    if (!p?.key) return;
    const e = { key: p.key };
    if (p.useWb) e.rating = Math.max(1, demonWb || 1);
    else if (p.rating != null) e.rating = p.rating;
    out.push(e);
  };
  one(prop);
  if (prop.extra) one(prop.extra);
  return out;
}
