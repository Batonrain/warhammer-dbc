/** Категории, которые дают одно число всей партии. */
export const PARTY_KEYS = XP_CATEGORIES.filter(c => c.scope === "party").map(c => c.key);

/** Категории, у которых своё число у каждого персонажа. */
export const EACH_KEYS = XP_CATEGORIES.filter(c => c.scope === "each").map(c => c.key);

