//
//  У возможности без читателя (`reader` пуст в module/constants/
//  capabilities.mjs) панель «ВОЗМОЖНОСТИ СЕЙЧАС» писала одно слово: «вручную».
//  Слово честное, но бесполезное: за столом оно не говорит НИ ЧТО делать, ни
//  почему система за это не взялась. «Вручную» у иммунитета и «вручную» у
//  способности «раз за бой потратить Очко» — это две совершенно разные заботы.
//
//  Здесь подпись возможности разбирается на типовую форму. Форма считается ИЗ
//  ПОДПИСИ, а не хранится полем: подпись и так пишет автор контента, а второе
//  поле рядом с ней разъехалось бы с ней при первой же правке — тот же довод,
//  по которому в этом проекте не дублируют данные книги в код.
//
//  Формы взяты не из головы, а из сплошной ревизии 05.09.2026: из 144
//  возможностей без читателя, реально выданных предметами паков, 64 оказались
//  НАМЕРЕННЫМИ пометками (в подписи прямо сказано «не автоматизировано» либо
//  «число вынесено отдельной записью, capability покрывает остаток»), а
//  остальные ложатся на небольшой набор повторяющихся форм.
//
//  Порядок правил значим: первое совпавшее и есть форма. Сперва признаки,
//  которые сами по себе объясняют, почему механики нет (автор так и написал),
//  потом формы, по которым видно, ЧТО делать за столом.
// ════════════════════════════════════════════════════════════════════════════

/**
 * @typedef {object} CapabilityForm
 * @property {string} key    машинный ключ формы
 * @property {string} label  что это значит за столом, одной строкой
 */

/** Формы по порядку проверки. Первое совпадение выигрывает. */
const FORMS = [
  { key: "partlyMechanized",
    test: /механизирован|покрывает ТОЛЬКО остаток|вынесен[аоы] отдельной записью|отдельной записью kind/i,
    label: "числа уже считаются, вручную — только остаток текста" },
  { key: "notModelled",
    test: /не автоматизирован|не смоделирован|нет авто-триггера|решается вручную|гейтить нечем|в системе нет|не входит в объём/i,
    label: "механики под это нет — целиком на ГМе" },
  { key: "summon",
    test: /призыв|скакун|в услужении|оживают|вселение в технику/i,
    label: "создаёт отдельное существо — заводит ГМ" },
  { key: "aura",
    // Не \b: в JS без флага u \w это [A-Za-z0-9_], русские буквы в него не
    // входят, и граница слова вокруг кириллицы не работает вовсе. Об эту
    // грабку в проекте спотыкались четырежды — см. AGENTS.md, «Кириллица в
    // регулярках». Границу пишем явным «не русская буква».
    test: /(^|[^а-яёА-ЯЁ])аур[аеуы]([^а-яёА-ЯЁ]|$)|в радиусе|всем в \d|нимб/i,
    label: "аура вокруг персонажа — радиус отмеряет ГМ" },
  { key: "oncePer",
    test: /полное действие|полудействие|раз в раунд|раз за бой|раз за сцену|за свободное действие|\+1 бесчестия:/i,
    label: "тратится действием или ресурсом — объявляет игрок" },
  { key: "immunity",
    test: /иммун|не подвержен|не может умереть|не действует на|не стареет/i,
    label: "иммунитет — ГМ не применяет к персонажу этот эффект" },
  { key: "reroll",
    test: /перебрасыва|переброс/i,
    label: "переброс — игрок просит его сам" },
  { key: "testMod",
    test: /[+−-]\d+\s*(к\s*)?(тест|бросок|навык)|[+−-]\d+\s*(социальн|Запугивание|Выживание|Awareness)/i,
    label: "модификатор к тесту — игрок вписывает в бросок" },
  { key: "derived",
    // Тот же запрет на \b после русского слова (см. форму «аура» выше).
    test: /[+−-]\d+\s*(AP|Dmg)([^A-Za-z]|$)|[+−-]\d+\s*(Ран|Структур|урона|Размера)/i,
    label: "прибавка к показателю — считает игрок" },
  { key: "substitute",
    test: /вместо/i,
    label: "подмена одного другим — решает игрок при броске" }
];

/**
 * Форма возможности по её подписи.
 *
 * @param {string} label подпись из реестра CAPABILITIES
 * @returns {?CapabilityForm} null — форма не опознана (сложная нарративная
 *   способность; таких в ревизии было 35 из 144, и врать про них не нужно)
 */
export function capabilityForm(label) {
  const text = String(label ?? "");
  if (!text.trim()) return null;
  const hit = FORMS.find(f => f.test.test(text));
  return hit ? { key: hit.key, label: hit.label } : null;
}

/**
 * Подпись колонки «Считает» на листе.
 *
 * Возможность с читателем считается сама — форма ей не нужна и не показывается.
 * Без читателя показывается форма: «вручную» без пояснения за столом не
 * помогает.
 *
 * @param {boolean} auto  есть ли читатель в расчёте
 * @param {string}  label подпись возможности
 * @returns {{text: string, hint: string}} слово в ячейке и подсказка к нему
 */
export function capabilityAutoHint(auto, label) {
  if (auto) return { text: "авто", hint: "Система учитывает эту возможность сама" };
  const form = capabilityForm(label);
  return {
    text: "вручную",
    hint: form
      ? `Расчёт это не считает: ${form.label}`
      : "Расчёт это не считает — применяет ГМ по тексту способности"
  };
}
