/** Ключ расы, которой органы выдаются по умолчанию. */
export const ASTARTES_RACE = "astartes";

/** Имя органа → его номер по книге (для сортировки и проверок). */
export const ASTARTES_IMPLANT_ORDER = Object.fromEntries(
  ASTARTES_IMPLANTS.map(i => [i.name, i.system.geneSeedOrder]));

/** Есть ли у актора этот орган (сравнение по английской части имени). */
const eng = (n) => String(n || "").split("/")[0].toLowerCase().trim();
export function hasAstartesImplant(actor, name) {
  const want = eng(name);
  return actor.items.some(i => i.type === "implant" && eng(i.name) === want);
}

/** Органы, которых у актора ещё нет — их и надо выдать. */
export function missingAstartesImplants(actor) {
  return ASTARTES_IMPLANTS.filter(o => !hasAstartesImplant(actor, o.name));
}
