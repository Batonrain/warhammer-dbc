const d   = (n) => Math.floor(Math.random() * n) + 1;
const pick = (a) => a[Math.floor(Math.random() * a.length)];
const chance = (p) => Math.random() < p;
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);

export function toRoman(n) {
  const m = [[1000,"M"],[900,"CM"],[500,"D"],[400,"CD"],[100,"C"],[90,"XC"],
             [50,"L"],[40,"XL"],[10,"X"],[9,"IX"],[5,"V"],[4,"IV"],[1,"I"]];
  let r = ""; for (const [v, s] of m) while (n >= v) { r += s; n -= v; } return r || "I";
}

// Процедурное слово: 2–3 слога CV (кластер только в начале) + согласное окончание.
function procWord() {
  let w = chance(0.12) ? pick(SYL_V)
        : chance(0.35) ? pick(SYL_CL) + pick(SYL_V)
        : pick(SYL_C) + pick(SYL_V);
  w += pick(SYL_C) + pick(SYL_V);                 // гарантированный второй слог
  if (chance(0.22)) w += pick(SYL_C) + pick(SYL_V); // изредка третий
  w += pick(SYL_END);
  return cap(w);
}

// Базовое «слово»: готовый корень (чаще) либо чистая процедурная генерация.
function baseWord() {
  const r = Math.random();
  if (r < 0.62) return pick(ROOTS);
  if (r < 0.78) {                                   // корень с лёгким окончанием
    const root = pick(ROOTS);
    const stem = /[аеиоуяэйь]$/i.test(root) ? root.slice(0, -1) : root;
    return cap(stem + pick(SUFFIX));
  }
  return procWord();
}

// Числовое/кодовое обозначение.
function designation() {
  const r = Math.random();
  if (r < 0.30) return toRoman(d(20));
  if (r < 0.50) return String(d(999));
  if (r < 0.68) return pick(GREEK);
  if (r < 0.82) return pick(ORDINAL);
  // буквенно-цифровой код
  const L = "АБВГДЕКЛМНПРСТФХЦ";
  const c = () => L[Math.floor(Math.random() * L.length)];
  return `${c()}${chance(0.5) ? c() : ""}-${d(999)}`;
}

