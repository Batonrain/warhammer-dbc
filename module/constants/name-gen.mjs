export function genChaosName() {
  const core = cap(pick(CH.root).toLowerCase() + pick(CH.suf));
  const r = Math.random();
  if (r < 0.30) return `${pick(CH.title)} ${core}`;
  if (r < 0.55) return `${pick(CH.epithet)} ${core}`;
  if (r < 0.72) return `${core} ${pick(CH.epithet)}`;
  if (r < 0.85) return `${core} ${toRoman(d(13))}`;
  return core;
}

/**
 * Генерирует имя.
 * @param {object} o { kind, number, species } kind влияет на стиль; species — ксено-стиль.
 */
export function genName(o = {}) {
  const kind = o.kind || "system";
  const forceNum = o.number;
  if (o.species && X[o.species]) return genXenosName(o.species);
  if (kind === "base") return baseWord();
  if (kind === "chaos") return genChaosName();
  let name, r = Math.random();

  // Стилевые предпочтения по типу объекта.
  if (kind === "station" || kind === "derelict" || kind === "asteroid") {
    // чаще кодовые/номерные
    if (r < 0.5) return `${baseWord()} ${designation()}`;
    if (r < 0.75) return `${pick(["Станция","Пост","Док","Бастион","Узел","Реликт","Форпост","Веха"])} «${baseWord()}»`;
    return `${baseWord()}-${d(99)}`;
  }
  if (kind === "anomaly") {
    return `${pick(["Аномалия","Разлом","Вихрь","Туманность","Око","Бездна","Завеса","Шрам","Пелена"])} ${chance(0.5) ? baseWord() : designation()}`;
  }

  // Звёзды / системы / планеты:
  if (r < 0.42) name = baseWord();                                   // одиночное
  else if (r < 0.66) name = `${baseWord()} ${pick(EPITHET)}`;        // двойное (эпитет)
  else if (r < 0.82) name = `${baseWord()} ${baseWord()}`;          // двойное (два корня)
  else name = `${baseWord()}-${baseWord().slice(0, 3)}`;            // дефисное

  if (forceNum || chance(kind === "planet" ? 0.45 : 0.25)) {
    name = `${name} ${designation()}`;
  }
  return name;
}

const isCanon = (n) => {
  const low = n.toLowerCase();
  for (const b of BLOCKLIST) if (low.includes(b)) return true;
  return false;
};

/**
 * Уникальное имя: не в avoid (Set строк) и не из канона. avoid пополняется.
 */
export function genUnique(avoid, o = {}) {
  avoid = avoid || new Set();
  for (let i = 0; i < 60; i++) {
    const n = genName(o);
    if (!avoid.has(n) && !isCanon(n)) { avoid.add(n); return n; }
  }
  // запасной вариант — гарантированно уникальный код
  const fb = `${baseWord()} ${toRoman(d(40))}-${d(9999)}`;
  avoid.add(fb);
  return fb;
}
