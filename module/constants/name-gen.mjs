export function genXenosName(species) {
  const x = X[species]; if (!x) return baseWord();
  let n = x.join(pick(x.pre), pick(x.mid), pick(x.suf));
  if (chance(0.30) && XENO_TITLE[species]) n = `${pick(XENO_TITLE[species])} ${n}`;
  if (chance(0.18)) n += ` ${toRoman(d(12))}`;
  return cap(n);
}

