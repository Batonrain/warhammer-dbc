/** Гемункул ли персонаж — по Элитному архетипу в шапке листа. */
export function isHaemonculus(actor) {
  return /гемункул/i.test(String(actor?.system?.eliteArchetype || ""));
}

/**
 * Цена трейта при данном числе рейтингов: первый по take, каждый следующий
 * по up. Трейты без рейтинга (up: null) всегда стоят take.
 */
export function traitCost(def, ranks) {
  const n = Math.max(1, Number(ranks) || 1);
  if (def.up == null) return def.take;
  return def.take + (n - 1) * def.up;
}

/**
 * Порча за варп-трейты в конце сессии: +1 за факт наличия трейта и +1 за
 * каждый рейтинг поверх первого (у Daemonic Presence — поверх пятого).
 * Blunted, Hoverer и Phase Порчу не приносят.
 */
export function warpCorruption(entries) {
  let cor = 0;
  for (const e of entries || []) {
    const def = HAEM_TRAIT_MAP.warp[e.key];
    if (!def || def.cor === false) continue;
    cor += 1;
    const step = def.step || 1;
    const base = def.corBase || 1;
    const rating = (Number(e.ranks) || 1) * step;
    if (rating > base) cor += Math.ceil((rating - base) / step);
  }
  return cor;
}

/**
 * Сводка по Гемункулу для листа: открытые ступени, накопленные прибавки,
 * бюджет очков и потраченное.
 *
 * Пул очков: книга говорит «лимит в I.b Очков» для Идеала Плоти, а Идеал
 * Варпа велит менять трейты «используя правила Идеала Плоти» — то есть тем же
 * лимитом. По умолчанию пул общий; флаг splitPools разводит его на два по I.b,
 * если за столом читают иначе.
 */
export function haemState(actor) {
  const h = actor?.system?.haemonculus || {};
  const stage = Math.max(0, Math.min(5, Number(h.stage) || 0));
  const ib = Number(actor?.system?.characteristics?.int?.bonus) || 0;

  const open = HAEM_STAGES.filter(s => s.stage <= stage);
  const unlocked = new Set(open.flatMap(s => s.unlocks));

  // Накопленные машинные прибавки по всем открытым ступеням.
  let unnaturalI = 0, fear = 0;
  for (const s of open) { unnaturalI += s.grants.unnaturalI || 0; fear += s.grants.fear || 0; }

  const spend = (list, kind) => (list || []).reduce((sum, e) => {
    const def = HAEM_TRAIT_MAP[kind][e.key];
    return def ? sum + traitCost(def, e.ranks) : sum;
  }, 0);
  const fleshSpent = spend(h.flesh, "flesh");
  const warpSpent  = spend(h.warp,  "warp");

  const split = !!h.splitPools;
  const pools = split
    ? { flesh: { cap: ib, spent: fleshSpent }, warp: { cap: ib, spent: warpSpent } }
    : { shared: { cap: ib, spent: fleshSpent + warpSpent } };

  const next = HAEM_STAGES.find(s => s.stage === stage + 1) || null;
  const xpSpent = open.filter(s => s.stage > 0).reduce((a, s) => a + s.cost, 0);

  return {
    stage, ib, open, next, split, pools, xpSpent,
    unnaturalI, fear,
    fleshOpen: unlocked.has("flesh"),
    warpOpen:  unlocked.has("warp"),
    fleshSpent, warpSpent,
    warpCor: warpCorruption(h.warp),
    // Раны и Регенерация — от Стадии 1, считаются от I.b.
    woundBonus: stage >= 1 ? ib : 0,
    regen:      stage >= 1 ? Math.ceil(ib / 2) : 0
  };
}
