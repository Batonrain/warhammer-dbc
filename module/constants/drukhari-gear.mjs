// ─────────────────── КЛОНИРУЮЩЕЕ ПОЛЕ: таблица по редкости ───────────────────
// Поле голографическое, а не силовое: оно не поглощает попадания, а срывает их.
// Сила растёт строго с редкостью, поэтому таблица — машинная.
export const CLONE_FIELD_TABLE = [
  { r: 0, desc: "Бытовое или сломанное клонирующее поле",            bonus: 0,  penalty: 0,  stealth: 0 },
  { r: 1, desc: "Личное поле архонтов мелких кабалов",               bonus: 10, penalty: 10, stealth: 20 },
  { r: 2, desc: "Стандартное клонирующее поле друкхари",             bonus: 20, penalty: 20, stealth: 40 },
  { r: 3, desc: "Клонирующее поле известных личностей",              bonus: 30, penalty: 30, stealth: 60 },
  { r: 4, desc: "Клонирующее поле сильнейших мира сего",             bonus: 40, penalty: 40, stealth: 80 },
  { r: 5, desc: "Клонирующие поля Тёмных Муз или величайших друкхари", bonus: 50, penalty: 50, stealth: 100 }
];

/**
 * Ступень Клонирующего Поля по его редкости.
 * bonus  — носителю на физическое избегание, вольт и рукопашные приёмы;
 * penalty — противнику на атаки по носителю;
 * stealth — носителю на Stealth (в неподвижности отдельно +40).
 * Poor.Q режет бонусы и штрафы вдвое.
 */
export function cloneFieldTier(rarity, quality = "common") {
  const r = Math.max(0, Math.min(5, Number(rarity) || 0));
  const row = CLONE_FIELD_TABLE[r];
  if (quality !== "poor") return { ...row, halved: false };
  return { ...row, bonus: Math.floor(row.bonus / 2), penalty: Math.floor(row.penalty / 2),
           stealth: Math.floor(row.stealth / 2), halved: true };
}

