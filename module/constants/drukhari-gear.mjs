// ─────────────────── СТАБ ДРУКХАРИ ───────────────────
// Высокотехнологичный аналог имперского стаббера: металл отсекается от бруска.
export const STUB_RULES = {
  semiBonus: 1, fullBonus: 2, clipMult: 3, reliabilityMod: -1,
  ammoRarityCap: 2, modRarityMod: -1,
  text: "Стаб Друкхари: +1 выстрел при короткой очереди, +2 при длинной; ×3 боекомплект; "
      + "Надёжность −1 (технологии высокие, но сделано из говна и палок); редкость боеприпасов "
      + "R2 и ниже опускается до 0; редкость улучшений уменьшена на 1."
};

/** Применяет правило Стаба к профилю оружия. */
export function stubProfile(system) {
  const s = { ...system };
  s.rof_semi   = (Number(s.rof_semi) || 0) && Number(s.rof_semi) + STUB_RULES.semiBonus;
  s.rof_full   = (Number(s.rof_full) || 0) && Number(s.rof_full) + STUB_RULES.fullBonus;
  s.magazineMax = (Number(s.magazineMax) || 0) * STUB_RULES.clipMult;
  s.magazineCur = Math.min(Number(s.magazineCur) || 0, s.magazineMax);
  return s;
}

