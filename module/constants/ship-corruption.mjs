// Пороги, пересечённые при данном DP.
export function crossedThresholds(dp) {
  const v = Number(dp) || 0;
  return SHIP_DEFILEMENT_THRESHOLDS.filter(t => v >= t.dp);
}

// Поиск искажения по итоговому броску (1..100; 100 = «00»).
export function findDistortion(total) {
  const v = Math.max(1, Math.min(100, Number(total) || 1));
  return SHIP_DISTORTIONS.find(d => v >= d.min && v <= d.max) || null;
}

export function findSubmutation(submut, roll) {
  if (!submut) return null;
  const v = Number(roll) || 1;
  return submut.table.find(s => v >= s.min && v <= s.max) || null;
}
