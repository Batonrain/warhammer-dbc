const IMG = "icons/svg/upgrade.svg";

function AM(name, o) {
  return {
    name, type: "armorMod", img: IMG, folder: o.folder,
    system: {
      description: o.desc || "", notes: "",
      category: "armor", modGroup: o.group || "general",
      requirement: o.req ? `${o.req}. Установка: Tech-Use+0 или Trade (Armourer)+20 (если не с бронёй).`
                         : "Установка: Tech-Use+0 или Trade (Armourer)+20 (если не с бронёй).",
      installedOn: "", weight: o.w ?? 0, availability: o.r ?? 0, quality: "common",
      activatable: !!o.act, active: false,
      effects: {
        apAll: 0, apHead: 0, apBody: 0, apArms: 0, apLegs: 0,
        apVsEnergy: 0, apVsImpact: 0, apVsRending: 0, apVsBlast: 0,
        maxAgilityMod: 0, addProps: [], charBonuses: [],
        ...(o.effects || {})
      }
    }
  };
}

