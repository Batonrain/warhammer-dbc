// un:  {stat: N}  — Unnatural/бонус к БОНУСУ х-ки (S/T/W/...).  } только
// val: {stat: N}  — бонус к ЗНАЧЕНИЮ х-ки.                     } для
// ap:  {head,body,arms,legs,all} — броня по локациям.           } миграции
// traits: [ ... ] — дарованные трейты (показ; влияние — вручную/через трейт-предмет).
// skills: [ ... ] — бонусы навыков (показ).
// q:   {poor,good,best} — градации Качества (памятка).
// note: строка — ситуативное/важное.
//
// ── Директивы автоматизации Техночудес (Кибернетика Механикум) ──────────────
// energyMax: N | {poor,common,good,best}
//                     — +N к максимуму Катушки Потенции (energy.maxTotal).
//                       Объект — когда сама надбавка зависит от Качества
//                       импланта (напр. базовая Катушка Потенции: 1/3/5/7).
// ironFocus: true     — Технофокус: его Качество может служить «Железом» для
//                       Техночудес (Poor −10 / Good +5 / Best +10 к связанным тестам).
// compensator: {poor,common,good,best} — бонус к тесту Компенсатора по Качеству
//                       (берётся МАКСИМУМ среди установленных имплантов).
// gen: [{res, amount, action, label, fromCognition?}] — действия генерации ресурса
//      (кнопки на вкладке ТЕХ). res: "cognition" | "energy". fromCognition —
//      конверсия ⚙→⚡ (стоимость в ⚙ за 1⚡, может меняться Качеством в обработчике).
// toggle: {label, note} — вкл/выкл-состояние (флаг "techActive" на предмете).

// Качество «Железа» → модификатор к тесту активации Техночуда и к I в формулах.
export const IRON_TEST_MOD = { poor: -10, common: 0, good: 5, best: 10 };
export const QUALITY_ORDER = { poor: 0, common: 1, good: 2, best: 3 };
export function ironModForQuality(q) { return IRON_TEST_MOD[q] ?? 0; }
/** Наихудшее (наименьшее) Качество из списка — по правилам «Железа». */
export function leastQuality(qualities = []) {
  if (!qualities.length) return null;
  return qualities.reduce((a, b) => (QUALITY_ORDER[b] < QUALITY_ORDER[a] ? b : a));
}

