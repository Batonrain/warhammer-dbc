/** Находит запись механики по имени импланта (или null). */
export function implantMech(name = "") {
  for (const m of IMPLANT_MECH) if (m.re.test(name)) return m;
  return null;
}

/**
 * Числовая роспись импланта в виде старого `system.effects` — той же формы, в
 * какой её несут остальные импланты пака. Отсюда её забирает миграция и делает
 * настоящий ActiveEffect (migrations/item-effects.mjs): дальше число видно на
 * вкладке ЭФФЕКТЫ и правится там же, чего у таблицы никогда не было.
 *
 * Возвращает null, если числового у импланта нет.
 */
export function implantTableEffects(name = "") {
  const mech = implantMech(name);
  if (!mech) return null;
  const out = {};
  if (mech.un)  out.charBonuses      = Object.entries(mech.un).map(([stat, value]) => ({ stat, value }));
  if (mech.val) out.charValueBonuses = Object.entries(mech.val).map(([stat, value]) => ({ stat, value }));
  if (mech.ap) {
    if (mech.ap.all)  out.apAll  = mech.ap.all;
    if (mech.ap.head) out.apHead = mech.ap.head;
    if (mech.ap.body) out.apBody = mech.ap.body;
    if (mech.ap.arms) out.apArms = mech.ap.arms;
    if (mech.ap.legs) out.apLegs = mech.ap.legs;
  }
  return Object.keys(out).length ? out : null;
}
