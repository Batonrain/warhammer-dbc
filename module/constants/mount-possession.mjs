/** Демоны, для которых сосуд-скакун привычен: только они не дают вторых −10. */
export const MOUNT_BEAST_FORMULAS = ["beast", "greaterBeast"];

/** Поправки ритуала при сосуде-скакуне (стр. 478). */
export const MOUNT_RITUAL_MODS = { vessel: -10, notBeast: -10 };

/**
 * Модификаторы ритуала для этого демона: всегда −10 за сосуд, и ещё −10, если
 * демон не (высший) демонический зверь.
 * @returns {{label:string, val:number}[]}
 */
export function mountRitualMods(demonFormula) {
  const rows = [{ label: "Сосуд — скакун или байк", val: MOUNT_RITUAL_MODS.vessel }];
  if (!MOUNT_BEAST_FORMULAS.includes(demonFormula)) {
    rows.push({ label: "Демон — не демонический зверь", val: MOUNT_RITUAL_MODS.notBeast });
  }
  return rows;
}

/** Бросок одного Демонического Свойства скакуна: 1d100 (+adj), минимум 1. */
export function rollMountProperty(adj = 0) {
  const raw = Math.floor(Math.random() * 100) + 1;
  const total = Math.max(1, raw + (adj || 0));
  const row = MOUNT_DEMON_TABLE.find(r => total >= r.min && total <= r.max)
           || MOUNT_DEMON_TABLE[MOUNT_DEMON_TABLE.length - 1];
  return { roll: raw, total, name: row.name, text: row.text, flag: row.flag };
}

/**
 * Что из выпавших свойств умеет считать система. Пишется в
 * flags.warhammer-dbc.mountPossession, откуда это читает rules/mount.mjs;
 * свойства без `flag` в объект не попадают — они целиком на столе.
 */
export function possessionFlags(properties = [], demonWb = 1) {
  const wb = Math.max(1, Number(demonWb) || 1);
  const out = { demonWb: wb };
  for (const p of properties) {
    switch (p?.flag) {
      case "splice":     out.spliceWb  = wb;  break;
      case "covered":    out.covered   = true; break;
      case "stabilized": out.stabilized = true; break;
      case "speed":      out.speedBonus = wb; break;
      case "reinforced": out.reinforced = 10; break;
      case "deflector":  out.deflector = 50; out.riderDeflector = 25; break;
      case "flight":     out.flight    = true; break;
    }
  }
  return out;
}
