// module/constants/requisition-places.mjs
// ════════════════════════════════════════════════════════════════════════════
//  «Таблица Модификаторов реквизиции» по месту — Книга Пустоты, «Реквизиция
//  узлов» (void.json). Решение владельца 27.10.2026 (Sahara 10-4eac): место
//  выбирается в окне «Достать снаряжение», режим «Узел корабля»; сдвиг
//  Редкости, штраф теста и недоступность считаются сами.
//
//  Только данные: логика — rules/requisition-places.mjs, окно — apps/requisition.mjs.
//  Таблица относится к УЗЛАМ корабля (её «Правила» говорят «Редкость … узлов»,
//  «Узлы недоступны», а Обслуживание ссылается на неё же), поэтому в обычной
//  реквизиции снаряжения она не участвует.
//
//  Поля строки:
//    key     — ключ (хранится в окне, не в данных документов);
//    label   — «Место» в книге, дословно;
//    rule    — «Правила» в книге, дословно (проверяется тестом по void.json);
//    shifts  — сдвиги Редкости узла в шагах книги: +1 — «повышается на шаг»
//              (тяжелее), −1 — «падает/ниже на шаг» (легче). Поля сдвига:
//                nodes  — каких узлов касается (NODE_SELECTORS в rules);
//                except — признаки узла, на которые сдвиг НЕ распространяется;
//                peer   — сдвиг только при Таланте Peer этой фракции;
//                flag   — сдвиг только при отмеченном условии (flags);
//    testMod — штраф к самому тесту реквизиции («−10 к тестам реквизиции»);
//    needs   — без этого узлы не купить вовсе: peer — Талант Peer фракции
//              (ключ из PEER_FACTIONS, ищется на листе), flag — условие;
//    blocked — узлы недоступны всегда («Узлы недоступны»);
//    forbid  — признаки узла, которые на этом месте недоступны («Ксенотех
//              недоступен»);
//    flags   — условия, которые игрок отмечает в окне: система не может узнать
//              их по листу (контролирующая фракция, решение МИ, сюзеренство).
//
//  Колонка «Установка» (+1d10 дней и т. п.) НЕ ведётся — сроки Реквизиции
//  в системе не считаются (решение владельца 26.10.2026). То же — «+10/+20 к
//  реквизиции Длительного ремонта» и «при Длительном Ремонте восстанавливается
//  10 Прочности»: Длительный ремонт — не тест Реквизиции узла.
// ════════════════════════════════════════════════════════════════════════════

