// Сборка торпеды: боеголовка + система наведения. Возвращает совмещённый профиль.
export function torpedoProfile(warheadId, navId) {
  const wh  = getTorpedoWarhead(warheadId);
  const nav = getTorpedoNav(navId) || TORPEDO_NAV_SYSTEMS[0];
  if (!wh) return null;
  return {
    label:   `${wh.label} / ${nav.label}`,
    warhead: wh.label, navLabel: nav.label,
    dmg: wh.dmg, crit: Number(wh.crit) || 0, rng: wh.rng,
    tp:  Number(wh.tp) || 0, spd: (Number(wh.spd) || 0) + (Number(nav.spd) || 0),
    navTR: Number(nav.tr) || 0,
    ignoreArmour: wh.id === "sonic",
    special: [wh.special, nav.id !== "standard" ? nav.desc : ""].filter(Boolean).join(" ")
  };
}

