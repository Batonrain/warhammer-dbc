/**
 * Библиотека Инструментов (Warhammer DBC).
 *
 * Создаётся системой в компендиуме "warhammer-dbc.tools" при первом запуске
 * (см. warhammer-dbc.mjs, хук "ready") и раскладывается по папкам категорий
 * (по полю system.toolCategory): Общие / Наборы инструментов / Стационарное /
 * Расходники / Мистическое. Оттуда предметы перетаскиваются Drag-and-drop.
 *
 * Поля тула: toolCategory, availability, weight, quantity, quality, description,
 * effect (сводка), reminder, qualityEffects{poor,good,best}.
 *
 * Универсальный эффект Качества («Прочее снаряжение»: Poor −10 / Good +5 /
 * Best +10 на тесты) применяется движком module/constants/quality.mjs и в данных
 * не дублируется. В qualityEffects — только специфичные для предмета правила.
 *
 * Стационарные (toolCategory: "stationary") — установки без веса (weight 0).
 * Редкость «X» (Апотекарион/Кузница) задана значением «стандартной» ступени,
 * полная таблица ступеней описана в effect.
 */

const IMG = "icons/svg/item-bag.svg";

function T(name, toolCategory, availability, weight, opts = {}) {
  return {
    name, type: "tool", img: opts.img || IMG,
    system: {
      toolCategory, availability, weight,
      quantity: opts.quantity ?? 1,
      quality: "common",
      description: opts.description || "",
      effect: opts.effect || "",
      reminder: opts.reminder || "",
      // Предмет из компендиума оружия с боевым профилем инструмента
      // (Нуль Жезл, Икона Хаоса и т.п.) — чтобы было чем бросать.
      linkedWeapon: opts.weapon || "",
      qualityEffects: opts.q || { poor: "", good: "", best: "" },
      bonuses: opts.bonuses || []
    }
  };
}

