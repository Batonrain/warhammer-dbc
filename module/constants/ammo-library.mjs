// ════════════════════════════════════════════════════════════════════════
//  Боеприпасы (Warhammer DBC) — компендиум "ammunition".
//  Предметы type="ammo". По правилам системы 1 единица запаса = 1 МАГАЗИН
//  (достаточно, чтобы заполнить стандартный магазин оружия).
//
//  Поля автоматики применяются в attack.mjs:
//    damageMod / penetrationMod / rangeMod(+м) / rangeMultiplier(×) /
//    damageTypeOverride / attackMod. Дарованные свойства (Toxic, Flame,
//    Crippling…) и ситуативные эффекты выводятся текстом из `special`,
//    полные правила — в `description`.
//
//  rarity (R) = доступность (availability).
// ════════════════════════════════════════════════════════════════════════

const IMG = "icons/svg/target.svg";

// Типы урона: E→energy, I→impact, R→rending, X→blast/взрыв, C→chemical
function A(name, o) {
  return {
    name, type: "ammo", img: o.img || IMG, folder: o.folder,
    system: {
      description:        o.desc || "",
      notes:              "",
      weaponTypes:        o.wt || [],
      ammoCategory:       o.cat || "bullets",
      rarity:             o.r ?? 0,
      quantity:           0,
      weight:             o.w ?? 0,
      availability:       o.r ?? 0,
      attackMod:          o.atk ?? 0,
      damageMod:          o.dmg ?? 0,
      // «+1 кубик урона» (Фарос, Осирис, стр. 203) — доп. d10 к первому попаданию.
      damageDiceMod:      o.dmgDice ?? 0,
      damageTypeOverride: o.dt || "",
      penetrationMod:     o.pen ?? 0,
      rangeMod:           o.rng ?? 0,
      rangeMultiplier:    o.rngx ?? 1.0,
      special:            o.props || "",
      // УСЛОВНЫЕ модификаторы (стр. 203): «+10 против целей с душами», «+30
      // против псайкеров и демонов» и т.п. Безусловно применять их нельзя, но
      // и прятать в текст жалко — диалог атаки покажет их отдельными галочками.
      // { label, atk, dmg, wp:[ключи свойств], note }
      condMods:           (o.cond || []).map(c => ({
                            label: c.label || "", atk: c.atk || 0, dmg: c.dmg || 0,
                            wp: c.wp || [], note: c.note || "" })),
      // Свойства ОРУЖИЯ, которые даёт боеприпас (стр. 203): Шип → Crippling(1),
      // Думдум → Tearing/Primitive и т.д. Формат как у оружия: {key, rating}.
      // Движок атаки подмешивает их к свойствам ствола (attack.mjs).
      properties:         (o.wp || []).map(p => typeof p === "string"
                            ? { key: p, rating: 0, rating2: 0 }
                            : { key: p.key, rating: p.rating || 0, rating2: p.rating2 || 0 })
    }
  };
}

