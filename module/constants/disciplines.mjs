/**
 * Готовит данные для зависимых селектов «дисциплина → подтип».
 * @param {object} REG       PSY_DISCIPLINES или TECH_DISCIPLINES
 * @param {string} curDisc   текущая дисциплина (ключ)
 * @returns {{groups:Array, subtypes:string[]}}
 */
export function buildDisciplineContext(REG, curDisc) {
  const groupMap = {};
  for (const [key, d] of Object.entries(REG)) {
    (groupMap[d.group] ??= []).push({ key, label: d.label });
  }
  const groups = Object.entries(groupMap).map(([label, items]) => ({ label, items }));
  const subtypes = REG[curDisc]?.subtypes ?? [];
  return { groups, subtypes };
}
