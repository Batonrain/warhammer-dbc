/**
 * Сводка дисциплины по имени папки компендиума психосил (wdbc-pwx). Папки
 * записаны ВЕРХНИМ РЕГИСТРОМ («ТАУМАТУРГИЯ», «ВЫСШЕЕ КОЛДОВСТВО») — совпадение
 * ищем без учёта регистра против PSY_DISCIPLINES[key].label. Пусто, если
 * сводки для дисциплины ещё нет (см. комментарий у PSY_DISCIPLINES — не для
 * всех дисциплин есть книжный текст) или имя не совпало ни с одной.
 */
export function disciplineDescByFolderName(name) {
  const norm = String(name ?? "").trim().toLowerCase();
  if (!norm) return "";
  const found = Object.values(PSY_DISCIPLINES).find(d => d.label.toLowerCase() === norm);
  return found?.desc || "";
}

