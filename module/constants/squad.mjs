/** Бонус Слаженности к тесту Команды: Координатор — половина (окр.▲) или двойной штраф. */
export function cohesionBonus(cohesion, isCoordinator = false) {
  const c = Number(cohesion) || 0;
  if (!isCoordinator) return c;
  return c >= 0 ? Math.ceil(c / 2) : c * 2;
}

/** Потолок Успехов Команды по уровню Риска (null — без ограничения). */
export function riskCap(level) {
  return RISK_LEVELS.find(r => r.level === (Number(level) || 0))?.max ?? null;
}

/** Толкование текущей Слаженности. */
export function cohesionBand(cohesion) {
  const c = Number(cohesion) || 0;
  return COHESION_BANDS.find(b => c >= b.min) || COHESION_BANDS[COHESION_BANDS.length - 1];
}
