// Группы для optgroup в выпадающем списке (порядок сохраняется)
export const PATH_GROUPS = ["Путь Видящих", "Путь Воина"];

/** HTML опций <select> со всеми путями (сгруппированы), selected — ключ. */
export function buildPathSelectOptions(selectedKey) {
  let html = `<option value="">— выберите Путь —</option>`;
  const sel = (k) => k === selectedKey ? " selected" : "";
  // Сначала сгруппированные
  for (const grp of PATH_GROUPS) {
    html += `<optgroup label="${grp}">`;
    for (const [key, p] of Object.entries(AZURIANE_PATHS)) {
      if (p.group === grp) html += `<option value="${key}"${sel(key)}>${p.label}</option>`;
    }
    html += `</optgroup>`;
  }
  // Затем одиночные
  html += `<optgroup label="Прочие Пути">`;
  for (const [key, p] of Object.entries(AZURIANE_PATHS)) {
    if (!p.group) html += `<option value="${key}"${sel(key)}>${p.label}</option>`;
  }
  html += `</optgroup>`;
  return html;
}

/** HTML опций <select> для градации. */
export function buildGradeSelectOptions(path, selectedGrade) {
  let html = "";
  for (const g of PATH_GRADE_ORDER) {
    if (!path?.grades?.[g]) continue;
    const sel = g === selectedGrade ? " selected" : "";
    html += `<option value="${g}"${sel}>${PATH_GRADES[g]}</option>`;
  }
  return html;
}

/**
 * Суммарные пассивные авто-бонусы по списку путей персонажа.
 * Кумулятивно по достигнутым градациям (novice..выбранная), но без двойного
 * учёта одного и того же эффекта в рамках одного пути (берётся максимум).
 * paths: [{ key, grade }]
 * → { charBonus: { wp: 2, ... }, corLimit: 25 }
 */
export function computePathPassives(paths) {
  const charBonus = {};
  let corLimit = 0;
  if (!Array.isArray(paths)) return { charBonus, corLimit };
  for (const row of paths) {
    const path = AZURIANE_PATHS[row?.key];
    if (!path) continue;
    const gradeIdx = PATH_GRADE_ORDER.indexOf(row.grade);
    if (gradeIdx < 0) continue;
    // Unnatural-бонусы характеристик СУММИРУЮТСЯ по достигнутым градациям
    // этого пути; лимит Порчи — берётся максимум (это одно и то же стоячее
    // значение, повторяемое в описаниях градаций).
    const localChar = {};
    let localCor = 0;
    for (let i = 0; i <= gradeIdx; i++) {
      const g = path.grades[PATH_GRADE_ORDER[i]];
      if (!g?.auto) continue;
      if (g.auto.charBonus) {
        for (const [k, v] of Object.entries(g.auto.charBonus)) {
          localChar[k] = (localChar[k] || 0) + v;
        }
      }
      if (g.auto.corLimit) localCor = Math.max(localCor, g.auto.corLimit);
    }
    // суммируем по разным путям
    for (const [k, v] of Object.entries(localChar)) {
      charBonus[k] = (charBonus[k] || 0) + v;
    }
    corLimit += localCor;
  }
  return { charBonus, corLimit };
}

/**
 * Свойство Aspect оружия/брони (wdbc-8b5/wdbc-28ld, стр. 168/228): рейтинг —
 * не число, а текст группы/Пути в скобках («Кьюанснанар (Варп-Пауки)» → на
 * предмете хранится просто «Варп-Пауки»). Сопоставляем подстрокой по label
 * (регистронезависимо) — предмет хранит короткое имя, у Пути в реестре label
 * — полный вид с родным названием. Пустой/нераспознанный текст → null (не
 * штрафуем на неполных/ошибочных данных, читающая сторона сама решает, что
 * делать с null).
 */
export function findAspectPathKey(ratingText) {
  const needle = String(ratingText || "").trim().toLowerCase();
  if (!needle) return null;
  const found = Object.entries(AZURIANE_PATHS).find(([, p]) => p.label.toLowerCase().includes(needle));
  return found ? found[0] : null;
}

/**
 * Есть ли у персонажа (system.paths — [{key,grade}]) Путь, сопоставленный
 * тексту рейтинга Aspect. Нераспознанный текст (findAspectPathKey → null) —
 * считается «есть» (не штрафуем на данных, которые не смогли разобрать).
 */
export function actorHasAspectPath(system, ratingText) {
  const key = findAspectPathKey(ratingText);
  if (!key) return true;
  return (system?.paths || []).some(p => p?.key === key);
}
