/** Запись Истории по броску 1d10. */
export function historyByRoll(roll) {
  return LEGACY_HISTORIES.find(h => h.roll === Number(roll)) || null;
}

/** Запись Мутации по броску 1d10 внутри выбранного Характера. */
export function mutationByRoll(characterKey, roll) {
  const table = LEGACY_CHARACTERS[characterKey];
  if (!table) return null;
  const n = Number(roll);
  return table.entries.find(e => n >= e.min && n <= e.max) || null;
}

/** Текст записи для конкретного оружия: общий либо свой у рукопашного. */
export function entryText(entry, isMelee) {
  if (!entry) return "";
  return entry.both || (isMelee ? entry.melee : entry.ranged) || "";
}

