export const ASPIRATION_TABLES = [
  { key: "pride",      label: "Гордость"  },
  { key: "motivation", label: "Мотивация" },
  { key: "disgrace",   label: "Позор"     }
];

const ASPIRATION_SOURCE = "Black Crusade — Стремления (стр. 22)";

// Предметы-Стремления (type:"aspiration") для компендиума warhammer-dbc.aspirations.
// Источник истины при выборе на листе — сам компендиум (см. module/apps/aspirations.mjs);
// эта функция лишь засеивает/синкает его из констант выше, как и остальные библиотеки.
export function aspirationLibrary() {
  const out = [];
  for (const t of ASPIRATION_TABLES) {
    for (const e of ASPIRATIONS[t.key]) {
      out.push({
        name: e.name, type: "aspiration", img: "icons/svg/aura.svg", folder: t.label,
        system: { key: `${t.key}:${e.n}`, table: t.key, n: e.n, mods: e.mods, description: e.desc,
                  bookSource: ASPIRATION_SOURCE }
      });
    }
  }
  return out;
}
