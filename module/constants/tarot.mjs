// Привязываем арт к каждой карте (из assets/tarot-card по номеру).
for (const c of TAROT_DECK) c.img = TAROT_IMAGES[c.n] || "";

const _byN = new Map(TAROT_DECK.map(c => [c.n, c]));
export function cardByN(n) { return _byN.get(Number(n)) || null; }

// URL-безопасный путь арта (пробелы/кириллица/скобки) для <img src>.
export function cardImgSrc(card) { return card?.img ? encodeURI(card.img) : ""; }

// Отображаемый заголовок карты: Старшая Аркана — по имени; Малая — «Ранг — Имя».
export function cardTitle(card) {
  if (!card) return "";
  return card.suit === "major" ? card.name : `${card.rank} — ${card.name}`;
}
export function cardSuitLine(card) {
  if (!card) return "";
  return card.suit === "major" ? `Старшая Аркана · ${card.rank}` : SUITS[card.suit];
}

