// ── Помощники ────────────────────────────────────────────────────────────
export function lookupTable(table, roll) {
  return table.find(r => roll >= r.min && roll <= r.max) || table[table.length - 1];
}
export function degWord(n) {
  const a = Math.abs(n);
  if (a === 1) return n > 0 ? "Успех" : "Провал";
  return n > 0 ? "Успех(ов)" : "Провал(ов)";
}
