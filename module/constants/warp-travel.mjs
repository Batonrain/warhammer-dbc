// ── Шаг 4: Длительность варп-прыжка (по степеням успеха) ──────────────────
// deg > 0 — Успехи; deg < 0 — Провалы.
export function jumpDurationMult(deg) {
  if (deg >= 4)  return "×1/4";
  if (deg === 3) return "×1/2";
  if (deg === 2) return "×3/4";
  if (deg >= 1)  return "×1";
  if (deg === -1) return "×2";
  if (deg === -2) return "×3";
  return "×4";
}

