// module/data/actor/minion.mjs
// ════════════════════════════════════════════════════════════════════════════
//  МИНЬОН (корбук стр. 111-113) — слуга, взятый Талантом «Миньон Хаоса».
//
//  Механика у него общая с существом: Характеристики, Навыки, Раны, снаряжение
//  и Трейты считаются как у всех. Своё — привязка к Хозяину: группа (Человек,
//  Зверь, Машина, Демон), сила (Низший … Орда) и Лояльность, которая идёт от
//  Характеристики Хозяина и меняется вместе с ней.
//
//  Чего у Миньона нет: Архетипа и Элитного архетипа, Родного мира,
//  Предсказания и Стремлений — путь его определяет не биография, а Талант
//  Хозяина. Поля эти остаются в общей схеме существа (лист их просто не
//  показывает): убрать их из схемы значило бы разложить creatureSchema на
//  части ради одного типа.
//
//  Группа хранится в том же поле, что и раньше, — system.minionType: миньоны
//  жили признаком на Персонаже, и заводить второе имя одному и тому же
//  значило бы держать одну вещь в двух местах.
// ════════════════════════════════════════════════════════════════════════════

import { creatureSchema } from "./_creature.mjs";

export class MinionData extends foundry.abstract.TypeDataModel {

  /** @override */
  static defineSchema() {
    const { StringField, BooleanField, SchemaField, NumberField } = foundry.data.fields;
    const num = initial => new NumberField({ initial, nullable: false });
    return {
      ...creatureSchema(),
      isMinion: new BooleanField({ initial: true, label: "Миньон" }),
      // Талант, которым этот слуга куплен: слот занимается именно им, а не
      // парой «группа + сила» — Талантов одной пары бывает несколько.
      slotTalentId: new StringField({ initial: "", label: "Талант-слот" }),
      // Орда Миньонов Ран не имеет вовсе — у неё Магнитуда от Бесчестия
      // Хозяина (стр. 113). Поле держим здесь, а не в общей схеме существа:
      // Магнитуда бывает только у Орды.
      magnitude: new SchemaField({ value: num(0), max: num(0) }, { label: "Магнитуда" })
    };
  }
}
