// module/data/item/elite-archetype.mjs
// ════════════════════════════════════════════════════════════════════════════
//  ЭЛИТНЫЙ АРХЕТИП (корбук стр. 114-164) — ступень поверх обычного Архетипа:
//  требования, бонусы Характеристик, бесплатные Таланты, снаряжение и свой
//  список Трейтов и Дополнительных Талантов.
//
//  Текстовые поля (req, charBonus, freeTalents, gear) намеренно строки — как у
//  Архетипа: их разбирает Мастер создания, а ГМ читает и правит глазами.
//  Раскладывать их по числам значило бы потерять оговорки книги («2000 xp»,
//  «Two Weapon Wielder (Both)»), а они там на каждом шагу.
//
//  Трейты и Дополнительные Таланты в документ не копируются: они уже лежат в
//  библиотеках Черт и Талантов в папке «Элитные архетипы» — здесь только имена
//  списком, чтобы одно и то же не правилось в двух местах.
// ════════════════════════════════════════════════════════════════════════════

export class EliteArchetypeData extends foundry.abstract.TypeDataModel {

  /** @override */
  static defineSchema() {
    const { StringField, ArrayField } = foundry.data.fields;
    const str = (initial, label) => new StringField({ initial, label });
    const list = label => new ArrayField(new StringField(), { label });

    return {
      key:         str("", "Ключ"),
      race:        str("", "Раса"),
      // Покровительство: у друкхари его нет вовсе, поэтому пусто — обычное дело.
      god:         str("", "Покровительство"),
      req:         str("", "Требования"),
      charBonus:   str("", "Бонусы Характеристик"),
      freeTalents: str("", "Бесплатные Таланты"),
      gear:        str("", "Снаряжение"),
      // Имена записей библиотек — сами Черты и Таланты лежат там.
      traits:      list("Трейты архетипа"),
      talents:     list("Дополнительные Таланты"),
      description: str("", "Описание"),
      notes:       str("", "Заметки"),
      bookSource:  str("", "Книга-источник")
    };
  }
}
