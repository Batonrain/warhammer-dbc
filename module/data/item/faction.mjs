// module/data/item/faction.mjs
// ════════════════════════════════════════════════════════════════════════════
//  ФРАКЦИЯ — узел дерева принадлежностей: Хаос → Легионы-предатели → Несущие
//  Слово → VI воинство → III рота → отделение. На неё ссылаются Таланты
//  (Hatred, Peer, Enemy, Good Reputation), и правило срабатывает не только на
//  саму фракцию, но и на любую нижестоящую: Ненависть к Хаосу достаёт и роту.
//
//  УРОВНЕЙ КАК ПОЛЯ НЕТ, и это осознанно. Лестницы у фракций разной природы не
//  совпадают: у Хаоса это Легион/Воинство/Рота, у друкхари Кабал/Ковен, у
//  эльдар Мир-корабль/Путь. Перечисление уровней в схеме повторило бы ошибку
//  template.json — закрытый список там, где содержимое открыто. Структуру
//  задаёт единственная ссылка `parentKey`, глубина считается обходом дерева
//  (module/rules/factions.mjs).
//
//  `parentKey` хранит КЛЮЧ, а не UUID, тоже осознанно: разбор дерева живёт в
//  реестре правил, а тот обязан быть чистыми функциями без обращений к
//  Foundry. Ключ разрешается по обычной карте, UUID потребовал бы
//  асинхронного fromUuid — и предикаты перестали бы проверяться тестом.
//
//  ПОЧЕМУ НЕ `parent`. Так поле называлось сначала, и это была ошибка: у
//  любого DataModel уже есть своё свойство `parent` — ссылка на документ-
//  владелец. Схема его не переопределяет, а оказывается им закрыта:
//  `item.system.parent` возвращал сам предмет, на листе это выглядело как
//  «[object Object]», а первое же сохранение записывало документ целиком в
//  поле. Имя поля схемы не должно совпадать со свойством модели — отсюда
//  `parentKey` и разовый переезд в migrateData ниже.
// ════════════════════════════════════════════════════════════════════════════

export class FactionData extends foundry.abstract.TypeDataModel {

  /** @override */
  static defineSchema() {
    const { StringField, ArrayField, BooleanField } = foundry.data.fields;
    return {
      // Устойчивый ключ, на который ссылаются другие фракции и Таланты.
      // Выдаётся при создании из названия (module/documents/item.mjs,
      // factionKeyFromName) и руками не правится: правка втихую разорвала бы
      // ссылки. Переименование подписи его тоже не трогает.
      key:    new StringField({ initial: "", label: "Ключ" }),
      // Ключ вышестоящей фракции. Пусто — корень дерева. На листе ставится
      // перетаскиванием этой фракции либо кнопкой «＋», а не набором руками.
      parentKey: new StringField({ initial: "", label: "Входит в состав" }),
      // Дополнительные принадлежности: ключи фракций, которым эта подчиняется
      // или служит, не будучи их частью по устройству. Караул Смерти —
      // Астартес по составу и Ордо Ксенос по службе, и правило должно доставать
      // его с обеих сторон.
      //
      // Отдельным полем, а не вторым родителем: дерево обязано остаться
      // деревом. Схема происхождения и глубина считаются по основной линии,
      // иначе лесенку пришлось бы превращать в граф; отбор правил при этом
      // берёт объединение обеих (module/rules/factions.mjs, factionAncestors).
      alsoIn: new ArrayField(new StringField(), { label: "Также состоит в" }),
      // Другие названия той же силы: по ним фракция ищется при разборе
      // книжных строк («Ecclesiarchy» и «Экклезиархия» — одна запись).
      aliases: new ArrayField(new StringField(), { label: "Другие названия" }),
      // Годится ли фракция как специализация Знаний (Common/Scholastic/
      // Forbidden Lore). Верхние уровни годятся, отделение — нет, поэтому
      // это признак записи, а не вывод из глубины.
      isLore: new BooleanField({ initial: false, label: "Годится как Знание" }),
      description: new StringField({ initial: "", label: "Описание" }),
      notes:       new StringField({ initial: "", label: "Заметки" }),
      bookSource:  new StringField({ initial: "", label: "Книга-источник" })
    };
  }

  /**
   * Переезд `parent` → `parentKey` (см. шапку файла).
   *
   * Строку переносим как есть. Если в поле лежит документ — это след прежней
   * ошибки; последнее верное значение сохранилось внутри него, потому что
   * записанным туда документом был сам предмет со своим прежним `system`.
   * Достаём его оттуда, а не гасим ссылку молча: иначе дерево, собранное
   * вручную, развалилось бы при обновлении системы.
   */
  static migrateData(source) {
    const old = source?.parent;
    if (old !== undefined && !source.parentKey) {
      if (typeof old === "string") source.parentKey = old;
      else if (typeof old?.system?.parent === "string") source.parentKey = old.system.parent;
    }
    delete source.parent;
    return super.migrateData(source);
  }
}
