// module/data/item/faction.mjs
// ════════════════════════════════════════════════════════════════════════════
//  ФРАКЦИЯ — узел дерева принадлежностей: Хаос → Легионы-предатели → Несущие
//  Слово → VI воинство → III рота → отделение. На неё ссылаются Таланты
//  (Hatred, Peer, Enemy, Good Reputation), и правило срабатывает не только на
//  саму фракцию, но и на любую нижестоящую: Ненависть к Хаосу достаёт и роту.
//
//  УРОВНЕЙ КАК ПОЛЯ НЕТ, и это осознанно. Лестницы у фракций разной природы не
//  совпадают: у Хаоса это Легион/Воинство/Рота, у друкхари Кабал/Ковен, у
//  эльдар Мир-корабль/Путь. Перечисление уровней в схеме повторило бы ошибку
//  template.json — закрытый список там, где содержимое открыто. Структуру
//  задаёт единственная ссылка `parent`, глубина считается обходом дерева
//  (module/rules/factions.mjs).
//
//  `parent` хранит КЛЮЧ, а не UUID, тоже осознанно: разбор дерева живёт в
//  реестре правил, а тот обязан быть чистыми функциями без обращений к
//  Foundry. Ключ разрешается по обычной карте, UUID потребовал бы
//  асинхронного fromUuid — и предикаты перестали бы проверяться тестом.
// ════════════════════════════════════════════════════════════════════════════

export class FactionData extends foundry.abstract.TypeDataModel {

  /** @override */
  static defineSchema() {
    const { StringField, ArrayField, BooleanField } = foundry.data.fields;
    return {
      // Устойчивый ключ, на который ссылаются другие фракции и Таланты.
      // Переименование подписи его не трогает.
      key:    new StringField({ initial: "", label: "Ключ" }),
      // Ключ вышестоящей фракции. Пусто — корень дерева.
      parent: new StringField({ initial: "", label: "Входит в состав" }),
      // Другие названия той же силы: по ним фракция ищется при разборе
      // книжных строк («Ecclesiarchy» и «Экклезиархия» — одна запись).
      aliases: new ArrayField(new StringField(), { label: "Другие названия" }),
      // Годится ли фракция как специализация Знаний (Common/Scholastic/
      // Forbidden Lore). Верхние уровни годятся, отделение — нет, поэтому
      // это признак записи, а не вывод из глубины.
      isLore: new BooleanField({ initial: false, label: "Годится как Знание" }),
      description: new StringField({ initial: "", label: "Описание" }),
      notes:       new StringField({ initial: "", label: "Заметки" }),
      bookSource:  new StringField({ initial: "", label: "Книга-источник" })
    };
  }
}
