//  ХРАНИЛИЩЕ источников правил — и ничего кроме (wdbc-795h).
//
//  Раньше хранилище и РЕГИСТРАЦИИ жили в одном файле (rules/sources.mjs), и это
//  замыкало круг: сборка правил (collect.mjs) обязана знать список источников,
//  то есть импортировать sources.mjs, а тот импортирует всю библиотеку правил и
//  все подсистемы. Значит НИ ОДИН модуль из этого графа не мог спросить у
//  актора возможность — hasRuleFlag тянет collect.mjs, а тот через sources.mjs
//  тянет обратно спрашивающего.
//
//  Так и вышло с Адъютантом: adjutant.mjs → ability-by-key.mjs → flags.mjs →
//  collect.mjs → sources.mjs → adjutant.mjs. Загрузка модулей вставала насмерть,
//  и тест каркаса (rules/scaffold) падал по таймауту в 20 секунд — не с
//  ошибкой, а именно зависал, что хуже: сообщения нет, искать не по чему.
//
//  Поэтому файл СОЗНАТЕЛЬНО без единого импорта. Он лист графа, и любой модуль
//  волен его тянуть, ничем не рискуя. Регистрации остались в sources.mjs — там
//  же, где были, и оттуда же по-прежнему реэкспортируются эти три функции: их
//  импортируют три с лишним десятка файлов, и переезд хранилища не должен
//  заставлять править каждый.
//
//  Правило на будущее: сюда нельзя добавить ни одного импорта. Структурный
//  сторож — test/rules/source-registry-acyclic.test.mjs.
// ════════════════════════════════════════════════════════════════════════════

/** Источник — функция (actor, ctx) => массив правил. */
const SOURCES = new Map();

export function registerRuleSource(key, fn) {
  SOURCES.set(key, fn);
}

export function getRuleSources() {
  return [...SOURCES.entries()];
}

/** Очистка реестра. Нужна тестам, чтобы подставить свои источники. */
export function clearRuleSources() {
  SOURCES.clear();
}
