export const SOUL_SEER_RADIUS_M = 10;

/** Категория души по типу актора — "" для типов вне трёх книжных категорий. */
export function soulSeerCategory(actorType) {
  if (actorType === "character") return "человек";
  if (actorType === "vehicle") return "дух машины";
  if (actorType === "daemon" || actorType === "demonPrince") return "демон";
  return "";
}
