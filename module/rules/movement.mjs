/**
 * SPD = Ag.bonus + size (size — прямой модификатор, 0 = Человек)
 *
 * Таблица:
 * SPD | Полушаг | Шаг | Натиск | Бег
 * 0.5 |   0.5   |  1  |  1.5   |  3
 *  1  |    1    |  2  |   3    |  6
 *  2  |    2    |  4  |   6    | 12
 *  3  |    3    |  6  |   9    | 18
 *  4  |    4    |  8  |  12    | 24
 * ...и т.д. (SPD × 1, ×2, ×3, ×6)
 */
export function calcMovement(agBonus, size) {
  // SPD = Ag.bonus + size_mod
  // size — прямой мод: 0=Человек, -1=Ребёнок, 1=Орк-nob, итд
  const spdRaw = agBonus + (size ?? 0);

  // Если SPD <= 0 → особый случай: SPD = 0.5
  const spd = spdRaw <= 0 ? 0.5 : spdRaw;

  return {
    spd,
    halfMove: spd,        // SPD × 1
    move:     spd * 2,    // SPD × 2
    charge:   spd * 3,    // SPD × 3
    run:      spd * 6     // SPD × 6
  };
}
