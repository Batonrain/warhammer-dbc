export const BURNED_SENSES_CAPABILITY = "mutation.burnedSenses";

/** Таблица книги (d10) → ключ чувства. */
export function burnedSenseFromRoll(d10) {
  const n = Number(d10);
  if (n === 1) return "sight";
  if (n >= 2 && n <= 3) return "touch";
  if (n >= 4 && n <= 6) return "hearing";
  if (n >= 7 && n <= 8) return "smell";
  if (n >= 9 && n <= 10) return "taste";
  return null;
}

export const SENSE_LABELS = {
  sight: "Зрение", touch: "Касание", hearing: "Слух", smell: "Нюх", taste: "Вкус"
};

/** По книжному названию чувства (item.system.submutation.name) — ключ таблицы выше. */
export function senseKeyFromName(name) {
  const n = String(name || "").trim().toLowerCase();
  for (const [key, label] of Object.entries(SENSE_LABELS)) {
    if (label.toLowerCase() === n) return key;
  }
  return null;
}

/** Условие перманентной потери — только Зрение/Слух, иначе null (честный нарратив). */
export function burnedSenseConditionKey(senseKey) {
  if (senseKey === "sight") return "blinded";
  if (senseKey === "hearing") return "deafened";
  return null;
}
