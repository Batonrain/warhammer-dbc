//
//  Усиление чувства («+20 и переброс провалов») — НЕ реализуемо ни для
//  ОДНОГО из пяти чувств: Бдительность (Awareness) в системе один общий
//  Навык на все чувства разом, и это уже осознанное решение ЭТОГО ЖЕ
//  тикета (rules/library/conditions.mjs: «разбить его на слух/зрение не
//  тема этого тикета») — нет отдельного «теста на чувство X», нечего
//  усиливать выборочно. Честный нарратив для всех пяти вариантов без
//  исключения.
//
//  «Одинаковые чувства» — книга сама называет это решением ГМа
//  («слегка изменённое ПО РЕШЕНИЮ ГМА»), не числом: код здесь только
