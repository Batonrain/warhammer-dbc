//  ПРАВИЛА ОТ ПУТЕЙ АЗУРИАН (wdbc-4e60).
//
//  Пути заменяют эльдар Мировоззрение и расписаны в книге Аэльдари на 30 Путей
//  и 120 градаций. До этого файла система умела считать по ним ровно одно —
//  пассивные числа (charBonus/corLimit) у двенадцати градаций
//  (constants/aeldari-paths.mjs::computePathPassives). Всё остальное держал в
//  голове ГМ: Пути хранятся полем актора (system.paths), предметами не
//  являются, а возможности в этой системе раздают ТОЛЬКО источники правил
//  (module/rules/sources.mjs). Источника по Путям среди семи зарегистрированных
//  не было, поэтому Путь не мог выдать ни возможности, ни модификатора.
//
//  Здесь два вида содержимого, и их не надо путать:
//
//  1. PATH_RULES — правила, общие для ГРУППЫ Путей или для условия по
//     градации. Отбираются обычным `when` (предикат pathGradeMin), поэтому
//     писать их по одному на каждый из десяти Путей Воина не нужно.
//  2. Правила отдельной ГРАДАЦИИ конкретного Пути живут рядом с её текстом —
//     поле `rules` у градации в constants/aeldari-paths.mjs, собирается
//     функцией pathRules(). Так правило стоит рядом с описанием, которое его
//     же и объясняет.
// ════════════════════════════════════════════════════════════════════════════

import { pathRules } from "../../constants/aeldari-paths.mjs";
import { itemHasName } from "../predicates.mjs";

/**
 * Оружие, которому книга разрешает стрельбу одной рукой адепту Пути Воина.
 *
 * Список именной, а не по классу или свойству, и это единственный честный
 * вариант: прогон по всем шестнадцати книгам даёт РОВНО ОДНО такое правило —
 * Стрела Кхейна (Книга Аэльдари, «АРСЕНАЛ ЭЛЬДАР / СЮРИКЕН ОРУЖИЕ»).
 * Раздать разрешение классу basic нельзя — одноручную стрельбу получили бы все
 * винтовки разом; свойству Carbine — тоже нельзя: его несут 33 предмета, а
 * книга говорит про один.
 *
 * Имена двуязычные, как везде в системе: сравнение идёт по любой половине
 * (rules/predicates.mjs::itemHasName).
 */
export const PATH_ONE_HANDED_WEAPONS = ["Khaine's Arrow", "Стрела Кхейна"];

/**
 * Правила, общие для групп Путей.
 *
 * Стрела Кхейна: «Персонаж, обладающий любым Путем Воина на уровне Следующий,
 * может стрелять из этого оружия держа его в одной руке без траты в Rng».
 * Возможность выдаётся АКТОРУ, а какое оружие она пускает в одну руку —
 * решают читатели по списку выше (attack-dialog.mjs и rules/hands.mjs, оба:
 * иначе окно атаки разрешит хват, которого не знает бюджет рук, — эта ошибка
 * уже ловилась в wdbc-f7iw).
 *
 * «Без траты в Rng» — это отличие от модификации Pistol Grip, которая за
 * одноручный хват режет дальность вдвое: здесь дальность не трогается вовсе,
 * поэтому и обычным хватом "1р" правило не выражается — нужен свой ключ.
 */
export const PATH_RULES = [
  {
    id: "path.warrior.next.oneHandedKhaineArrow",
    label: "Путь Воина (Следующий): Стрела Кхейна в одной руке",
    when: { pathGradeMin: { group: "Путь Воина", grade: "next" } },
    effects: [{ kind: "grantFlag", target: "weapon.oneHandedWarriorPath" }]
  }
];

/** Все правила Путей актора: общие по группе плюс свои у достигнутых градаций. */
export function pathRulesFor(actor) {
  return [...PATH_RULES, ...pathRules(actor?.system?.paths)];
}

/** Подходит ли оружие под правило «одной рукой от Пути Воина». */
export function isPathOneHandedWeapon(item) {
  return PATH_ONE_HANDED_WEAPONS.some(name => itemHasName(item, name));
}
