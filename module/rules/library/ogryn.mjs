// Правила Огрина — машинная часть расовых Черт. Формат записи —
// docs/rules-format.md. Две группы с разными источниками:
//
// OGRYN_RULES — источник «race» (rules/sources.mjs, RACE_RULES.ogryn): признак
// сложения под огринское оружие. Без него расчёт rules/ogryn-fit.mjs не
// отличал бы Огрина от человека и штрафовал бы Огрина за его же оружие. Та же
// возможность `weapons.ogryn` выдаётся и записью Конструктора на Черте
// «Физиология Громилы» — так её получает Миньон с комплексной Чертой «Огрин»,
// у которого расы нет.
//
// OGRYN_TRAIT_RULES — отбор по Черте (`when.hasTrait`), отдаётся вместе с
// правилами основной книги (источник «core»): BONE-Head есть не только у
// расы, но и у Миньона с Чертой «Огрин». Чистая часть — rules/bone-head.mjs.
//
// Остальное из Черт расы живёт не здесь:
//   • Размер, Сверхъестественные Сила и Стойкость — документы Черт в паке;
//   • «Физиология Громилы»: +15 Ран, иммунитет к Обескровливанию, −20 на
//     тонкую манипуляцию (галочка в диалоге) и возможности
//     brutePhysiology.* — записи Конструктора на самой Черте
//     (packs-src/traits/Brute_Physiology…); их читатели — в
//     constants/capabilities.mjs.

