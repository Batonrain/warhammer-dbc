// module/rules/library/core.mjs
//
// Правила основной книги — те, что действуют у всех и не зависят ни от расы, ни
// от Происхождения. Источник «core» (rules/sources.mjs) отдаёт их каждому
// актору, а отбор идёт по условию `when`.
//
// Здесь живут правила, которые нельзя приписать одной расе: Черта есть у
// нескольких, а действует она на того, кто атакует её носителя.

export const CORE_RULES = [
  {
    // «Атакующим по нему −Ag.b к попаданию» (стр. 168). Черта записана у
    // Астартес, Азуриан, Друкхари и Кроорка, поэтому правило не принадлежит
    // расе: оно отбирается по Черте у ЦЕЛИ.
    //
    // Числа в данных быть не может — штраф равен Бонусу Ловкости той цели, по
    // которой бьют сейчас. Поэтому `valueFrom` вместо `value`.
    //
    // Рейтинг в названии Черты у разных рас записан по-разному («Nimble» и
    // «Nimble (10)»), а сравнение имён отбрасывает скобки на конце
    // (rules/predicates.mjs), поэтому в условии достаточно короткого имени.
    id: "core.nimble",
    label: "Проворный (цель уворачивается)",
    when: { targetHasTrait: "Nimble" },
    effects: [{
      kind: "rollBonus",
      target: "attack",
      valueFrom: { targetCharBonus: "ag", multiplier: -1 }
    }]
  }
];
