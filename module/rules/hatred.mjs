// специализация Берсерк) — впервые получает реального потребителя
// (wdbc-1rno, разведка 12.09.2026: во всём паке НИ ОДИН Талант с целями
// Hatred/Peer/Good Reputation не читался в бою, инфраструктура целей
// (rules/talent-targets.mjs, apps/target-choice.mjs) существовала с этапа
// Родных миров, но собранные игроком цели нигде не сравнивались с целью
// текущего броска — Талант был честным текстом на листе).
//
// Книжный текст (packs-src, benefit): «Цели, против которых у персонажа
// есть этот Талант (Ненавистные), дают ему +10 на рукопашные атаки по ним;
// он может перебрасывать тесты на Подавление, Страх, Шок и Панику и
// встречные социальные тесты против них. Он должен проходить W+0, желая
// отступить из боя с Ненавистным врагом, проявить милосердие, либо
// атаковать другую цель.»
//
// Реализовано из четырёх пунктов:
//   1. +10 на рукопашные атаки — target:"weapon:melee", тот же
//      ctx.targetActor, что и у остальных cross-actor правил атаки.
//   2. Переброс социального теста, который персонаж САМ бросает против цели
//      Ненависти — target:"social" (та же область, что у Синэстезии/
//      Countenance of Gods), тот же ctx.targetActor, что теперь заполняется
//      и на плоских тестах Навыка (actor-sheet.mjs, с 01.09.2026), не
//      только в атаке.
//   3. Переброс теста на Подавление и Теста Страха «против» цели
//      Ненависти — target:"morale" (wdbc-1rno, 12.09.2026, устраняет
//      повторно всплывавший пробел «источник угрозы у тестов Морали не
//      известен», см. также Heart of Steel wdbc-tsz6):
//      • Подавление (module/combat/suppression.mjs::rollSuppressionTest) —
//        стрелок известен уже в момент выстрела (карточка атаки несёт
//        attackerUuid ради Орды), но терялся к моменту клика по кнопке
//        теста в чате: владелец ТОКЕНА ЦЕЛИ жмёт кнопку позже и с другого
//        клиента. Кнопка теперь несёт data-attacker-uuid, hooks.mjs читает
//        его и передаёт actor'ом дальше — rollMoraleTest получил opts.
//        sourceActor, едущий как ctx.targetActor.
//      • Тест Страха (sheets/tabs/disorders.mjs::openFearDialog) — книжно НЕ
//        привязан к конкретному токену (игрок вручную выбирает числовой
//        рейтинг из таблицы), но если источник угрозы всё же выделен на
//        сцене — тот же приём, что у attack-dialog.mjs (game.user.targets),
//        читается и подставляется в ctx диалога, переброс всплывает
//        галочкой (ruleRerollsHtml), как и у прочих правил Морали.
//      • Выход из Шока (module/combat/fear.mjs::rollShockRecovery) и Паника
//        от Горения (module/combat/condition-ticks.mjs) сознательно БЕЗ
//        источника — оба катаются позже исходной угрозы (состояние уже
//        оторвано от того, кто его вызвал), и у Паники от Горения источник —
//        огонь, не актор: sourceActor туда не передаётся, opts.sourceActor
//        остаётся null, ведут себя как раньше.
//
// НЕ реализовано (честно, не лень — решение стола, не программы):
//   4. W+0 «пройти, чтобы отступить/проявить милосердие/сменить цель» — это
//      поведенческое ограничение игрока, а не бонус: движок нигде не
//      удерживает персонажа от собственного действия принудительно (тот же
//      вывод, что «лимит одной атаки в Ход» у Решительности Сражаться,
//      wdbc-1rno 03.09.2026).

import { hatredTargetsOf } from "./predicates.mjs";
import { anyTargetMatches } from "./talent-targets.mjs";

/**
 * Правила от Ненависти для ТЕКУЩЕГО теста — источник sources.mjs::"hatred".
 * Обе записи безусловные (`when: {}`): единственный настоящий гейт — совпала
 * ли цель ЭТОГО броска (ctx.targetActor) хоть с одной целью Ненависти,
 * проверено здесь один раз, до того как записи попадут в отбор. Без матча
 * источник отдаёт пустой список — дешевле, чем гонять два безусловных
 * правила через collectRules ради того, чтобы effectAppliesTo всё равно
 * отсеяла и атаку, и социальный тест по не-Ненавистной цели.
 */
export function hatredRules(actor, ctx = {}) {
  const targets = hatredTargetsOf(actor);
  if (!targets.length || !anyTargetMatches(targets, ctx)) return [];

  return [
    {
      id: "hatred.meleeBonus", label: "Ненависть: рукопашная атака по Ненавистной цели",
      when: {},
      effects: [{ kind: "rollBonus", target: "weapon:melee", value: 10 }]
    },
    {
      id: "hatred.socialReroll", label: "Ненависть: встречный социальный тест против Ненавистной цели",
      when: {},
      effects: [{ kind: "rollMode", target: "social", mode: "keepBest", rolls: 2, who: "self" }]
    },
    {
      id: "hatred.moraleReroll", label: "Ненависть: тест Морали против Ненавистной цели",
      when: {},
      effects: [{ kind: "rollMode", target: "morale", mode: "keepBest", rolls: 2, who: "self" }]
    }
  ];
}
