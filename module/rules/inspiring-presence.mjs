// module/rules/inspiring-presence.mjs
//
// Inspiring Presence / Вдохновляющее Присутствие — Черта архетипа Чемпион
// (Космодесант, корбук, «Архетипы Космодесантников», стр. 15):
//
//   «Чемпион может позволять союзникам и подчиненным в пределах видимости
//   использовать его Очки Бесчестья, как если бы они имели Cor и
//   Покровительство Чемпиона. Переданные таким образом Очки Бесчестия
//   позволяют другому персонажу перебрасывать уже переброшенный тест.»
//
// Чистая логика: кому из Чемпионов на сцене союзник может «одолжить» Очко.
// Сцена (токены, поле зрения) — module/combat/inspiring-presence.mjs; кнопка —
// меню переброса карточки теста (module/hooks.mjs::_attachFateContextMenu).
//
// «Уже переброшенный тест» система и так не запирает — меню переброса есть у
// любой карточки теста, в том числе у карточки переброса.
// «Как если бы имели Cor и Покровительство Чемпиона» касается способностей
// Очка с порогом Порчи/запретом Бога; меню карточки даёт только Переброс и
// +10 (оба без порога Порчи), поэтому здесь ни с чем не сравнивается.

/** Имя возможности (module/constants/capabilities.mjs), выдаёт документ Черты. */
export const INSPIRING_PRESENCE = "trait.inspiringPresence";

/**
 * Может ли этот Чемпион дать Очко этому персонажу.
 * @param {object} p
 * @param {boolean} p.sameActor  Чемпион — сам бросающий (тогда это обычная трата, не эта Черта)
 * @param {string}  p.relation   отношение токенов (regions/auras.mjs::tokenRelationship)
 * @param {boolean} p.inSight    токен бросающего в поле зрения токена Чемпиона
 * @returns {boolean}
 */
export function canInspire({ sameActor, relation, inSight } = {}) {
  return !sameActor && relation === "ally" && !!inSight;
}

/**
 * Почему пункт меню недоступен (пусто — доступен).
 * @param {{pool:number, canSpend:boolean}} p
 *   pool — Очки Чемпиона (с временным запасом); canSpend — этот клиент может
 *   списать их: владеет Чемпионом, либо в игре есть ГМ для ретрансляции.
 */
export function inspireBlockReason({ pool, canSpend } = {}) {
  if (!(Number(pool) >= 1)) return "У Чемпиона нет Очков Бесчестия";
  if (!canSpend) return "Списать чужое Очко некому: нет ГМа в игре";
  return "";
}
