//  остальные частоты — прямой перевод минут/часов книги.
// ════════════════════════════════════════════════════════════════════════

import { SECONDS_PER_ROUND } from "./condition-duration.mjs";

export const BREEZE_CAPABILITY = "mutation.breeze";

/** Частота теста (constants/environment.mjs::tempEffect().freq) → секунды кулдауна. */
const FREQ_SECONDS = {
  "каждый Ход":      SECONDS_PER_ROUND,
  "каждую минуту":   60,
  "раз в 5 минут":   5 * 60,
  "раз в 30 минут":  30 * 60,
  "каждый час":      3600,
  "раз в 2 часа":    2 * 3600,
  "раз в 4 часа":    4 * 3600,
  "раз в 8 часов":   8 * 3600
};

/** null — неизвестная строка частоты (защита от рассинхрона с environment.mjs). */
export function tempHazardIntervalSeconds(freq) {
  return FREQ_SECONDS[freq] ?? null;
}
