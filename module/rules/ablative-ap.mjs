// module/rules/ablative-ap.mjs
// ════════════════════════════════════════════════════════════════════════════
//  wdbc-bxw6 — общий примитив для ТРЁХ разных «аблативных AP/Структуры»
//  механик, которые делят только слово «аблативный» с уже построенным пулом
//  Аблативных Ран (wdbc-smy7/wdbc-w8ws, module/rules/wounds.mjs) — здесь
//  считается НЕ поглощение урона по очкам, а плоская добавка к AP/Структуре,
//  которая теряет ровно 1 заряд за КАЖДОЕ попадание, независимо от урона:
//   1. Мод брони «Аблативная» (armor-mods/Укрепление): +5 AP всем зонам,
//      −1 заряд с каждого попадания по владельцу, на 0 — мод бездействует
//      (module/combat/armor-mods.mjs::getArmorModEffects).
//   2. Роба Чемпиона + 5 бестиарных копий: 1 тPR → 2 аблативных AP «психощита»
//      персонажа (system.ablativeApShield, _creature.mjs) — тот же −1/попадание,
//      плюс отдельное угасание 1d5+1 в начале каждого нового Раунда.
//   3. Минный Плуг (vehicle-equipment): +20 аблативной Структуры техники
//      против мин (system.structure.ablative, data/actor/vehicle.mjs) —
//      тот же −1/попадание (какие именно попадания «от мин» — решает GM,
//      автоматического детектора мин в конвейере урона нет, см. combat/vehicle.mjs).
//  Все три читают/пишут через applyAblativeApHit ниже — единая точка, чтобы
//  правило «−1 за попадание» не разъезжалось по трём копипастам.
// ════════════════════════════════════════════════════════════════════════════

/** Заряд после одного попадания — ровно −1, не зависит от урона. Пол — 0. */
export function ablativeApAfterHit(current) {
  return Math.max(0, (Number(current) || 0) - 1);
}

/** Угасание в начале нового Раунда (Роба Чемпиона: 1d5+1) — на произвольную величину. */
export function ablativeApAfterDecay(current, amount) {
  return Math.max(0, (Number(current) || 0) - (Number(amount) || 0));
}
