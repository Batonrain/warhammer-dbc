//  ОПОЗНАНИЕ СПОСОБНОСТИ ПО КЛЮЧУ — рядом с опознанием по имени (wdbc-iadw).
//
//  Полсотни Талантов, Черт и Мутаций опознавались в коде по литеральному
//  имени: `itemHasName(i, "Bone Song")`. Имя — договор, который не держится ни
//  на чём: переименовали предмет в компендиуме (например при сверке с книгой),
//  и механика молча перестала работать. Ни один гейт этого не ловил, в консоль
//  ничего не писалось; заметить можно было только за столом, когда кнопка не
//  появилась. AGENTS.md приводит это на своём же примере — в паке лежал «Sure
//  Stitch» вместо «Sure Strike».
//
//  Здесь связь переводится на ключ Возможности (module/constants/
//  capabilities.mjs): предмет несёт запись Конструктора kind:"capability", код
//  спрашивает ключ. Ключ не зависит ни от того, как способность называется
//  по-русски и по-английски, ни от того, Талант это, Черта или Мутация.
//
//  ПОЧЕМУ ИМЯ ПРОВЕРЯЕТСЯ ПЕРВЫМ, а не наоборот:
//
//  1. Приём проекта — новое живёт РЯДОМ со старым (скилл dbc-workflow). Ни
//     один шаг не начинается с удаления работающего кода: пока не все паки
//     несут ключ, проверка по имени обязана продолжать работать.
//  2. Цена. Разбор имени идёт по кэшу на самом предмете (predicates.mjs) и
//     почти бесплатен, а hasRuleFlag ВНЕ пересчёта листа собирает все правила
//     актора заново — обход всех предметов и всех записей Конструктора
//     каждого. За одну атаку такие вопросы задаются десятками, и порядок
//     наоборот превратил бы каждый в полный обход.
//
//  То есть в обычном случае, когда имя на месте, до сборки правил дело не
//  доходит вовсе, а ключ срабатывает ровно тогда, когда имя разошлось.
//
//  Когда все паки будут нести ключи и это подтвердится живой проверкой,
//  проверку по имени можно снимать — отдельным шагом, не этим.
// ════════════════════════════════════════════════════════════════════════════

import { CAPABILITIES } from "../constants/capabilities.mjs";
import { hasRuleFlag } from "./flags.mjs";
import { itemHasName } from "./predicates.mjs";

/**
 * Есть ли у актора способность — по имени предмета ИЛИ по ключу Возможности.
 *
 * @param {object} actor
 * @param {string} key    ключ из module/constants/capabilities.mjs
 * @param {string} name   имя предмета (любая половина двуязычного — не пара!)
 * @param {string|string[]} types  тип(ы) предмета-носителя для проверки по имени
 * @returns {boolean}
 */
export function hasAbility(actor, key, name, types = "talent") {
  const kinds = Array.isArray(types) ? types : [types];
  const items = actor?.items;
  if (items?.some?.(i => kinds.includes(i?.type) && itemHasName(i, name))) return true;
  return !!key && hasRuleFlag(actor, key);
}

/**
 * hasAbility для Таланта, чьё английское имя записано в реестре (source
 * «English / Русское»). Для читателей, которые знали только ключ: у персонажа,
 * взявшего Талант до того, как запись легла в пак, копия ключа не несёт до
 * «Обновить мир» (приёмка #554). Привязку имён к пакам держит
 * test/rules/talent-capability-stale-copy.test.mjs.
 *
 * @param {object} actor
 * @param {string} key ключ из module/constants/capabilities.mjs
 */
export function hasTalentCapability(actor, key) {
  return hasAbility(actor, key, String(CAPABILITIES[key]?.source ?? "").split(" / ")[0].trim(), "talent");
}
