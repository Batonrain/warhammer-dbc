// Единая таблица Сложности (корбук, стр. 26, «Сложность»): модификатор от +40 до
// −60 с шагом 10, без вложенного смысла — сам столбец «Пример» в книге не даёт
// названий уровней, только россыпь примеров на каждый мод. Подписывать шаги
// придуманными словами («Рутинно», «Тяжело»…) значило бы дописать то, чего нет в
// источнике, поэтому подпись — сам модификатор.
//
// Список пуст только числами: диалог броска решает, как их показать
// (выпадающий список, значение по умолчанию и т.п.), а откуда мод берётся здесь
// не описывается — у будущих диалогов (крафт, верховая езда) своя предустановка,
// эта же таблица только даёт доступные шаги.

export const DIFFICULTY_STEPS = [
  { value:  40, label: "+40" },
  { value:  30, label: "+30" },
  { value:  20, label: "+20" },
  { value:  10, label: "+10" },
  { value:   0, label: "+0" },
  { value: -10, label: "−10" },
  { value: -20, label: "−20" },
  { value: -30, label: "−30" },
  { value: -40, label: "−40" },
  { value: -50, label: "−50" },
  { value: -60, label: "−60" }
];

/** Шаг по умолчанию — центр таблицы, «без модификатора сложности». */
export const DEFAULT_DIFFICULTY = 0;

/** Значение есть в таблице? Диалог не должен предустанавливать шаг, которого нет. */
export function isKnownDifficulty(value) {
  return DIFFICULTY_STEPS.some(s => s.value === Number(value));
}
