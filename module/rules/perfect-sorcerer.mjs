// module/rules/perfect-sorcerer.mjs
// ════════════════════════════════════════════════════════════════════════
//  Perfect Sorcerer / Совершенный Чародей (Тзинч, wdbc-1rno, d100 70…73):
//  «...может изучать психосилы Высшего Колдовства, невзирая на своё
//  Покровительство.»
//
//  Обычное правило книги (constants/disciplines.mjs::highSorcery, поле
//  desc): «Только персонажи, не имеющие Покровительства ни одного из
//  Богов, могут выучить эти психосилы... Псайкеры не-Хаоситы не могут
//  изучать или манифестировать психосилы Высшего Колдовства.» — нигде в
//  коде эта дисциплина-специфичная привязка к Покровительству раньше не
//  проверялась (единственный существующий гейт психосил — Метка Бога,
//  sheets/tabs/psychic.mjs::missingMarkForPower, СВОЙ отдельный механизм,
//  этот Дар его не трогает).
//
//  «Без Покровительства конкретного Бога» в системе — patronGod пуст либо
//  "undivided" (Хаос Неделимый); один из 4 конкретных Богов — запрет.
//  Тот же фолбэк уже читает actor-sheet.mjs::_infamyKey (`patronGod ||
//  "undivided"`) — не изобретаем новый смысл поля.
//
//  ВАЖНО: книга запрещает Покровительством ИЗУЧЕНИЕ, а применение прямо
//  сохраняет — «но если они получают покровительство Богов ПОСЛЕ ЭТОГО, они
//  сохраняют способность их использования». Поэтому гейт манифестации по
//  Покровительству был неверен (приём 14.09.2026): колдун, выучивший силу до
//  присяги Богу, по книге продолжает ею пользоваться, а система ему
//  отказывала. Манифестацию книга закрывает по ДРУГОМУ признаку — второй
//  фразой той же записи: «Псайкеры не-Хаоситы не могут изучать ИЛИ
//  МАНИФЕСТИРОВАТЬ психосилы Высшего Колдовства». Её и проверяем.
//
//  «Не-Хаосит» в системе — `system.alignment !== "heretic"`; то же поле
//  разделяет Судьбу и Бесчестье в rules/death-save.mjs, нового смысла не
//  заводим.
//
//  Запрет ИЗУЧЕНИЯ (blocksHighSorcery ниже) остаётся невостребованным: в
//  системе нет гейта на добавление психосилы на лист ни для одной
//  дисциплины — предмет кладут перетаскиванием. Предикат сохранён потому,
//  что он выражает книжное правило верно и именно его снимает этот Дар;
//  подключение — отдельной задачей, не гейтом манифестации.
//
//  «Обучать других любой психосиле» (вторая половина Дара) — вне рамок:
//  такой механики («передать психосилу другому актору») в системе нет
//  вовсе, ни для одной находки; решено пока игнорировать (12.09.2026).
//
//  «Фокус Дисциплин» (wdbc-l6zg, реализовано 14.09.2026): книга даёт Дару
//  Фокус Колдовства/Пагубной Демонологии/Высшего Колдовства/всех
//  Фундаментальных Дисциплин, обходя для НОСИТЕЛЯ общий запрет книги («эти
//  дисциплины не могут быть выучены через Фокус», disciplines.mjs::
//  NO_FOCUS_DISCIPLINES). Суб-дисциплина «Пагубная Демонология» отдельного
//  ключа в PSY_DISCIPLINES не имеет (daemonology — одна запись на обе
//  суб-дисциплины Демонологии, subtype — свободный текст на психосиле, не
//  ключ) — грант даёт Фокус ВСЕЙ daemonology, это единственная возможная
//  точность на нынешней модели данных, не намеренное расширение книжного
//  дара на Чистую Демонологию.
// ════════════════════════════════════════════════════════════════════════

import { hasRuleFlag } from "./flags.mjs";

export const PERFECT_SORCERER_CAPABILITY = "gift.tzeentch.perfectSorcerer";

/** Дисциплины, чей Фокус даёт этот Дар в обход общего запрета книги (wdbc-l6zg). */
export const PERFECT_SORCERER_FOCUS_DISCIPLINES =
  ["sorcery", "daemonology", "highSorcery", "telekinesis", "telepathy", "divination", "biomancy", "pyromancy"];

/** Дисциплины, Фокус которых актору даёт этот Дар — пусто, если Дара нет. */
export function perfectSorcererFocusDisciplines(actor) {
  return hasRuleFlag(actor, PERFECT_SORCERER_CAPABILITY) ? PERFECT_SORCERER_FOCUS_DISCIPLINES : [];
}

const RESTRICTED_PATRONS = ["khorne", "nurgle", "tzeentch", "slaanesh"];

/** Книжный запрет Высшего Колдовства сам по себе — без учёта этого Дара. */
export function blocksHighSorcery(patronGod) {
  return RESTRICTED_PATRONS.includes(patronGod);
}

/**
 * Гейт МАНИФЕСТАЦИИ Высшего Колдовства — true, если манифестировать нельзя.
 *
 * Единственное, что книга закрывает на манифестации, — не-Хаоситы. По
 * Покровительству здесь не отказываем: книга прямо сохраняет право
 * применять за тем, кто выучил силу до того, как обрёл Покровителя (см.
 * шапку файла). Носителю Совершенного Чародея это и так безразлично — Дар
 * Тзинча достаётся только хаоситу.
 */
export function highSorceryManifestBlocked(actor, discipline) {
  if (discipline !== "highSorcery") return false;
  return actor?.system?.alignment !== "heretic";
}
