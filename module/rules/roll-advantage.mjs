// ════════════════════════════════════════════════════════════════════════════
//  «Бросок с Преимуществом» вида «кинуть N раз, взять лучший результат» —
//  Эльданар на стартовое Влияние (Мастер создания), Серый Человек/Oteshii на
//  боевую Инициативу (module/documents/combatant.mjs). Оба случая — обычная
//  арифметика (характеристика/инициатива), где БОЛЬШЕЕ число лучше.
//
//  НЕ путать с rules/reroll-pick.mjs::pickReroll — там «лучший» исторически
//  МЕНЬШИЙ бросок (d100-тест успешен, если бросок не выше порога): слепое
//  переиспользование той функции здесь молча инвертировало бы результат
//  (взяло бы худший из N бросков вместо лучшего). Поэтому — отдельная, явная
//  по направлению функция, а не режим существующей.
// ════════════════════════════════════════════════════════════════════════════

/**
 * @param {number[]} values броски в порядке выпадения
 * @returns {?{value:number, index:number, dropped:number[]}} null на пустом списке
 */
export function pickHighest(values) {
  const list = Array.isArray(values) ? values.map(Number).filter(Number.isFinite) : [];
  if (!list.length) return null;

  let index = 0;
  // Строгое сравнение оставляет первый из равных: иначе одинаковые броски
  // выбирались бы по-разному от запуска к запуску (тот же принцип, что у
  // pickReroll).
  for (let i = 1; i < list.length; i++) if (list[i] > list[index]) index = i;

  return { value: list[index], index, dropped: list.filter((_, i) => i !== index) };
}
