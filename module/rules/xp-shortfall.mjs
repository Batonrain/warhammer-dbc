//  НЕХВАТКА ОПЫТА ПРИ ПОКУПКЕ (сверка «Опыт», стр. 23).
//
//  Книга: смена Покровительства пересчитывает цены уже купленного и «может
//  приводить к отрицательному нераспределенному опыту, в коем случае персонаж
//  не может покупать новые продвижения, пока не погасит этот негативный опыт».
//
//  Лист не запрещает, а спрашивает — так уже работают Элитные Архетипы и
//  Психосилы (apps/elite-buy.mjs): «в долг» бывает за столом, и решает ГМ.
//  Здесь только чистая часть: нужно ли спрашивать и что сказать.
// ════════════════════════════════════════════════════════════════════════════

const num = v => Number(v) || 0;

/**
 * Хватает ли свободного опыта на трату.
 *
 * @param {number} free  свободный опыт (experience.current), может быть < 0
 * @param {number} cost  сколько стоит покупка — ПРИРОСТ цены, а не полная цена
 *   уровня: у Характеристики и Навыка на листе хранится накопленная сумма
 * @returns {null | {cost:number, free:number, lack:number, negative:boolean}}
 *   null — спрашивать нечего (трата нулевая, отрицательная — это возврат — или
 *   опыта хватает)
 */
export function xpShortfall(free, cost) {
  const need = num(cost);
  const have = num(free);
  if (need <= 0 || need <= have) return null;
  return { cost: need, free: have, lack: need - have, negative: have < 0 };
}

/** Текст вопроса. Минус называется отдельно — это случай, о котором книга. */
export function shortfallMessage({ cost, free, negative }) {
  const tail = negative
    ? " Опыт уже в минусе: по книге, пока он не погашен, новые продвижения не покупаются."
    : "";
  return `Нужно <b>${cost}</b>, свободно <b>${free}</b>.${tail} Взять всё равно?`;
}
