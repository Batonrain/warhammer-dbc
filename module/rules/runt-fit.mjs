import { itemHasName } from "./predicates.mjs";

/** Возможность «сложен как Ратлинг» — запись Механики Черты Runt / Коротышка. */
export const RUNT_FIT_FLAG = "weapons.runt";

/** Установлена ли модификация Compact / Компактное. */
export function hasCompactMod(mods = []) {
  return (mods ?? []).some(m => m?.type === "weaponMod" && itemHasName(m, "Compact"));
}

/** Винтовка в руках Коротышки считается длинной (без Compact). */
export function runtLongRifle({ isRunt = false, weaponClass = "", hasLongRifle = false, compact = false } = {}) {
  return !!isRunt && weaponClass === "basic" && !hasLongRifle && !compact;
}

/**
 * Хваты стрелкового после запрета «двуручное одной рукой». Двуручное — чей
 * природный (первый собственный) хват «2р», либо, без своих хватов, класс не
 * пистолет/метательное. Пистолет с «1р (2р)» не трогается — он одноручный.
 */
export function runtRangedGrips(grips, { isRunt = false, compact = false, ownGrips = [], weaponClass = "" } = {}) {
  if (!isRunt || compact) return grips;
  const natural = ownGrips[0] || (["pistol", "thrown"].includes(weaponClass) ? "1р" : "2р");
  if (natural !== "2р") return grips;
  return grips.filter(g => g !== "1р");
}
