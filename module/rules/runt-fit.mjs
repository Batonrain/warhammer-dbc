//      удара прикладом как у длинной винтовки;
//    • двуручное стрелковое (природный хват «2р») одной рукой нельзя вовсе —
//      ни своим «(1р)», ни выданным модификацией/Талантом.
//  Установленная модификация Compact снимает оба. «Оружие под Ратлингов»
//  отдельной пометки в паках не имеет — его ставят как Compact.
//
//  Чистые функции; читатели — sheets/attack-dialog.mjs (окно атаки) и
//  rules/hands.mjs (бюджет рук). Возможность — RUNT_FIT_FLAG, выдаёт Механика
