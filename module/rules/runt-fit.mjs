//  персонажей Размером 0, но считает все винтовки — длинными винтовками, и не
//  может использовать двуручное стрелковое оружие одной рукой, невзирая на его
//  модификации. Модификация Compact нивелирует эти штрафы (оружие, специально
//  созданное под Ратлингов, считается уже имеющим эту модификацию)».
//
//  Два следствия, оба — на конкретном стволе в конкретных руках:
//    • винтовка = длинная винтовка: свойство Long Rifle (constants/
