// ═══════════════════════════════════════════════════════════════════════════
//  Четвероногий (X) / Quadruped (X) — корбук, глава «Трейты»:
//    «Он удваивает свой SPD и вес Ношения. Рейтинг отображает природу
//     «четвероногости»: 0 — нет манипулирующих рук…; 1 — он может двигаться на
//     четвереньках или прямоходящим: в первом случае он не может ничего носить в
//     одной паре рук (кроме оружия-когтей и кулаков), во втором — двигается как
//     без этого Трейта; 2 — «кентавр», без ограничений для рук, может проводить
//     Верховую Атаку самостоятельно.»
//
//  Реализовано (dbc-114 / 55-15, 13.11.2026, решение владельца): SPD ×2 вместе с
//  надбавками (множитель — на итоговый SPD, после Черт/Перевеса) и вес Ношения ×2
//  (Подъём и Толкание книга не упоминает — не трогаются). Рейтинги 0 и 2 — удвоено
//  всегда; рейтинг 1 — по переключателю режима: «на четвереньках» (удвоено) или
//  «прямоходящий» (как без Трейта). Режим — флаг актора quadrupedUpright.
//  НЕ реализовано (остаётся текстом): ограничения рук по рейтингу (0 — нет
//  манипулирующих рук; 1 на четвереньках — одна пара занята), самостоятельная
//  Верховая Атака у рейтинга 2.
// ═══════════════════════════════════════════════════════════════════════════

import { itemHasName } from "./predicates.mjs";

export const QUADRUPED_UPRIGHT_FLAG = "quadrupedUpright";

/** Черта Четвероногий на акторе (тип «Черта») или null. */
export function quadrupedTrait(actor) {
  return [...(actor?.items ?? [])].find(i => i?.type === "trait"
    && (itemHasName(i, "Quadruped") || itemHasName(i, "Четвероногий"))) ?? null;
}

/** Прямоходящий ли сейчас (флаг режима; по умолчанию — на четвереньках). */
export function isQuadrupedUpright(actor) {
  const flagged = actor?.flags?.["warhammer-dbc"]?.[QUADRUPED_UPRIGHT_FLAG] ?? actor?.getFlag?.("warhammer-dbc", QUADRUPED_UPRIGHT_FLAG);
  return !!flagged;
}

/**
 * Множитель SPD и Ношения: 2, если Черта есть и действует, иначе 1. Рейтинг 1 в
 * режиме «прямоходящий» не удваивает; рейтинги 0 и 2 — всегда.
 */
export function quadrupedMultiplier(actor) {
  const t = quadrupedTrait(actor);
  if (!t) return 1;
  const rating = Number(t.system?.rating) || 0;
  if (rating === 1 && isQuadrupedUpright(actor)) return 1;
  return 2;
}
