//  (combat/cover.mjs::coverApForToken), и оно либо накрывало целиком, либо не
//  работало вовсе. «Выглянул из-за стены головой и рукой стрелять — торс и ноги
//  прикрыты, голова и рука нет» выразить было нечем.
//
//  ── Два источника числа и почему БОЛЬШЕЕ, а не сумма ──────────────────────
//  AP укрытия приходит из двух мест: ручное поле на листе (для стола, который
//  не размечает зоны Укрытия на сцене — иначе цифру взять негде вовсе) и
//  разовый бонус ОБЪЯВЛЕННОГО Отскока в укрытие (combat/recoil.mjs пишет флаг,
//  combat/damage.mjs его тратит). Оба описывают ОДНУ И ТУ ЖЕ стену, за которой
//  стоит персонаж, поэтому берётся большее: сумма задвоила бы одно укрытие —
//  тот, кто и стоял за стеной, и нырнул за неё, получил бы двойную защиту.
//
//  ── Чего здесь НЕТ и почему ───────────────────────────────────────────────
//  AP зоны Region в постоянный расчёт не подмешивается. combat/cover.mjs::
//  coverApForToken намеренно НЕ проверяет линию огня, и её шапка объясняет,
//  почему это законно: игрок уже объявил «отскочил в эту зону» сам. Звать её
//  на каждое попадание значило бы дать броню стены и против удара в упор, и
//  против стрелка, стоящего за той же стеной. Зона остаётся автоматической
//  ровно там, где была — в объявленном Отскоке.
//
import { HIT_LOCATIONS } from "../data/actor/_creature.mjs";

/** Отмечена ли хоть одна конечность — иначе укрытие считается общим. */
export function hasCoveredLocations(cover = {}) {
  return HIT_LOCATIONS.some(loc => !!cover?.[loc]);
}

/**
 * AP укрытия, применимый к КОНКРЕТНОЙ локации попадания.
 *
 * @param {object} cover      system.cover актора (ручное поле + галочки)
 * @param {string} location   ключ локации: head/leftArm/rightArm/body/leftLeg/rightLeg
 * @param {number} declaredAp AP из ОБЪЯВЛЕННОГО источника — сейчас это бонус
 *   Отскока в укрытие (0, если Отскока не было)
 * @returns {number} 0, если эта часть тела не прикрыта
 */
export function coverApForLocation(cover = {}, location = "", declaredAp = 0) {
  const ap = Math.max(Number(cover?.ap) || 0, Number(declaredAp) || 0);
  if (ap <= 0) return 0;
  if (!hasCoveredLocations(cover)) return ap;   // укрытие общее — как раньше
  return cover?.[location] ? ap : 0;
}
