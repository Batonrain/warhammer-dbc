import { hasRuleFlag } from "./flags.mjs";

export const EVER_YOUTHFUL_CAPABILITY = "gift.slaanesh.everYouthful";

/** Дисциплины психосил, чьи эффекты Вечно Юный гасит (пока — только Биомантия). */
const PROTECTED_DISCIPLINES = new Set(["biomancy"]);

/** Гасит ли Вечно Юный ЭТУ конкретную силу: дисциплина защищена И цель — носитель Дара. */
export function everYouthfulBlocksPower(targetActor, discipline) {
  if (!PROTECTED_DISCIPLINES.has(String(discipline || "").trim().toLowerCase())) return false;
  return hasRuleFlag(targetActor, EVER_YOUTHFUL_CAPABILITY);
}
