import { LIMB_LOSS_KEYS } from "./limb-loss.mjs";

/** Характеристики, на которые действует «Атака Ненависти». */
export const HATE_ATTACK_CHARS = ["ws", "bs"];

/** Бог актора для способностей: только Хаосит, без Бога — «undivided». */
function patronOf(actor) {
  if (actor?.system?.alignment !== "heretic") return "";
  return actor.system.patronGod || "undivided";
}

/** Покровительство Кхорна у Хаосита — окно атаки предлагает «Атаку Ненависти». */
export function khornePatron(actor) {
  return patronOf(actor) === "khorne";
}

/**
 * Действует ли «Атака Ненависти» на тест по этой Характеристике: только WS/BS.
 * Окно атаки позволяет подменить Характеристику (Локус Мутации и т.п.), поэтому
 * на броске проверяется именно выбранная, а не стартовая.
 * @param {string} charKey  Характеристика теста («ws», «bs»…)
 */
export function hateAttackApplies(charKey) {
  return HATE_ATTACK_CHARS.includes(String(charKey ?? "").toLowerCase());
}

/** Можно ли предложить «Сладкое Страдание» цели Критического Эффекта. */
export function sweetSufferingApplies(actor) {
  return patronOf(actor) === "slaanesh";
}

/**
 * Какие пилюли Критического Эффекта «Сладкое Страдание» НЕ гасит: потеря
 * конечностей и Оглушение. Смерть — не пилюля Состояния (отдельная кнопка
 * «Констатировать смерть»), её способность не трогает вовсе.
 */
export const SWEET_SUFFERING_KEPT = new Set([...LIMB_LOSS_KEYS, "stunned"]);

/**
 * Игнорируется ли эффект с этим ключом Состояния.
 *
 * Кровотечение — исключение из исключения: книга «Потеря конечностей ВСЕГДА
 * приводит к Кровотечению» (combat/crit-effect-parser.mjs кладёт его парой к
 * потере), и если потеря конечности остаётся, остаётся и её Кровотечение.
 * Без потери конечности в карточке Кровотечение — обычный эффект и гасится.
 *
 * @param {string}   condKey  ключ Состояния пилюли
 * @param {string[]} cardKeys ключи ВСЕХ пилюль этой карточки
 */
export function sweetSufferingIgnores(condKey, cardKeys = []) {
  if (SWEET_SUFFERING_KEPT.has(condKey)) return false;
  if (condKey === "bleeding" && cardKeys.some(k => LIMB_LOSS_KEYS.includes(k))) return false;
  return true;
}
