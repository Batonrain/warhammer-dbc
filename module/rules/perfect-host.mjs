//  Идеальный Хозяин / Perfect Host (Дар Нургла, d100 55..58, wdbc-1rno):
//  «Персонаж не страдает от симптомов болезней, которыми он заражён, и НЕ
//  МОЖЕТ БЫТЬ ВЫЛЕЧЕН от болезней. Он может заражаться даже болезнями и
//  паразитами, которые не действуют на его вид. Все болезни, которыми он
//  заражён, имеют общие векторы распространения…»
//
//  Из четырёх обещаний книги движку доступно ровно одно — запрет на
//  излечение, и это не мелочь: снятие болезни в системе есть настоящей
//  кнопкой (✕ в списке БОЛЕЗНИ, sheets/tabs/diseases.mjs), а значит есть
//  что запрещать. Остальные три опираются на то, чего в системе нет:
//   • «не страдает от симптомов» — симптомы у Болезни это свободный текст
//     (module/data/item/disease.mjs: symptoms — строка), движок их не
//     применяет и не считает, гасить нечего;
//   • «может заражаться болезнями, не действующими на его вид» — проверки
//     видовой применимости болезни нет вовсе, запрета не существует, и
//     снимать его не с чего;
//   • «все болезни делят векторы распространения» — векторы тоже текст, и
//     заражение других персонажей движок не моделирует.
//  Все три остаются честным текстом Дара, а не тихой заглушкой.
// ════════════════════════════════════════════════════════════════════════

