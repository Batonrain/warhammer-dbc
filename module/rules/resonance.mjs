//  Резонирующее (Resonant) — свойство оружия, книга «Особые Свойства Оружия».
//
//  «Каждое попадание этого оружия (до нанесения урона) накладывает на цель 1
//  пункт Резонанса до максимума в <Размер цели>+2. Резонанс умножает
//  количество кубиков урона всего оружия с этим свойством (но не бонусных
//  кубиков от других свойств или Талантов) по цели и накладывает на неё штраф
//  −10×Резонанс на все тесты P (−20×Резонанс на тесты Слуха). В конце каждого
//  своего Хода цель теряет 1 пункт Резонанса.»
//
//  Здесь — чистая арифметика. Состояние «Резонанс» (счётчик-уровень на цели) —
//  в constants/conditions.mjs; штраф −10×уровень к Восприятию — правило
//  conditions.resonance (rules/library/conditions.mjs); потеря пункта в конце
//  Хода цели — combat/condition-ticks.mjs; наложение и множитель кубиков —
//  combat/attack.mjs (цель читается тем же приёмом, что у Керамита/Горжета).
// ════════════════════════════════════════════════════════════════════════════

/** Максимум пунктов Резонанса: Размер цели + 2 (не меньше 1 — у Размера −1 и меньше). */
export function resonanceCap(size) {
  return Math.max(1, (Number(size) || 0) + 2);
}

/**
 * Уровень Резонанса цели после `hitNo` попаданий подряд (считая с 1) при
 * стартовом `start`, не выше `cap`.
 */
export function resonanceAfterHits(start, hitNo, cap) {
  return Math.min(Math.max(0, Number(cap) || 0), Math.max(0, Number(start) || 0) + Math.max(0, Number(hitNo) || 0));
}

/**
 * Умножить число кубиков ПЕРВОГО кубикового члена формулы урона на `k`.
 * Фиксированная прибавка и кубики, которых в формуле нет (бонусные кубы
 * Меткого/Рассеивания/Максимального бросаются отдельным Roll), не трогаются.
 * Рвущее/Проверенное: «Nd10min5kh2» — пул растёт вместе с числом отбрасываемых
 * кубов (kh тоже ×k), чтобы «лишний куб, оставить лучший» сохранялся для каждого
 * множителя.
 */
export function multiplyDamageDice(formula, k) {
  const mult = Math.floor(Number(k) || 1);
  const f = String(formula ?? "");
  if (mult <= 1) return f;
  const re = /(\d+)d(\d+)((?:min\d+)?)((?:kh(\d+))?)/;
  const m = f.match(re);
  if (!m) return f;
  const dice = parseInt(m[1], 10) * mult;
  const keep = m[5] != null ? `kh${parseInt(m[5], 10) * mult}` : "";
  return f.replace(re, `${dice}d${m[2]}${m[3]}${keep}`);
}
