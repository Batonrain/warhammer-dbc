import { esc } from "../helpers/utils.mjs";

export const CURSED_HEIRLOOM_MAX_AVAILABILITY = 4;

export const CURSE_TABLE = [
  { roll: 1, key: "bloodlust", name: "Кровожадность",
    text: "Когда персонаж впервые за сессию убивает кого-то этим оружием, он должен провести следующую атаку по трупу." },
  { roll: 2, key: "repulsive", name: "Отталкивающее",
    text: "Персонаж должен перебрасывать первый успешный тест на F в сессию." },
  { roll: 3, key: "contagious", name: "Заразная Неудача",
    text: "Когда персонаж совершает Критический Промах этим оружием, каждый персонаж в радиусе 10м автоматически Критически Промахивается своей первой атакой до начала его следующего Хода." },
  { roll: 4, key: "illFate", name: "Злой Рок",
    text: "Каждый раз, когда персонаж тратит Очки Бесчестия, он бросает d10 – на 1 очко тратится без всякого эффекта." },
  { roll: 5, key: "toxic", name: "Токсичное",
    text: "Персонаж должен перебрасывать первый успешный тест на T в сессию." }
];

/** Проклятье по результату d5 (1-5) — null вне диапазона. */
export function curseForRoll(roll) {
  return CURSE_TABLE.find(c => c.roll === Number(roll)) ?? null;
}

/** «Заметки» оружия (HTML) с дописанным проклятьем — флаг лист предмета не показывает. */
export function notesWithCurse(notes, curse) {
  return `${notes ?? ""}<p><b>Проклятое Наследство — ${esc(curse.name)}:</b> ${esc(curse.text)}</p>`;
}
