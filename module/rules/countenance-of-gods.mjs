//  Общий «остаток» для четырёх Даров «Лик <Бога>» (Countenance of Khorne/
//  Nurgle/Slaanesh/Tzeentch, wdbc-1rno). Базовые социальные бонусы +N уже
//  смоделированы прямыми записями kind:"testMod" на самих предметах — этот
//  файл покрывает то, что у ВСЕХ ЧЕТЫРЁХ описано ОДНИМ и тем же абзацем
//  книги (тот же текст, только с заменой имён Богов):
//
//  1. «Демоны <Бога> рангом ниже Герольда автоматически считают его одним
//     из их рода и признают его авторитет в Командовании, если его Inf 30+
//     и ими не командует кто-то более могущественный.» — ЧЕСТНО НЕ
//     механизируется: Командование в этой системе не гейтит НИКОГО по
//     «готовности слушать» (module/rules/command.mjs решает только КАКИЕ
//     эффекты доходят до типа актора, не «будет ли актор вообще слушаться
//     этого конкретного командира») — обходить нечего, признание
//     авторитета не меняет ни одной цифры теста, это чистое разрешение для
//     стола, снимающее необходимость отдельно спрашивать ГМа.
//
//  2. «За свободное действие персонаж может потратить Очко Бесчестия, чтобы
//     усилить сходство лика с оригиналом до предела, получив рейтинг Страха
//     3 до начала своего следующего Хода. Этот Страх не работает на других
//     <тот же Бог>итов, а <другой конкретный Бог>иты, провалившие тест на
//     Страх от него, вместо бросков на Шок… <особая реакция>».
//
//     Книга не даёт этой способности радиуса/списка целей — это личный
//     рейтинг Страха персонажа (как у Трейта Fear(X)), не волна по площади:
//     придумывать порог обстрела значило бы придумывать за книгу. Тест
//     Страха в этой системе всегда запускается вручную (openFearDialog,
//     module/sheets/tabs/disorders.mjs — числовой рейтинг выбирается игроком/
//     ГМом из выпадающего списка, не читается автоматически ни с одного
//     Трейта нигде в системе, см. также разбор dread-wail.mjs «рейтинг Страха
//     2 до конца боя — не интегрирован в fearRating»).
//
//     Реализовано ТЕМ ЖЕ уровнем автоматизации, что и Dread Wail:
//     реальная трата 1 Очка Бесчестия (не просто текст) + персистентный
//     флаг с полным текстом исключения/особой реакции — готовым для стола,
//     без ручного пролистывания книги. Сам факт применения рейтинга к
//     конкретному тесту Страха остаётся отметкой вручную.
// ════════════════════════════════════════════════════════════════════════

export const COUNTENANCE_FLAG = "countenanceOfGods";
const RATING = 3;

/** Данные по каждому Богу: кого исключает Страх и особая реакция другого Бога. */
export const COUNTENANCE_INFO = {
  khorne: {
    god: "khorne", exclude: "khorne", excludeLabel: "Кхорнитов",
    special: "slaanesh", specialLabel: "Слаанешиты",
    specialText: "вместо бросков на Шок в течение 1 Раунда должны перебрасывать Успехи на любые тесты, кроме атак по персонажу или тестов на то, чтобы убраться от него как можно дальше"
  },
  nurgle: {
    god: "nurgle", exclude: "nurgle", excludeLabel: "Нурглитов",
    special: "tzeentch", specialLabel: "Тзинчиты",
    specialText: "вместо бросков на Шок в течение 1 Раунда должны перебрасывать Успехи на любые тесты, кроме атак по персонажу и тестов на то, чтобы убраться от него как можно дальше"
  },
  slaanesh: {
    god: "slaanesh", exclude: "slaanesh", excludeLabel: "Слаанешитов",
    special: "khorne", specialLabel: "Кхорниты",
    specialText: "вместо бросков на Шок впадают в Ярость"
  },
  tzeentch: {
    god: "tzeentch", exclude: "tzeentch", excludeLabel: "Тзинчитов",
    special: "nurgle", specialLabel: "Нурглиты",
    specialText: "вместо бросков на Шок в течение 1 Раунда должны перебрасывать Успехи на любые тесты, кроме атак по персонажу или тестов на то, чтобы убраться от него как можно дальше"
  }
};

/** Хватает ли персонажу Бесчестия и есть ли он в реестре — общая охрана перед тратой. */
export function countenanceInfoFor(godKey) {
  return COUNTENANCE_INFO[godKey] || null;
}

/**
 * Собрать флаг для actor.setFlag("warhammer-dbc", COUNTENANCE_FLAG, ...).
 * roundHint — номер боевого Раунда каста (Number(game.combat?.round) || null),
 * только для показа в карточке: механического тика по нему нет (см. шапку).
 */
export function buildCountenanceFearFlag(godKey, roundHint = null) {
  const info = countenanceInfoFor(godKey);
  if (!info) return null;
  return {
    rating: RATING,
    god: godKey,
    exclude: info.exclude,
    excludeLabel: info.excludeLabel,
    special: info.special,
    specialLabel: info.specialLabel,
    specialText: info.specialText,
    grantedRound: roundHint,
    restriction: "до начала своего следующего Хода (отметьте вручную — рейтинг Страха этой способности не интегрирован в общий расчёт, тест Страха всегда запускается вручную)"
  };
}
