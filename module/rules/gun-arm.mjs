//
//  Книга (корбук, Элитные архетипы, 400 хр): «Если Одержимый вооружён
//  пистолетом или винтовкой (в т.ч. длинной), ЕЁ втягивает в его предплечье…
//  и ОНО больше не тратит стандартные боеприпасы при выстреле». Речь про ОДНО
//  конкретное оружие — то, что вросло.
//
//  Возможности отвечают только на вопрос «умеет ли ПЕРСОНАЖ»: они висят на
//  акторе. Поэтому проверка «класс pistol|basic И у актора есть
//  weapon.noStandardAmmo» давала бесконечный боезапас ЛЮБОМУ его пистолету и
//  любой винтовке — включая ту, что он только что достал из рюкзака.
//
//  ПРИЁМ ВЗЯТ У «РУКИ СМЕРТИ» (module/rules/hand-of-death.mjs): выбранное
//  оружие несёт метку-флаг, а не актор. Разница только в том, что там метка
//  ставится вместе со свойством fusedLimb и записью АП на руку, а здесь ничего
//  к оружию не добавляется — Дар просто говорит, какое из них вросло.
//
//  ПОЧЕМУ ТОЛЬКО ПАТРОНЫ, А НЕ ВТОРАЯ ПОЛОВИНА ДАРА. Возможность
//  weapon.oneHandedRifle («винтовку можно держать одной рукой») выдаёт не
//  только этот Дар, но и Откатная Перчатка с Подавителями Отдачи — а те по
//  книге работают с ЛЮБОЙ винтовкой, это же перчатка. Гейтить её по вросшему
//  оружию значило бы сломать перчатку ради Дара.
// ════════════════════════════════════════════════════════════════════════════

import { hasRuleFlag } from "./flags.mjs";
import { itemIs } from "./item-marker.mjs";

const FLAG = "warhammer-dbc";

/** Возможность, которую даёт Дар: «не тратит стандартные боеприпасы». */
export const GUN_ARM_CAPABILITY = "weapon.noStandardAmmo";

/** Классы оружия, которые Дар втягивает в предплечье (стр. 171). */
export const GUN_ARM_CLASSES = ["pistol", "basic"];

/** Это предмет-Дар «Рука-Пушка»? */
export function isGunArmGift(item) {
  return itemIs(item, "talent", GUN_ARM_CAPABILITY, "Gun Arm");
}

/** Оружие несёт метку «вросло в предплечье». */
export function isGunArmWeapon(weapon) {
  if (weapon?.type !== "weapon") return false;
  return !!(weapon.getFlag?.(FLAG, "gunArmSource") ?? weapon.flags?.[FLAG]?.gunArmSource);
}

/** Вросшее оружие актора, или null. */
export function gunArmWeaponOf(actor) {
  return [...(actor?.items ?? [])].find(isGunArmWeapon) ?? null;
}

/**
 * Действует ли Дар на ЭТО оружие.
 *
 * Требуется всё сразу: подходящий класс, сам Дар у персонажа и метка именно на
 * этом оружии. Без метки Дар не действует ни на что — и это намеренно: пока
 * ГМ не сказал, какое оружие вросло, книга не даёт бесконечных патронов
 * никакому.
 */
export function gunArmAppliesTo(weapon, actor) {
  if (!actor || !GUN_ARM_CLASSES.includes(weapon?.system?.weaponClass)) return false;
  return hasRuleFlag(actor, GUN_ARM_CAPABILITY) && isGunArmWeapon(weapon);
}
