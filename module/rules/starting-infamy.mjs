// module/rules/starting-infamy.mjs
// ════════════════════════════════════════════════════════════════════════════
//  Стартовое Бесчестие персонажа (корбук стр. 4).
//
//  «Стартовое Inf равно базовому для расы +1d5 при Генерации или +2». База у
//  всех рас книги — 19, отсюда привычное «19 + 1d5»; но берётся она из самой
//  расы, а не вписана числом: раса с другой базой должна считаться правильно.
//
//  Надбавка зависит от способа выдачи Характеристик: у Генерации (бросок 2d10
//  в каждую) она случайная, у распределения — ровно +2, потому что и сами
//  Характеристики там без случайности.
//
//  Архетипы Изгоев и Мореплавателей несут свой бросок Влияния (system.infRoll,
//  вида «3d5+10») — он старше этого правила и заменяет его целиком.
// ════════════════════════════════════════════════════════════════════════════

/** Надбавка при Генерации — формула, а не число: её бросают. */
export const INFAMY_GEN_BONUS = "1d5";

/** Надбавка при распределении Характеристик — фиксированная. */
export const INFAMY_FLAT_BONUS = 2;

/**
 * Формула стартового Бесчестия. Возвращает строку для броска при Генерации и
 * число при распределении — вызывающему остаётся бросить первое и записать
 * второе.
 *
 * @param {number}  base       базовое Бесчестие расы (у книжных рас 19)
 * @param {boolean} generated  Характеристики выданы Генерацией
 */
export function startingInfamyFormula(base, generated = true) {
  const start = Number(base) || 0;
  return generated ? `${start}+${INFAMY_GEN_BONUS}` : start + INFAMY_FLAT_BONUS;
}
