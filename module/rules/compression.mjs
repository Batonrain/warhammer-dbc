//  Сжатие (мутация «Compression», wdbc-1rno): «Когда он получает попадание
//  в конечность или голову и может провести Уклонение от него, он может
//  вместо Уклонения потратить Реакцию и втянуть эту часть тела в торс,
//  нивелируя попадание». Реактивная АЛЬТЕРНАТИВА Уклонению/Парированию, не
//  активируемая способность — потому и не `kind:"script"` на предмете, а
//  своя кнопка рядом с Уклонением/Парированием в карточке атаки
//  (combat/attack-card.mjs::defenseSection, combat/defense.mjs::
//  _performCompression). Модуль сам — чистые функции без Foundry-зависимостей
//  (тот же стиль, что и combat/attack-outcome.mjs), состояние втянутых
//  частей тела хранится списком меток HIT_LOCATIONS (constants/combat.mjs)
//  на акторе (flags.warhammer-dbc.compressedParts), обвязка Foundry-документов
//  — в combat/defense.mjs.
//
//  СОЗНАТЕЛЬНО НЕ АВТОМАТИЗИРОВАНО (честно — не выдумано число, которого нет
//  в тексте, и не переиспользован НЕПОДХОДЯЩИЙ существующий механизм):
//   - «Втянутая голова лишает зрения (но не слуха)» — ослепление в системе
//     уже есть (system.conditions.blinded/blindedRounds,
//     combat/condition-ticks.mjs), но это СЧЁТЧИК РАУНДОВ, тикающий и
//     автоматически снимающийся в начале Хода — механизм для ВРЕМЕННОЙ
//     слепоты по длительности, а не для состояния «пока часть тела не
//     разложена обратно». Подключить его молча значило бы дать персонажу
//     тихо «прозреть» с втянутой головой после N раундов — хуже, чем не
//     сделать вовсе. Отражено только чат-заметкой.
//   - «Втянутые ноги уменьшают мобильность» — книга не называет число (в
//     отличие от, например, Странной Походки: «SPD −2»), значит и здесь не
//     выдумывается — тоже только чат-заметка, штраф на усмотрение ГМа.
//   - Выпуск оружия/инструментов из втягиваемой руки — не отменяет автоматом
//     экипировку (что именно держал персонаж в КОНКРЕТНОЙ руке — вне модели
//     system.equipped), только напоминание в чате.
// ════════════════════════════════════════════════════════════════════════

/** Части тела, которые вообще можно втянуть (HIT_LOCATIONS без «Торс»). */
export const COMPRESSIBLE_LOCATIONS = ["Голова", "П. Рука", "Л. Рука", "П. Нога", "Л. Нога"];

/** «Конечности» в узком книжном смысле пункта «сжав ВСЕ конечности» — без Головы. */
const ARM_LEG_LOCATIONS = ["П. Рука", "Л. Рука", "П. Нога", "Л. Нога"];

/**
 * Метки Избирательной атаки (AIM_LOCATIONS, combat/attack-outcome.mjs,
 * стр. 35) БЕЗ стороны — там атакующий сам называет часть тела («Рука», не
 * «Правая Рука»), книга стороны для Избирательной не вводит вовсе (таблица
 * штрафов стр. 35: Торс/Нога/Рука/Голова/Сочленение/Глаз — без «П.»/«Л.»).
 * Мутация же («Когда он получает попадание в конечность или голову... может
 * ... втянуть эту часть тела» — текст мутации не отличает случайное
 * попадание от Избирательного) хранит втянутые части СО СТОРОНОЙ, как и
 * HIT_LOCATIONS случайного попадания (wdbc-8dyp).
 *
 * Сторона для «Рука»/«Нога» здесь НЕ спрашивается диалогом — проект уже
 * решил тот же вопрос для брони этого же попадания (combat/damage.mjs,
 * LOCATION_TO_ARMOR: «Рука» → rightArm, «Нога» → rightLeg, т.е. по
 * умолчанию правая), это тот же выбор стороны для того же попадания, а не
 * второй, — здесь используется та же конвенция, чтобы Сжатие не спорило
 * с тем, какая рука/нога у этого попадания «на самом деле» пострадала бы
 * от брони, если бы игрок не сжался. «Сочленение / Шея» и «Глаз (Голова)» —
 * оба фактически попадание в голову (там же, LOCATION_TO_ARMOR: оба → head;
 * стр. 35: «Попадание в глаз — это попадание в голову»).
 */
const UNSIDED_TO_COMPRESSIBLE = {
  "Рука":              "П. Рука",
  "Нога":              "П. Нога",
  "Сочленение / Шея":  "Голова",
  "Глаз (Голова)":     "Голова"
};

/** Метка попадания → каноническая метка COMPRESSIBLE_LOCATIONS (см. UNSIDED_TO_COMPRESSIBLE). */
export function normalizeCompressibleLocation(label) {
  return UNSIDED_TO_COMPRESSIBLE[label] ?? label;
}

export function isCompressibleLocation(label) {
  return COMPRESSIBLE_LOCATIONS.includes(normalizeCompressibleLocation(label));
}

/** Новый список втянутых частей после добавления одной (без дублей, метка нормализуется). */
export function retractPart(parts, location) {
  const set = new Set(parts ?? []);
  if (isCompressibleLocation(location)) set.add(normalizeCompressibleLocation(location));
  return [...set];
}

/** Новый список втянутых частей после возврата одной обратно. */
export function extendPart(parts, location) {
  return (parts ?? []).filter(p => p !== location);
}

export function isPartCompressed(parts, location) {
  return (parts ?? []).includes(location);
}

export function hasCompressedHead(parts) {
  return isPartCompressed(parts, "Голова");
}

/** «Сжав все конечности» (стр. текста мутации) — все 4 руки/ноги, Голова не считается. */
export function allLimbsCompressed(parts) {
  const set = new Set(parts ?? []);
  return ARM_LEG_LOCATIONS.every(l => set.has(l));
}
