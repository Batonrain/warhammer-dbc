// module/rules/sundering.mjs
// ════════════════════════════════════════════════════════════════════════
//  Sundering / Разделение (Тзинч, wdbc-1rno, d100 13…15): «Когда чемпион
//  умирает, он может потратить Очко Бесчестия, чтобы его тело исчезло и на
//  его месте появилось две его копии на 1 Размер меньше. Копии имеют 9 Ран,
//  −20 к S и T, Трейты Stuff of Nightmares, Daemonic (+1) и Warp Instability
//  и находятся под контролем персонажа, действуя в его Инициативу. Их
//  снаряжение такое же, как у самого чемпиона, но не соткано из Варпа. Если
//  чемпион поддерживал психосилы или техночудеса, обе его копии поддерживают
//  те же. Урон всех атак копий уменьшает кубики с 1d10 до 1d5 и заменяет
//  1d5 на 1. В конце сцены обе копии исчезают и на месте одной из них (по
//  выбору персонажа) возникает он сам с 0 Ран. Если обе копии убиты или
//  изгнаны, это считается как смерть персонажа как обычно и её можно
//  избегать обычными способами.»
//
//  «Снаряжение такое же» реализовано ШИРЕ буквы книги — копируется ВЕСЬ
//  список предметов чемпиона (не только оружие/броня), а не только
//  «снаряжение» узко. Так же бесплатно решается «поддерживал психосилы или
//  техночудеса — копии поддерживают те же»: поддерживаемые psychicPower/
//  navigatorPower — тоже предметы в этом списке, isSustained/
//  sustainedDegree/sustainedTargetUuid копируются вместе с самим предметом
//  без отдельного шага (module/combat/sundering.mjs::spawnSunderingCopies).
//  Разделять «снаряжение» и «остальные предметы» здесь означало бы
//  создавать копии без Талантов/Черт, от которых их же боевые числа зависят
//  — читерский разрыв книге не нужен, полная копия честнее.
//
//  «Техночудеса» отдельно от психосил книга упоминает как поддерживаемые —
//  в системе у type:"techPower" (module/data/item/tech-power.mjs) НЕТ поля
//  isSustained вовсе (есть только у psychicPower/navigatorPower) — то есть
//  «поддерживаемое техночудо» в этой системе не отслеживается НИГДЕ, не
//  только у Разделения: копировать нечего, состояния для этого не
//  существует. Честный предел архитектуры, не сокращение находки.
//
//  «Не соткано из Варпа» — свойства «сотканности из Варпа» у оружия/брони в
//  системе тоже нет ни одного поля (только текст описаний), чисто
//  нарративная деталь без числового следа.
//
//  Урон копий (1d10→1d5, 1d5→1) — тот же ДВУХСТУПЕНЧАТЫЙ даунгрейд, что уже
//  умеет combat/through-shot.mjs::throughShotReductionDie (та же прогрессия
//  d10→d5→флэт), только не цепочкой попаданий, а постоянным свойством
//  атакующего: sunderingDamageFormula переписывает ОБА уровня сразу в
//  формуле одним проходом.
// ════════════════════════════════════════════════════════════════════════

export const SUNDERING_CAPABILITY = "gift.tzeentch.sundering";

/** Флаг на КОПИИ — сама копия и её сиблинг/чемпион (для отката в конце сцены). */
export const SUNDERING_COPY_FLAG = "sunderingCopy";

/** Флаг на ЧЕМПИОНЕ — какие копии сейчас за него действуют + был ли скрыт его токен. */
export const SUNDERING_ACTIVE_FLAG = "sunderingActive";

/** Штраф S/T копии (стр. книги: «−20 к S и T»), не уводит характеристику ниже 0. */
const CHAR_PENALTY = 20;

/**
 * Данные system копии — глубокая копия system чемпиона с книжными правками:
 * −20 S/T (в `base`, чтобы производный `total` пересчитался сам той же
 * формулой, что и всегда — не трогаем total напрямую, он не хранится),
 * 9 Ран (полностью, не «максимум 9» — копия только что возникла целой),
 * Размер −1.
 */
export function sunderingCloneSystem(championSystem) {
  const sys = foundry.utils.deepClone(championSystem ?? {});
  sys.characteristics ??= {};
  for (const key of ["s", "t"]) {
    sys.characteristics[key] ??= {};
    const base = Number(sys.characteristics[key].base) || 0;
    sys.characteristics[key].base = Math.max(0, base - CHAR_PENALTY);
  }
  sys.wounds = { value: 9, max: 9, critical: 0 };
  sys.size = (Number(sys.size) || 0) - 1;
  return sys;
}

/** Данные трёх Трейтов, которые получает каждая копия — сами по себе честные заглушки (см. шапку). */
export function sunderingCloneTraits() {
  return [
    { name: "Stuff of Nightmares / Материал Кошмаров", type: "trait",
      system: { benefit: "Материя копии соткана из кошмаров Варпа, не из плоти.", hasRating: false } },
    { name: "Daemonic (+1) / Демонический (+1)", type: "trait",
      system: { benefit: "Демоническая природа копии.", hasRating: true, rating: 1 } },
    { name: "Warp Instability / Варп-нестабильность", type: "trait",
      system: { benefit: "Копия соткана из Варпа временно — исчезает в конце сцены.", hasRating: false } }
  ];
}

/**
 * Урон копий: 1d10→1d5, затем (в том же проходе, включая только что
 * понижённые) 1d5→плоское число, равное количеству костей. «NdX» с любым N
 * (не только 1) — книжный пример «1d5→1» обобщается на N костей → N очков,
 * не одну общую единицу (естественное обобщение, других формул книга не даёт).
 */
export function sunderingDamageFormula(formula) {
  if (!formula) return formula;
  // (?!\d) — иначе «1d10» ловит «d10» и ВНУТРИ «1d100», обрезая его до «10».
  let f = String(formula).replace(/(\d*)d10(?!\d)/gi, (_, n) => `${n || 1}d5`);
  f = f.replace(/(\d*)d5(?!\d)/gi, (_, n) => `${n || 1}`);
  return f;
}
