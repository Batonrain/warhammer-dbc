import { sightGrants, SIGHT_EFFECT } from "./sight-effects.mjs";

/** Штраф теста Внимательности по книге: «Awareness–10». */
export const LASER_DOT_TEST_MOD = -10;

/** Сколько строк карточки получают свою общую отметку «тест уже брошен» (ключи laserSpot0…N в card-once.mjs). */
export const LASER_SPOT_ROWS = 20;

/** Выдаёт ли действующий прицел точку лазера (Лазерный и Омни-Прицел, rules/sight-effects.mjs). */
export const hasLaserDot = activeMods => !!sightGrants(activeMods, SIGHT_EFFECT.laserDot);

/** Слать ли ГМу шёпот про точку: дальнобойная атака + точка лазера. */
export const laserDotOffered = ({ isMelee, laserDot }) => !isMelee && !!laserDot;

/**
 * База теста Внимательности врага: итог Навыка (с Тренировкой), а если записи
 * Навыка нет — Восприятие. Без модификатора −10 — он добавляется отдельной ячейкой.
 */
export function awarenessBase(actor) {
  const total = actor?.system?.skills?.awareness?.total;
  if (Number.isFinite(total)) return total;
  return Number(actor?.system?.characteristics?.per?.total) || 0;
}
