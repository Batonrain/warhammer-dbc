//  Blessed Fits / Благословенные Припадки (Общие Мутации, wdbc-1rno, d100
//  15): «Когда персонаж тратит Очко Бесчестия на Переброс и переброшенный
//  тест оказывается провалом, он Оглушается на 1 Раунд, но если он проводит
//  полный Раунд в Оглушении, по завершении Раунда он восстанавливает
//  потраченное Очко Бесчестия.»
//
//  Переброс за Очко Бесчестия — не Преимущество/Помеха (roll-advantage.mjs/
//  reroll-pick.mjs, те бесплатны и от Таланта), а отдельная жёстко зашитая
//  кнопка контекстного меню карточки чата (module/hooks.mjs::
//  _attachFateContextMenu, btnReroll) — единственное место, где расход
//  Очка и исход переброшенного теста видны рядом. Реализовано ТОЛЬКО для
//  обычного теста Навыка/Характеристики (там `hit` — готовый булев прямо в
//  обработчике); переброс АТАКИ повторяет `_executeAttackRoll` целиком
//  (1700+ строк, без возврата исхода наружу) — тот же честный предел, что
//  уже фиксирует rules/eye-of-envy.mjs для встречного теста своей находки:
//  не трогаем гигантскую функцию ради одной ветки одной находки.
//
//  «Полный Раунд в Оглушении» — Оглушение тикает вниз в НАЧАЛЕ Хода
//  носителя (combat/condition-ticks.mjs::processConditionTurnStart,
//  constants/conditions.mjs::stunned, счётчик "rounds"). Даётся 1 Раунд —
//  значит его снятие естественным декрементом (до 0, не снятое раньше
//  каким-то другим способом — «встряхнулся» и т.п.) И ЕСТЬ «провёл полный
//  Раунд в Оглушении»: если Оглушение сняли раньше срока, декремент до 0
//  в этой функции просто не наступит, а если наступит — прошёл ровно
//  заявленный книгой полный срок. Возврат Очка стоит на ЭТОМ декременте
//  (тот же файл, тот же цикл ROUND_TICK_CONDITIONS), метку — флаг на
//  акторе, которого больше ни для чего в системе не существует.
// ════════════════════════════════════════════════════════════════════════

export const BLESSED_FITS_CAPABILITY = "mutation.blessedFits";

/** Флаг на акторе — списанное на переброс Очко Бесчестия ждёт возврата. */
export const BLESSED_FITS_PENDING_FLAG = "blessedFitsPendingRefund";

/** Пора ли вернуть Очко — Оглушение только что естественно дошло до 0, и метка ещё стоит. */
export function blessedFitsRefundDue(pendingFlag, nextStunnedRounds) {
  return !!pendingFlag && Number(nextStunnedRounds) <= 0;
}
