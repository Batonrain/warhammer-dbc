import { itemHasName } from "./predicates.mjs";

export const VOLUNTEER_ACTOR_CAPABILITY = "talent.volunteerActor";

/** Оружие «Поцелуй Арлекина» (любой формы имени — русская половина без спецсимволов). */
export function isHarlequinsKissItem(item) {
  return item?.type === "weapon" && itemHasName(item, "Поцелуй Арлекина");
}

const HOUR = 3600;
export const MIMIC_WIRE_SURGERY_DURATION = 16 * HOUR;
export const MIMIC_WIRE_SURGERY_FLAG = "mimicWireSurgeryEndsAt";

/** Дедлайн хирургического извлечения — 16 игровых часов от момента начала операции. */
export function scheduleMimicWireSurgery(worldTime) {
  return Number(worldTime) + MIMIC_WIRE_SURGERY_DURATION;
}

/** Прошли ли уже 16ч операции. */
export function isMimicWireSurgeryReady(deadline, worldTime) {
  return deadline != null && Number(worldTime) >= Number(deadline);
}
