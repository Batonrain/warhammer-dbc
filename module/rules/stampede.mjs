// module/rules/stampede.mjs
// ═══════════════════════════════════════════════════════════════════════════
//  Stampede / Затоптать — корбук, глава «Трейты»: «Это существо реагирует на
//  страх безумной скачкой. Когда оно проваливает любой тест на W, оно сразу же
//  перемещается прямо вперёд на расстояние Натиска, совершая Напролом против всех
//  на его пути. Все персонажи на его пути (как друзья, так и враги) получают по
//  одному попаданию его естественным оружием. Если одно существо с этим Трейтом
//  проваливает тест на W, все остальные существа с этим Трейтом, которые его
//  видят, тоже должны пройти тест на W+0, или начинают нестись в том же
//  направлении, затаптывая всех на своем пути.»
//
//  Реализовано (dbc-114 / 55-15, 13.11.2026, решение владельца) ТОЛЬКО как
//  подсказка Мастеру в карточке проваленного теста Страха (combat/fear.mjs): сам
//  сдвиг токена, Напролом и цепная реакция не автоматизированы — тесты Воли
//  бросаются в десятках мест кода, общего места нет, а движение чужого токена не
//  в его Ход система не умеет.
// ═══════════════════════════════════════════════════════════════════════════

import { itemHasName } from "./predicates.mjs";

/** Есть ли у актора Черта Затоптать. */
export function hasStampede(actor) {
  return [...(actor?.items ?? [])].some(i => i?.type === "trait"
    && (itemHasName(i, "Stampede") || itemHasName(i, "Затоптать")));
}

/**
 * Строка-подсказка для карточки проваленного теста Воли у носителя Трейта;
 * пустая строка, если Трейта нет.
 */
export function stampedeNoteHtml(actor) {
  if (!hasStampede(actor)) return "";
  return `<div class="roll-threshold" style="margin-top:4px;">🐃 <b>Затоптать:</b> тест Воли провален — существо сразу `
    + `несётся прямо вперёд на дистанцию Натиска, Напролом против всех на пути (и друзья, и враги — по одному `
    + `попаданию естественным оружием). Остальные существа с этим Трейтом, видящие его, проходят тест W+0, `
    + `иначе бегут в ту же сторону. Движение и попадания считает Мастер.</div>`;
}
