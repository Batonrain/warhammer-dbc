/** Перевертыш считается женщиной для Полиморфина: A+20 (мужской вариант книги — A−10). */
export const SHAPESHIFT_MOD = 20;

export const SHAPESHIFT_STEPS = [
  { min: 1, text: "цвет и тонус кожи и цвет глаз, исказить свой голос" },
  { min: 2, text: "цвет волос, чужой голос, форма лица чуть отличная от своей" },
  { min: 3, text: "лицо на лицо человека того же пола, сменить размер на +/– 10%" },
  { min: 4, text: "форму тела на человека того же пола, размер +/– 20%" },
  { min: 5, text: "форму тела и лицо на другой пол, размер +/– 40%" },
  { min: 7, text: "форму тела и лицо на гуманоидного ксеноса того же Размера с тем же количеством конечностей" }
];

/**
 * Строка таблицы для числа Успехов теста — наибольший достигнутый порог, либо
 * null (провал / 0 Успехов: облик не меняется).
 * @param {number} successes
 * @returns {{min:number, text:string}|null}
 */
export function shapeshiftStep(successes) {
  const n = Number(successes) || 0;
  let hit = null;
  for (const s of SHAPESHIFT_STEPS) if (n >= s.min) hit = s;
  return hit;
}
