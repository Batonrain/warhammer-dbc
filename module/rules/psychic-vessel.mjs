//  Общий примитив «через кого сейчас манифестирует псайкер» (wdbc-q30d).
//  До этой правки единственным местом, где такое понятие вообще
//  упоминалось, был Путь Силы "familiar" (module/constants/psyker.mjs,
//  PSY_PATHS.familiar) — чисто текстовая заметка «Дальность считается от
//  фамильяра», без единого байта данных, связывающих псайкера с конкретным
//  актором фамильяра. Spirit Talk/Духовный Разговор (module/combat/
//  spirit-talk.mjs) — второй, независимый случай той же потребности
//  («персонаж может манифестировать психосилы... через конструкт»), и два
//  случая уже оправдывают общий примитив (не один, как в большинстве
//  находок Категории D wdbc-1rno, где заводить новое ради одной находки
//  было НЕ оправдано).
//
//  Ссылку хранит ПСАЙКЕР (тот же приём, что system.mount.uuid у всадника,
//  module/data/actor/_creature.mjs — «кто на ком» всегда однозначно с одной
//  стороны) — но как ФЛАГ, а не поле схемы: значение целиком программное
//  (никогда не редактируется формой листа напрямую, в отличие от
//  system.mount), схема/миграции/шаблон ради него разводить не нужно.
//
//  Это НЕ автоматизация дальности психосилы — dialог манифестации
//  (sheets/tabs/psychic.mjs) вообще не мерит дистанцию нигде, «Дальность:
//  PR×10 метров» у психосил — только текстовая подсказка игроку/ГМу
//  (sys.range), даже для собственной позиции кастера. Этот модуль только
//  ДАЁТ имя текущего носителя тем местам, что уже показывают заметку —
//  сама механика измерения псионической дальности остаётся вне рамок
//  (заводить её только ради этой находки, когда её нет даже для базового
//  случая, было бы новым примитивом непропорционального масштаба).
// ════════════════════════════════════════════════════════════════════════

const FLAG = "psychicVessel";

/** Кто сейчас служит псайкеру носителем манифестации (или null). */
export function getPsychicVessel(actor) {
  return actor?.getFlag?.("warhammer-dbc", FLAG) ?? null;
}

/** Назначить носителя — Spirit Talk на захват, ритуал/бондинг фамильяра на связывание. */
export async function setPsychicVessel(psykerActor, vesselActor, { label } = {}) {
  if (!psykerActor || !vesselActor) return;
  await psykerActor.setFlag("warhammer-dbc", FLAG, {
    uuid: vesselActor.uuid ?? null, name: label ?? vesselActor.name ?? ""
  });
}

/** Снять носителя — конец захвата/боя, разрыв связи с фамильяром и т.п. */
export async function clearPsychicVessel(psykerActor) {
  if (!psykerActor) return;
  await psykerActor.unsetFlag("warhammer-dbc", FLAG);
}
