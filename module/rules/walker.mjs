/**
 * Стоимость «пилот использует ВСЁ оружие машины — дальнее и ближнее — в один
 * Ход, как если бы у него был Трейт Multiple Arms достаточного рейтинга»
 * (п.6).
 *
 * Трейт Multiple Arms в системе НЕ даёт лишних атак — он даёт БЮДЖЕТ РУК на
 * удержание оружия (module/rules/hands.mjs, прямая оговорка в шапке: «rating
 * Трейта — уже ПОЛНОЕ число рук»). Переиспользовать оттуда, стало быть,
 * нечего: в книге фраза значит «рук хватает на все стволы разом», а в цене
 * действий это ровно то же, что уже умеет Залп (combat/vehicle.mjs::
 * resolveVolleyAction) — ОДНО полное действие оператора на всю станцию.
 * Разница только в охвате: Залп ограничен станцией и требует Черты
 * «Продвинутые Прицельные Системы», а Шагоходу книга даёт то же самое даром
 * и на ВСЮ машину.
 *
 * Чего это НЕ делает (осознанно, не забыто): не режет число выстрелов из
 * одного ствола, не считает штрафов за атаку несколькими руками (стр. 32) и
 * не запрещает выстрелить одним и тем же орудием дважды — учёта «выстрелов на
 * ствол за Ход» у техники нет вовсе (см. combat/vehicle.mjs, заметки
 * Мультиприцела), и подделывать его здесь значило бы обещать проверку,
 * которой нет.
 */
export const WALKER_ALL_ARMS_ACTION = "Полное действие";
