/** Значение chassis.type, при котором машина — Шагоход (constants/vehicle.mjs). */
export const WALKER_CHASSIS = "walker";

/** Имя «раз-в-Раунд» возможности поворота вне Хода (rules/cooldown.mjs). */
export const WALKER_TURN_CAPABILITY = "walker.turnAbout";

/** Бонус рукопашного приёма машины за объявленный Натиск (стр. 13, как у персонажа). */
export const WALKER_CHARGE_BONUS = 20;

/** Метка состояния «Опрокидывание» — та же строка, что у VEHICLE_STATUS_EFFECTS. */
export const TIP_OVER_LABEL = "Опрокидывание";

/**
 * Кто «за рулём» Шагохода. Порядок именно такой: Уклонение книга привязывает
 * к Operate (это мехвод), а «атакует как персонаж» — к тому, кто машиной
 * управляет. У Дредноута место называется `pilot` (rules/dreadnought.mjs),
 * у прочих шагоходов в паках чаще `driver`; командир — последний разумный
 * запасной вариант, стрелок машиной не правит.
 */
export const WALKER_CREW_ROLES = ["pilot", "driver", "commander"];

const norm = v => String(v ?? "").trim().toLowerCase();
const num  = v => Number(v) || 0;

/** Шагоход ли это (актор техники с шасси walker). */
export function isWalkerVehicle(actorData) {
  if (actorData?.type !== "vehicle") return false;
  return norm(actorData.system?.chassis?.type) === WALKER_CHASSIS;
}

/**
 * Штраф Шагохода на Парирование и Уклонение: −Размер×10 (п.5).
 *
 * Та же формула, что у Виража (rules/vehicle.mjs::swerveMod), и это не
 * совпадение: книга одинаково штрафует машину за габариты в любом Избегании.
 * Отдельная функция всё равно нужна — swerveMod несёт ещё и «гусеничная −10»,
 * которой у Шагохода не бывает по определению.
 */
export function walkerDefenceMod(size) {
  return -num(size) * 10;
}

/**
 * Пороги Уклонения Шагохода (п.5): «Уклонение всегда комбинированное с
 * Operate−10».
 *
 * Комбинированный тест — корбук, стр. 25: «персонаж определяет Пределы для
 * всех вовлеченных Навыков и выбирает наименьший из них», ОДИН бросок против
 * него (rules/test-kind.mjs::combinedThreshold). Второй способ, живущий в
 * combat/mount.mjs (два броска, оба должны пройти), книге не соответствует —
 * расхождение зафиксировано отдельной бидой, здесь взят книжный.
 *
 * −Размер×10 ложится ТОЛЬКО на половину Уклонения: книга называет два разных
 * модификатора («со штрафом −Размер×10» и «с Operate−10»), а не один общий.
 *
 * @param {{dodgeBase:number, size:number, operate:number}} p
 * @returns {{dodgePart:number, operatePart:number, threshold:number}}
 */
export function walkerDodgeThresholds({ dodgeBase = 0, size = 0, operate = 0 } = {}) {
  const dodgePart   = num(dodgeBase) + walkerDefenceMod(size);
  const operatePart = num(operate) - 10;
  return { dodgePart, operatePart, threshold: Math.min(dodgePart, operatePart) };
}

/**
 * Сколько раз за Раунд Шагоход может повернуться на до 180° ВНЕ своего Хода
 * (п.8): обычно один раз, а пилоту с Талантом Combat Master — до ½WS.b
 * (окр. вверх) раз.
 *
 * Не меньше одного даже при WS.b 0-1: Талант книга даёт как усиление, и
 * ½ от единицы, округлённая вверх, это и есть один — но при WS.b 0 формула
 * дала бы ноль, то есть Талант ОТНИМАЛ бы возможность. Пол в единицу.
 */
export function walkerTurnsPerRound({ combatMaster = false, wsBonus = 0 } = {}) {
  if (!combatMaster) return 1;
  return Math.max(1, Math.ceil(Math.max(0, num(wsBonus)) / 2));
}

/** Узнаём Талант Combat Master / Мастер Боя среди предметов пилота. */
const COMBAT_MASTER_MATCH = /Combat Master|Мастер Боя/i;
export function hasCombatMasterTalent(items) {
  return (items || []).some(i => i?.type === "talent" && COMBAT_MASTER_MATCH.test(i.name || ""));
}

/**
 * Дистанция Натиска Шагохода (п.1: «двигается как персонаж… включая Натиск»).
 * Персонажный Натиск — SPD×3, не менее 4 м (combat/movement-actions.mjs).
 * Книга переопределяет Шагоходу только БЕГ (4×SPD вместо 6×SPD, п.3), про
 * Натиск не говорит ничего — значит, действует общее правило персонажа.
 */
export function walkerChargeDistance(spd) {
  return Math.max(4, num(spd) * 3);
}

/**
 * Метка объявленного Натиска: бой и Раунд, в которых он объявлен. Своё поле, а
 * не usageLimits (rules/cooldown.mjs): та плоскость отвечает на вопрос
 * «сколько раз потрачено», а здесь нужен факт «в этом Раунде объявлен» —
 * счётчиком его не выразить, а смешивать плоскости хуже, чем завести своё.
 */
export function walkerChargeMark({ combatId = "", round = 0 } = {}) {
  return { combat: String(combatId || ""), round: num(round) };
}

/**
 * Действует ли объявленный Натиск сейчас. Вне боя (round 0 и пустой combatId)
 * метка живёт до следующего объявления: считать Раунды нечем, и гасить бонус
 * молча значило бы отнимать у стола то, что он только что объявил.
 */
export function isWalkerChargeActive(mark, { combatId = "", round = 0 } = {}) {
  if (!mark) return false;
  const markRound = num(mark.round);
  const nowRound  = num(round);
  if (!nowRound) return true;                       // боя нет — метка не истекает сама
  if (String(mark.combat || "") !== String(combatId || "")) return false;
  return markRound === nowRound;
}

// ── Опрокидывание (п.2) ─────────────────────────────────────────────────────
// VEHICLE_STATUS_EFFECTS, «Опрокидывание»: «Шагоход падает (в случайную
// сторону, если не от направленного толчка): <Размер>d10 урона в
// приземлившуюся сторону (АР вдвое ниже, окр.▲). С уступа +1 урон за каждые
// ½ м. Экипаж T+0 или Оглушение на 1 Раунд. Встаёт за полное действие (Leap
// Up — за полудействие)».

/**
 * Что происходит с этой машиной вместо Сбивания с Ног (п.2). Отдельная
 * функция, а не `if (walker)` на месте: сегодня ни один путь наложения
 * `prone` до актора-техники не доходит (у vehicle нет system.conditions
 * вовсе), но как только такой путь появится, он обязан спросить здесь, а не
 * завести вторую копию правила.
 *
 * @returns {"tipOver"|"prone"}
 */
export function knockdownOutcomeFor(actorData) {
  return isWalkerVehicle(actorData) ? "tipOver" : "prone";
}

/** Формула урона Опрокидывания: <Размер>d10 (Размер меньше 1 — всё равно 1d10). */
export function tipOverDamageFormula(size) {
  return `${Math.max(1, num(size))}d10`;
}

/** АР приземлившейся стороны при Опрокидывании: вдвое ниже, окр. ▲. */
export function tipOverArmour(ap) {
  return Math.ceil(Math.max(0, num(ap)) / 2);
}

/** Падение с уступа: +1 урона за каждые полметра высоты (неполные не считаются). */
export function tipOverLedgeBonus(metres) {
  return Math.floor(Math.max(0, Number(metres) || 0) / 0.5);
}

/** Лежит ли машина Опрокинутой (состояние в system.damageStates). */
export function isTippedOver(actorData) {
  return (actorData?.system?.damageStates || [])
    .some(s => String(s?.label || "") === TIP_OVER_LABEL);
}

