//  Здесь — арифметика тех пунктов, которые считаются, а не пересказываются:
//
//    п.1 «двигается и атакует как персонаж, включая Натиск» — дистанция
//        Натиска и метка «Натиск объявлен в этом Раунде»;
//    п.2 «вместо сбивания с ног — Опрокидывается» — исход толчка и числа
//        самого Опрокидывания (урон по Размеру, ополовиненная АР, уступ);
//    п.5 «Парирование/Уклонение со штрафом −Размер×10, Уклонение всегда
//        комбинированное с Operate−10» — оба Порога;
//    п.6 «пилот использует всё оружие машины в один Ход» — сколько действий
//        это стоит;
//    п.8 «раз в Раунд вне своего Хода поворот до 180°, с Combat Master — до
//        ½WS.b раз» — лимит поворотов на Раунд.
//
//  Почему отдельный файл, а не rules/vehicle.mjs: тот считает ПРОИЗВОДНЫЕ
//  листа (SPD, Маневрирование, Структура) на каждом пересчёте актора, а это —
//  боевые правила одного шасси, которые спрашивают в момент действия. Мешать
//  их значило бы гонять расчёт Шагохода на каждом обновлении любой машины.
//
//  Foundry здесь нет намеренно (AGENTS.md, «Тесты»): всё проверяется без
//  заглушки, а обвязка — module/combat/walker.mjs.
