// ════════════════════════════════════════════════════════════════════════
//  Touch of Pain / Касание Боли (Дар Слаанеш, d100 30..33, wdbc-1rno):
//  «Его безоружные атаки и атаки естественным оружием игнорируют T.b в
//  Поглощении живых целей и получают свойство Shocking, но Критические
//  Эффекты от них никогда не убивают цель или повреждают её части тела,
//  игнорируя эти результаты.»
//
//  «Безоружные атаки и атаки естественным оружием» — та же плоскость
//  данных, что уже использовал Touch of Entropy (Дар Нургла, тот же тикет):
//  предметы с флагом integralAttack (combat/equipped-melee.mjs::
//  isIntegralAttack) — Кулак/Пинок и природное оружие (Хвост/Клыки и т.п.)
//  заведены такими же предметами.
//
//  «Живых целей» — НЕ различается: в системе нет классификатора
//  живое/неживое (демоны/техника/конструкты — те же Actor-документы с тем
//  же T). Применяется шире буквы книги — тот же класс компромисса, что уже
//  документирован у Fully Armed/Gift of Tongues (честно ширее, не уже).
//
//  Свойство Shocking добавляется СИНТЕТИЧЕСКИ в список свойств этого
//  конкретного выстрела (module/combat/attack.mjs, тот же приём, что уже
//  даёт splinterFullAutoTearing для Tearing при полном автообстреле
//  осколочным) — НЕ записывается в сам предмет Кулака/Пинка, иначе Shocking
//  получили бы вообще все персонажи с голыми руками, а не только носитель
//  Дара.
//
//  «Критические Эффекты никогда не убивают/не калечат» — ЧЕСТНО НЕ
//  смоделировано: Критические Эффекты в системе — свободный текст
//  (combat/crit-effect-parser.mjs), автоматической подмены исхода на
//  «менее тяжёлый» нет ни у одного другого источника в системе.
// ════════════════════════════════════════════════════════════════════════

import { hasRuleFlag } from "../rules/flags.mjs";
import { isIntegralAttack } from "./equipped-melee.mjs";

export const TOUCH_OF_PAIN = "gift.slaanesh.touchOfPain";

/** Активна ли находка для ЭТОЙ конкретной атаки — Дар есть и удар безоружный/природный. */
export function touchOfPainActive(actor, item) {
  if (!actor || !hasRuleFlag(actor, TOUCH_OF_PAIN)) return false;
  if (item && !isIntegralAttack(item)) return false;
  return true;
}
