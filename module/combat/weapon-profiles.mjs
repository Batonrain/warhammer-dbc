// ════════════════════════════════════════════════════════════════════════════
//  ПРОФИЛИ ОРУЖИЯ: авторские плюс выводимые (wdbc-bs0q).
//
//  «Профиль» в этой системе уже есть и работает: system.profiles — список
//  {label, range, damage, damageType, penetration, weaponProps}, из которого
//  окно атаки строит выпадающий список, а HUD — переключатель. Заполняется он
//  из текста оружия миграцией (module/migrations/weapon-grips.mjs).
//
//  ── Что здесь появилось и зачем ──────────────────────────────────────────
//  Удар стрелковым оружием в упор (корбук стр. 40) до этого профилем НЕ был.
//  Он жил отдельной кнопкой HUD и открывал СИНТЕТИЧЕСКУЮ безоружную атаку
//  (_showAttackDialogNoWeapon) — то есть формально это была не атака этим
//  оружием, а отдельный ход в обход всей оружейной машинерии: без выбора Хвата
//  и Стойки, без Тренировки по категории, без свойств самого предмета.
//
//  Теперь это обычный профиль, выводимый из класса оружия. Данных на 891
//  предмет паков не потребовалось: таблица книги короткая и целиком выражается
//  через weaponClass, поэтому профиль СЧИТАЕТСЯ, а не хранится.
//
//  ── Признак `melee` ──────────────────────────────────────────────────────
//  Профилю понадобилось новое поле: до этого «рукопашная это или стрельба»
//  решалось по предмету целиком (weaponClass === "melee"), и рукопашный
//  профиль у винтовки всё равно бросался бы по BS. Поле необязательное — все
//  авторские профили без него ведут себя ровно как раньше.
// ════════════════════════════════════════════════════════════════════════════

const SYSTEM = "warhammer-dbc";

// «Закреплено ли оружие» считает combat/brace-weapon.mjs по геометрии токена —
// а это цепочка импортов до Foundry (facing → regions), которую этот чистый
// модуль тянуть не должен: его грузят HUD, окно атаки и тесты без сцены.
// brace-weapon.mjs регистрирует свою проверку сам при загрузке; без неё
// (тесты) оружие считается незакреплённым.
let braceCheck = () => false;
export function registerBraceCheck(fn) { braceCheck = typeof fn === "function" ? fn : () => false; }

/**
 * Импровизированная рукопашная по классу оружия (корбук стр. 40).
 *
 * Таблица книги (core.json, «Безоружный Бой»):
 *
 *   Пистолет      1р Булава 1   1d5–2  I(Cr) Bl −1
 *   Винтовка      2р Посох  2-3 1d10–2 I(Cr) Bl −1
 *   Дл. винтовка  2р Посох  2-4 1d10–2 I(Cr) Bl −1
 *   Тяж. оружие   2р Булава 3   2d10–4 I(Cr) Bl −2
 *
 * всем Pen 0, Imprecise + Primitive; «Все атаки стрелковым оружием, использующим
 * эти профили, получают штраф –10, который увеличивается до –20 для тяжелого
 * оружия» — поле attackMod (окно атаки читает его отдельной строкой порога).
 * Баланс — поле balance: у ствола свой system.balance про стрельбу не пишется
 * вовсе, а рукопашной нужен книжный (Парирование, Стойки/Приёмы с минимумом).
 *
 * «Дл. винтовка» — не класс, а свойство longRifle на предмете (тип «дл.
 * винтовка» в таблицах Арсенала), тот же признак, что запрещает из неё
 * стрелять в рукопашной.
 *
 * Числа сверены с книгой в wdbc-x1nz.2: до этого стояли −3/−3 и 3→2 м,
 * унаследованные из старой кнопки HUD, а не из книги.
 *
 * ── ПОЧЕМУ В СТРОКЕ НЕТ «+S.b» ──────────────────────────────────────────
 * Прежнее описание удара в упор писало ИТОГ («1d5-3+S.b»), а система записывает урон рукопашного БЕЗ
 * бонуса Силы и прибавляет его сама: combat/attack.mjs::flatBonus добавляет
 * sbEff каждой рукопашной атаке. Так записаны все рукопашные предметы и все
 * авторские рукопашные профили паков — у меча «1d10+2», у профиля «Посох»
 * «2d10+4», ни у одного нет «+S.b».
 *
 * Первая версия несла «+S.b» в строке, скопированный из прежнего описания
 * удара в упор, и живая проверка поймала следствие: Сила прибавлялась ДВАЖДЫ
 * (S.b=3 давало 1d10-3+3+3 вместо 1d10-3+3). Возвращать «+S.b» «чтобы было как
 * в книге» нельзя — это удвоение, а не точность.
 */
const HEAVY_ROW = { damage: "2d10-4", like: "Булава", range: "3 м", balance: -2, attackMod: -20, heavy: true };
const IMPROVISED_BY_CLASS = {
  pistol:     { damage: "1d5-2",  like: "Булава", range: "1 м",   balance: -1, attackMod: -10 },
  basic:      { damage: "1d10-2", like: "Посох",  range: "2–3 м", balance: -1, attackMod: -10 },
  heavy:      HEAVY_ROW,
  launcher:   HEAVY_ROW,
  stationary: HEAVY_ROW
};
const IMPROVISED_LONG_RIFLE =
              { damage: "1d10-2", like: "Посох",  range: "2–4 м", balance: -1, attackMod: -10 };

/** Класс, не названный в книге поимённо, бьёт как винтовка — прежнее умолчание. */
const IMPROVISED_FALLBACK = IMPROVISED_BY_CLASS.basic;

function hasLongRifleProp(sys) {
  return (sys?.weaponProps || []).some(p => (p?.key ?? p) === "longRifle");
}

/** Строка таблицы книги для этого ствола. */
function improvisedRow(sys) {
  if (sys?.weaponClass === "basic" && hasLongRifleProp(sys)) return IMPROVISED_LONG_RIFLE;
  return IMPROVISED_BY_CLASS[sys?.weaponClass] || IMPROVISED_FALLBACK;
}

/**
 * «Закрепленное тяжелое оружие нельзя использовать в рукопашной и персонаж с
 * таким оружием считается безоружным до начала своего следующего Хода, если он
 * стрелял из него» (core.json, «Безоружный Бой»). Метку «стрелял из
 * Закреплённого» ставит combat/attack.mjs, гасит начало своего Хода
 * (rules/turn-flags.mjs, firedBracedHeavy).
 */
export const FIRED_BRACED_FLAG = "firedBracedHeavy";

export function firedBracedHeavyIds(actor) {
  const v = actor?.getFlag?.(SYSTEM, FIRED_BRACED_FLAG) ?? actor?.flags?.[SYSTEM]?.[FIRED_BRACED_FLAG];
  return Array.isArray(v) ? v.map(String) : [];
}

/** Тяжёлое оружие сейчас Закреплено или из Закреплённого стреляли в этом Ходу. */
export function braceBlocksMelee(item) {
  if (!improvisedRow(item?.system).heavy) return false;
  const actor = item?.actor ?? item?.parent ?? null;
  if (!actor) return false;
  return !!braceCheck(actor, item) || firedBracedHeavyIds(actor).includes(String(item.id));
}

/**
 * Метка профиля удара оружием. По ней же его узнаёт HUD и окно атаки.
 * Была «Удар в упор» — переименована по просьбе владельца 06.09.2026:
 * «в упор» в этой системе уже занято дальностью стрельбы, и игроки читали
 * метку как условие дистанции, а не как «бей тем, что в руках».
 */
export const IMPROVISED_MELEE_LABEL = "Ударить оружием";

/**
 * Полагается ли этому предмету профиль удара в упор.
 *
 * Четыре условия; первые три — по просьбе владельца, четвёртое — книга:
 *
 * 1. ОРУЖИЕ НАДЕТО. Прикладом бьют тем, что в руках; ствол в рюкзаке такого
 *    профиля не даёт. Гейт стоит ЗДЕСЬ, а не у каждого читателя: HUD и так
 *    показывает только надетое, но окно атаки открывается и для снятого
 *    оружия, и без общего условия профиль там бы всплывал.
 * 2. Оружие СТРЕЛКОВОЕ — у рукопашного свой рукопашный профиль и так есть.
 * 3. Это не интегральная атака (кислотный плевок, вопль, демонические дары):
 *    у них нет физического приклада. Если он всё же нужен конкретному предмету
 *    (экзотическое оружие Дредноута и т.п.), включается точечно флагом
 *    allowGunMeleeStrike — тот же гейт, что стоял у кнопки HUD до переезда.
 *
 * Чего здесь НЕТ и быть не может: способа удалить этот профиль или сохранить
 * его в предмет. Он СЧИТАЕТСЯ на каждый вызов и нигде не хранится — редактор
 * профилей на листе предмета (sheets/item-sheet.mjs) читает system.profiles
 * напрямую и его не видит, поэтому у него нет ни строки, ни крестика. Вместе с
 * удалённым оружием он исчезает сам: считать станет не из чего.
 */
export function canStrikeWithGun(item, { isIntegralAttack } = {}) {
  const sys = item?.system || {};
  if (!sys.equipped) return false;
  if (sys.weaponClass === "melee") return false;
  // Метательное/Граната (стр. 40, wdbc-x1nz.2.58): «в рукопашной может
  // использоваться как рукопашное оружие» — своим ЖЕ профилем (нож остаётся
  // ножом), а не синтетическим «прикладом» IMPROVISED_BY_CLASS ниже (там нет
  // ключа "thrown", и без этого исключения оно ловило бы фолбэк «как Посох»,
  // теряя собственные Урон/Тип/Пробитие). Рукопашное использование включает
  // opts.forceMelee (см. attackIsMelee) — оно уже не трогает этот профиль.
  if (sys.weaponClass === "thrown") return false;
  // 4. Закреплённое тяжёлое (или стрелял из Закреплённого в этом Ходу) —
  //    рукопашной им нельзя, см. braceBlocksMelee.
  if (braceBlocksMelee(item)) return false;
  const integral = isIntegralAttack ? isIntegralAttack(item) : false;
  if (!integral) return true;
  return !!(item?.getFlag?.(SYSTEM, "allowGunMeleeStrike")
         ?? item?.flags?.[SYSTEM]?.allowGunMeleeStrike);
}

/**
 * Профиль удара в упор для этого оружия — или null, если не полагается.
 *
 * Форма — та же, что у авторского профиля из system.profiles, плюс `melee` и
 * `generated`. Второе поле нужно, чтобы такой профиль было видно отличить от
 * авторского: сохранять его в предмет нельзя, он выводится заново каждый раз.
 */
export function improvisedMeleeProfile(item, opts = {}) {
  if (!canStrikeWithGun(item, opts)) return null;
  const p = improvisedRow(item?.system);
  return {
    label: IMPROVISED_MELEE_LABEL,
    melee: true,
    generated: true,
    // Категория рукопашного — та, которой книга велит бить: «как Булава»,
    // «как Посох» (решение владельца 06.09.2026, вариант «а»). Она отдельным
    // полем, а не меткой, потому что метку видит игрок в списке профилей и там
    // должно стоять «Ударить оружием», а не «Посох».
    //
    // Что это меняет: Melee Training по книге открывает АЛЬТЕРНАТИВНЫЕ приёмы
    // и хваты, а не саму атаку («Типы Рукопашного Оружия... отображает
    // специализацию Таланта Melee Training для использования альтернативных
    // приемов и хватов», корбук, «II. МЕХАНИКА → БОЙ»). Поэтому нетренированный
    // ударит прикладом всегда — просто Обычной Атакой, Стандартной Стойкой и
    // Базовым Хватом. Булава вдобавок освобождена от Таланта прямой цитатой
    // книги (constants/weapon-categories.mjs::MELEE_TRAINING_EXEMPT), так что
    // разница видна только у приклада ВИНТОВКИ, который бьёт как Посох.
    meleeCategory: p.like,
    range: p.range,
    damage: p.damage,
    damageType: "impact",
    // I(Cr) по таблице книги. Без явного поля attack-weapon.mjs взял бы
    // подтип самого ствола (напр. Взрывной у болтера) — прикладом не взрывают.
    damageSubtype: "crushing",
    penetration: 0,
    weaponProps: [{ key: "imprecise" }, { key: "primitive" }],
    balance: p.balance,
    attackMod: p.attackMod,
    note: `Импровизированное рукопашное — как ${p.like}, досягаемость ${p.range}, Баланс ${p.balance}, атака ${p.attackMod}.`
  };
}

/**
 * Все профили оружия: авторские из system.profiles плюс выводимые.
 *
 * Порядок важен и не случаен: авторские идут первыми и сохраняют свои индексы.
 * По индексу профиля хранится выбор игрока (флаг hudProfile на предмете) и
 * ходит techniqueOpts.profileIdx — вставь выводимый профиль в начало, и у всех
 * уже сделанных выборов молча съедет смысл.
 */
export function weaponProfiles(item, opts = {}) {
  const authored = Array.isArray(item?.system?.profiles) ? item.system.profiles : [];
  const improvised = improvisedMeleeProfile(item, opts);
  return improvised ? [...authored, improvised] : [...authored];
}

/** Рукопашный ли это профиль (у авторских поля нет — значит по предмету). */
export function isMeleeProfile(profile) {
  return !!profile?.melee;
}

/**
 * Рукопашная ли эта атака — ЕДИНОЕ решение для окна атаки и для самого броска
 * (wdbc-bs0q).
 *
 * Раньше формула «weaponClass === melee || forceMelee» была выписана в двух
 * местах: в окне (sheets/attack-dialog.mjs) и в исполнителе броска
 * (combat/attack.mjs). Пока рукопашность зависела только от предмета, копии
 * совпадали. Как только появился рукопашный ПРОФИЛЬ у стрелкового, они
 * разошлись — и разошлись молча: окно катило тест по WS и писало «Рукопашная
 * атака», а бросок считал ту же атаку стрельбой. Цена расхождения не
 * косметическая: S.b не прибавлялся к урону (flatBonus берёт его только у
 * рукопашной), а кнопки защиты в карточке уезжали в стрелковую ветку, где
 * Парирование требует Талант «Щит Клинков».
 *
 * Поэтому решение одно и живёт здесь. Профиль важен наравне с предметом:
 * «Ударить оружием» — рукопашная атака стрелковым оружием, и это её свойство, а
 * не свойство ствола.
 *
 * @param {object} sys     system оружия
 * @param {object} opts    { forceMelee, profile }
 */
export function attackIsMelee(sys, { forceMelee = false, profile = null } = {}) {
  return sys?.weaponClass === "melee" || !!forceMelee || isMeleeProfile(profile);
}
