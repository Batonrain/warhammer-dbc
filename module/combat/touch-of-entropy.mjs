//  Касание Энтропии / Touch of Entropy (Дар Нургла, d100 37..40, wdbc-1rno):
//  «Его безоружные атаки и атаки естественным оружием уменьшают АР участка
//  брони, по которой они попадают, на ½ Cor.b (окр.▲) ДО НАНЕСЕНИЯ УРОНА,
//  или уменьшают Качество любого оружия, которым его успешно парировали, на
//  1, ломая броню, если её АР опустилось до 0, или оружие, если его Качество
//  опустилось ниже Poor.Q. Эти повреждения исправляются сменой ремонта (тест
//  не нужен).»
//
//  ПОЧЕМУ ЭТО НЕ СВОЙСТВО Corrosive, хотя выглядит как оно. Соблазн был
//  большой: Разъедающее(X) тоже «−X AP места попадания» и тоже копит потерю
//  в system.armorCorrosion. Но два отличия принципиальные:
//   1. СРОК. Corrosive применяется ПОСЛЕ расчёта поглощения (combat/
//      damage.mjs, рядом с Проникающим/Калечащим) — то есть текущему удару
//      уже не помогает. Книга здесь говорит «до нанесения урона»: снятый AP
//      обязан облегчить именно ЭТО попадание.
//   2. ОСТАТОК. У Corrosive рейтинг сверх наличного AP превращается в
//      непоглощаемый урон. Здесь такого нет вовсе — лишнее просто пропадает,
//      и подмена дала бы Дару урон, которого книга не давала.
//  Поэтому механика своя, а вот НАКОПИТЕЛЬ переиспользуется тот же
//  (system.armorCorrosion): и потеря стойкая, и «исправляется сменой
//  ремонта без теста» — дословно то, что делает уже существующая кнопка
//  repairArmorCorrosion (combat/damage.mjs).
//
//  «Безоружные атаки и атаки естественным оружием» — это ровно предметы с
//  флагом integralAttack (combat/equipped-melee.mjs::isIntegralAttack):
//  Кулак/Пинок/Удар Головой заведены такими же предметами, что и Хвост,
//  Клыки и прочие природные орудия (см. apps/hud.mjs). Отдельного признака
//  «природное оружие» изобретать не нужно — он уже есть.
//
//  НЕ смоделирована вторая половина книжной альтернативы: «−1 Качество
//  оружия, которым его успешно парировали». Парирование не проходит через
//  конвейер урона вовсе (module/combat/defense.mjs — это встречный тест без
//  попадания), и повесить туда порчу чужого предмета негде без отдельного
//  крюка «чем именно парировали». Отмечено остатком, а не сделано молча.
// ════════════════════════════════════════════════════════════════════════

import { hasRuleFlag } from "../rules/flags.mjs";
import { isIntegralAttack } from "./equipped-melee.mjs";

export const TOUCH_OF_ENTROPY = "gift.nurgle.touchOfEntropy";

/** ½ Cor.b, округление ВВЕРХ («окр.▲» книги). */
export function touchOfEntropyRating(corBonus) {
  return Math.ceil(Math.max(0, Number(corBonus) || 0) / 2);
}

/**
 * Рейтинг разъедания для КОНКРЕТНОЙ атаки: 0, если у атакующего нет Дара
 * или удар нанесён не безоружно/не природным оружием.
 */
export function attackEntropyRating(actor, item) {
  if (!actor || !hasRuleFlag(actor, TOUCH_OF_ENTROPY)) return 0;
  if (item && !isIntegralAttack(item)) return 0;
  return touchOfEntropyRating(actor.system?.corruptionBonus);
}

/**
 * Сколько AP реально съедено этим попаданием: не больше, чем было.
 * Остаток рейтинга пропадает — в отличие от Разъедающего, он никуда не
 * переливается (см. шапку).
 */
export function entropyArmourLoss(currentAP, rating) {
  return Math.min(Math.max(0, Number(rating) || 0), Math.max(0, Number(currentAP) || 0));
}
