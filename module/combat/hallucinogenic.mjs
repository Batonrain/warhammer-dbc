/** Патч на дополнительный мех. эффект конкретной грани (или {} — только текст). */
function mechanicFields(mechanic, actor = null) {
  if (mechanic === "dazedProne") return { ...conditionApplyFields("dazed", null, actor), ...conditionApplyFields("prone", null, actor) };
  if (mechanic === "dazed")      return conditionApplyFields("dazed", null, actor);
  if (mechanic === "helpless")   return conditionApplyFields("helpless", null, actor);
  if (mechanic === "rage")       return { "system.inRage": true };
  return {};
}

/**
 * Бросает 1d10 по книжной таблице, применяет её механическую часть (если
 * есть) и запоминает грань (flags.warhammer-dbc.hallucinationEffect) — для
 * запрета Атаки у грани 9 (attack-dialog.mjs, гейт живёт, пока стоит и
 * conditions.hallucinogenic, и эта грань — см. isHallucinatingCannotAttack).
 * Возвращает {roll, entry} — вызывающая сторона (hooks.mjs) сама собирает
 * карточку в чат, этот модуль Foundry-документов сам не постит.
 */
export async function rollHallucinogenicEffect(actor) {
  const roll  = await new Roll("1d10").evaluate();
  const entry = HALLUCINOGENIC_TABLE[roll.total - 1];
  const update = { [`flags.warhammer-dbc.hallucinationEffect`]: roll.total, ...mechanicFields(entry.mechanic, actor) };
  await actor.update(update);
  return { roll, entry };
}

/** Грань 9 («Я маленький...», не может Атаковать) активна, пока стоит и она, и само Состояние. */
export function isHallucinatingCannotAttack(actor) {
  return !!actor?.system?.conditions?.hallucinogenic
      && Number(actor?.getFlag?.("warhammer-dbc", "hallucinationEffect")) === 9;
}
