// ─────────────────────────────────────────────────────────────────────────────
//  Роза смещения — общий бросок «мимо цели» для любой атаки по площади: сейчас
//  использует только Взрывное (attack.mjs, Прицельный выстрел под цель), но
//  сделан отдельным переиспользуемым модулем на будущее — под гранаты, шаблоны
//  психосил/техночудес и прочие AoE-эффекты с тем же промахом-смещением.
//
//  d10 — дистанция смещения в метрах, d8 — направление по розе (1 — «Вперёд»,
//  дальше по часовой стрелке; читается вдоль линии огня, от стрелка к точке
//  прицеливания, а «вперёд» — это продолжение той же линии).
// ─────────────────────────────────────────────────────────────────────────────

/**
 * 8 направлений розы смещения, по часовой стрелке от «Вперёд». `deg` —
 * угол относительно «Вперёд» (0°), по часовой стрелке — переиспользуется
 * зоной «Остаётся» (module/regions/linger-zone.mjs) для дрейфа: там
 * «Вперёд» — не линия огня (той уже нет спустя раунды), а направление от
 * стрелка к точке первого размещения зоны, зафиксированное один раз.
 */
export const SCATTER_ROSE = [
  { n: 1, label: "Вперёд",        icon: "⬆️", deg: 0 },
  { n: 2, label: "Вперёд-вправо", icon: "↗️", deg: 45 },
  { n: 3, label: "Вправо",        icon: "➡️", deg: 90 },
  { n: 4, label: "Назад-вправо",  icon: "↘️", deg: 135 },
  { n: 5, label: "Назад",         icon: "⬇️", deg: 180 },
  { n: 6, label: "Назад-влево",   icon: "↙️", deg: 225 },
  { n: 7, label: "Влево",         icon: "⬅️", deg: 270 },
  { n: 8, label: "Вперёд-влево",  icon: "↖️", deg: 315 }
];

/**
 * Бросок смещения: d10 метров дистанции + d8 направление по розе.
 * @returns {Promise<{distance:number, dir:object, distRoll:Roll, dirRoll:Roll}>}
 */
export async function rollScatter() {
  const distRoll = await new Roll("1d10").evaluate();
  const dirRoll  = await new Roll("1d8").evaluate();
  const dir = SCATTER_ROSE[dirRoll.total - 1];
  return { distance: distRoll.total, dir, distRoll, dirRoll };
}
