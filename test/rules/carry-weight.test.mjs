// Таблица Максимального Веса (стр. 27): Ношение, Подъём и Толкание по сумме
// S.b + T.b. Раньше в коде лежал один столбец, а Подъём и Толкание выводились
// сдвигом строки на +1 и +2. Сходится это только у слабых персонажей: уже при
// сумме 4 книга даёт Подъём 36, а строка 5 — 27. В самом столбце Ношения
// хвост тоже разошёлся: с суммы 43 там стояли числа Подъёма.

import { describe, it, expect } from "vitest";
import { carryRow, _calcMaxCarry } from "../../module/helpers/utils.mjs";

describe("таблица Максимального Веса", () => {
  it("строки книги воспроизводятся целиком", () => {
    expect(carryRow(0)).toEqual({ carry: 0.9, lift: 2.25, push: 4.5 });
    // Толкание на сумме 4 — одна из собственных неровностей книги: она не
    // удваивает Подъём здесь (36), а даёт то же самое значение (36).
    expect(carryRow(4)).toEqual({ carry: 18, lift: 36, push: 36 });
    expect(carryRow(10)).toEqual({ carry: 78, lift: 156, push: 268 });
    expect(carryRow(20)).toEqual({ carry: 2250, lift: 4500, push: 7200 });
  });

  it("Астартес (S.b 8 + T.b 8) носит 675, поднимает 1350, двигает 1800", () => {
    expect(carryRow(16)).toEqual({ carry: 675, lift: 1350, push: 1800 });
  });

  it("хвост таблицы взят из столбца Ношения, а не Подъёма", () => {
    expect(carryRow(43).carry).toBe(80000);    // было 84 000
    expect(carryRow(44).carry).toBe(92000);    // было 106 000
    expect(carryRow(45).carry).toBe(106000);   // было 212 000
  });

  it("за краями таблицы берутся крайние строки", () => {
    expect(carryRow(-5)).toEqual(carryRow(0));
    expect(carryRow(999)).toEqual(carryRow(45));
  });

  it("_calcMaxCarry — это столбец Ношения", () => {
    expect(_calcMaxCarry(16)).toBe(675);
    expect(_calcMaxCarry(0)).toBe(0.9);
  });

  it("Подъём вдвое, Толкание вчетверо от Ношения — там, где так в книге", () => {
    for (const idx of [30, 45]) {
      const row = carryRow(idx);
      expect(row.lift).toBe(row.carry * 2);
      expect(row.push).toBe(row.carry * 4);
    }
  });

  // Толкание раньше считалось формулой ×2 от Подъёма (или ×4 от Ношения) для
  // ВСЕХ строк. Это совпадает с книгой на концах таблицы (0-3, 23-45, кроме
  // собственной опечатки книги на 26), но на суммах 4-22 книга даёт заметно
  // МЕНЬШЕЕ Толкание, чем такая формула — там ×2 от Подъёма не работает.
  // Столбец должен быть переписан из книги построчно, как Ношение и Подъём.
  it("Толкание воспроизводит книгу целиком, а не формулу ×2 от Подъёма", () => {
    const BOOK_PUSH = [
      4.5, 9, 18, 36, 36, 72, 108, 114, 180, 224, 268, 312, 360, 448, 900,
      1348, 1800, 2700, 3600, 5400, 7200, 9000, 11600, 16800, 19400, 22000,
      25000, 29000, 33200, 38200, 44000, 52000, 60000, 68000, 80000, 92000,
      104000, 120000, 140000, 160000, 184000, 212000, 280000, 320000, 368000, 424000
    ];
    BOOK_PUSH.forEach((push, idx) => {
      expect(carryRow(idx).push).toBe(push);
    });
  });
});
