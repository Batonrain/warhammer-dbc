// Границы слова у кириллицы. `\b` в JS считает словом только ASCII, поэтому
// `/\bмеч\b/` не совпадает НИ С ЧЕМ: слева от «м» и справа от «ч» стоят такие
// же не-ASCII символы (или край строки), а граница требует перехода
// слово/не-слово. Написанные так фильтры Мастера молча переставали работать —
// «силовой меч» не относился к оружию, а строки «любое …» переставали
// считаться абстрактными и уходили в автосоздание предметов.
//
// Проверяется поведение, а не текст регулярки: и что нужное слово ловится, и
// что однокоренное («мечта», «ножны», «защита») — нет, ради чего границы и
// заводились.

import "../support/foundry-stub.mjs";

import { describe, it, expect } from "vitest";
import { CharacterWizard } from "../../module/apps/character-wizard.mjs";

// Метод читает только свой аргумент — экземпляр Мастера (а с ним и живой
// Foundry) для проверки не нужен.
const guess = (text) => CharacterWizard.prototype._guessGearPack.call(null, text);

describe("Мастер создания: пак по описанию снаряжения", () => {
  it.each([
    ["силовой меч", "weapons"],
    ["меч", "weapons"],
    ["боевой нож, 2 шт.", "weapons"],
    ["латы", "armor"],
    ["щит", "shields"],
    ["chainsword", "weapons"],
    ["flak armour", "armor"]
  ])("«%s» → %s", (text, pack) => {
    expect(guess(text)).toBe(pack);
  });

  it.each(["мечта", "ножны", "защита", "латышский"])(
    "однокоренное «%s» пак не угадывает", (text) => {
      expect(guess(text)).toBeNull();
    });
});
