// test/helpers/short-label.test.mjs
//
// Короткая шапка длинной подписи (wdbc-m7we).
//
// Подписи возможностей в реестре — это текст книги целиком: медиана 120
// символов, 98 штук длиннее 200, самая длинная 2266. Панель «ВОЗМОЖНОСТИ
// СЕЙЧАС» кладёт их прямо в ячейку таблицы, и строка на два абзаца ломает
// вёрстку панели, ради которой она заведена — быстро увидеть, что у тебя
// сейчас есть.
//
// Правило по этому листу (указание пользователя): объяснения уходят в
// подсказку, место в ячейке остаётся под кнопки и цифры. Тот же приём уже
// применён у подсказки слота субрасы (sheets/character-context.mjs).
//
// Резать надо по смысловому шву, а не посреди слова: у этих подписей первая
// часть до «;» или «—» и есть суть, а дальше идут оговорки.

import { describe, it, expect } from "vitest";
import { shortLabel } from "../../module/helpers/utils.mjs";

describe("shortLabel", () => {
  it("короткую подпись не трогает", () => {
    expect(shortLabel("Иммунитет к радиации")).toBe("Иммунитет к радиации");
  });

  it("режет по первому «;» — дальше идут оговорки", () => {
    expect(shortLabel("Не стареет, иммунитет к болезням; кроме накопления Порчи"))
      .toBe("Не стареет, иммунитет к болезням…");
  });

  it("режет по тире-шву", () => {
    expect(shortLabel("Ужасы делятся на 3 — редиректа попаданий в системе нет"))
      .toBe("Ужасы делятся на 3…");
  });

  it("шов дальше предела не спасает: режет по слову", () => {
    const long = "Полное действие и одна Рана себе: заражает до трёх трупов в двух метрах вокруг, они оживают зомби";
    const out = shortLabel(long, 40);
    expect(out.length).toBeLessThanOrEqual(41);      // 40 плюс многоточие
    expect(out.endsWith("…")).toBe(true);
    expect(long.startsWith(out.slice(0, -1))).toBe(true);
    expect(out).not.toMatch(/\s…$/);                  // без пробела перед многоточием
  });

  it("не режет посреди слова", () => {
    expect(shortLabel("Абракадабра длинноеслово хвост", 15)).toBe("Абракадабра…");
  });

  it("одно слово длиннее предела режется жёстко — иначе не влезет вовсе", () => {
    expect(shortLabel("Абракадабрическое", 10)).toBe("Абракадабр…");
  });

  it("пустое и не-строка дают пустую строку", () => {
    expect(shortLabel("")).toBe("");
    expect(shortLabel(null)).toBe("");
    expect(shortLabel(undefined)).toBe("");
  });

  it("шов в самом начале не даёт пустой шапки", () => {
    // «— что-то» дало бы пустую строку при наивной резке по первому шву.
    expect(shortLabel("— Не выбрано")).toBe("— Не выбрано");
  });

  it("края обрезаются от пробелов", () => {
    expect(shortLabel("  Иммунитет к огню  ")).toBe("Иммунитет к огню");
  });
});
